import { parseArgs } from 'util';
import { OverlayEffectConfig } from './src/overlay-effects/types';
import { EffectPipeline } from './src/overlay-effects/pipeline';
import { getGenerator, listGenerators } from './src/overlay-effects/registry';

async function main() {
  const { values } = parseArgs({
    args: process.argv.slice(2),
    options: {
      effect: { type: 'string', short: 'e' },
      variant: { type: 'string', short: 'v', default: 'default' },
      duration: { type: 'string', short: 'd' },
      fps: { type: 'string', short: 'f' },
      width: { type: 'string', short: 'w' },
      height: { type: 'string', short: 'h' },
      output: { type: 'string', short: 'o' },
      'bg-transparent': { type: 'boolean', short: 't', default: false },
      'canvas-engine': { type: 'string', short: 'c', default: 'napi-rs' },
    },
    allowPositionals: true,
  });

  if (!values.effect) {
    console.error(`Error: --effect is required. Available effects: ${listGenerators().join(', ')}`);
    process.exit(1);
  }

  const effectName = values.effect.toLowerCase();
  const generator = getGenerator(effectName);

  if (!generator) {
    console.error(`Error: Unknown effect '${effectName}'. Available effects: ${listGenerators().join(', ')}`);
    process.exit(1);
  }

  // Parse config with defaults
  const defaultOutputDir = './autogenerated/overlay-effects';
  const defaultOutputName = `${effectName}_${values.variant || 'default'}_${values.duration || 3}s.${values['bg-transparent'] ? 'webm' : 'mp4'}`;
  const defaultOutputPath = `${defaultOutputDir}/${defaultOutputName}`;
  
  const config: OverlayEffectConfig = {
    width: values.width ? parseInt(values.width, 10) : 1920,
    height: values.height ? parseInt(values.height, 10) : 1080,
    fps: values.fps ? parseInt(values.fps, 10) : 30,
    duration: values.duration ? parseFloat(values.duration) : 3.0,
    output: values.output || defaultOutputPath,
    bgTransparent: values['bg-transparent'] ?? false,
    canvasEngine: (values['canvas-engine'] as any) || 'napi-rs',
    variant: values.variant || 'default',
  };

  // Ensure output directory exists
  const fs = require('fs');
  const path = require('path');
  const outputDir = path.dirname(config.output);
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  console.log(`\n=== Overlay Effects Generator ===`);
  console.log(`Effect:     ${generator.name} (${config.variant})`);
  console.log(`Resolution: ${config.width}x${config.height} @ ${config.fps} FPS`);
  console.log(`Duration:   ${config.duration}s`);
  console.log(`Background: ${config.bgTransparent ? 'Transparent (WebM/VP9)' : 'Solid Black (MP4/H.264)'}`);
  console.log(`Engine:     ${config.canvasEngine}`);
  console.log(`Output:     ${config.output}\n`);

  try {
    const pipeline = new EffectPipeline(config);
    await generator.generate(config, pipeline);
    await pipeline.close();

    // Generate JSON metadata
    const metadata = {
      effect: generator.name,
      variant: config.variant,
      resolution: {
        width: config.width,
        height: config.height
      },
      fps: config.fps,
      duration: config.duration,
      background: {
        type: config.bgTransparent ? 'transparent' : 'solid',
        color: config.bgTransparent ? null : '#000000',
        recommended_blend_mode: config.bgTransparent ? 'overlay' : 'screen'
      },
      file: path.basename(config.output)
    };

    const parsedPath = path.parse(config.output);
    const jsonPath = path.join(parsedPath.dir, `${parsedPath.name}.json`);
    
    fs.writeFileSync(jsonPath, JSON.stringify(metadata, null, 2));
    console.log(`Metadata successfully saved to ${jsonPath}`);
    
  } catch (error) {
    console.error('\nFailed to generate effect:', error);
    process.exit(1);
  }
}

main();
