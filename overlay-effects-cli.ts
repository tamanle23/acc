import { parseArgs } from 'util';
import { RegistryManager } from './src/core/Registry';
import path from 'path';
import fs from 'fs';
import { renderEffectLayer } from './src/overlay-effects/engine';
import { FFmpegManager } from './src/core/FFmpegManager';
import { askChoice, askQuestion, askYesNo, closeInteractiveConsole } from './src/core/interactive';

async function generateHeadless(values: any) {
  if (!values.effect && !values.composite) {
    console.error('Error: Either --effect or --composite is required.');
    process.exit(1);
  }

  const registry = new RegistryManager();
  
  const outDir = './autogenerated/overlay-effects';
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }

  const layerOptions = {
    fps: values.fps ? parseInt(values.fps, 10) : undefined,
    width: values.width ? parseInt(values.width, 10) : undefined,
    height: values.height ? parseInt(values.height, 10) : undefined
  };

  try {
    if (values.composite) {
      const compositeName = values.composite.toLowerCase();
      const compositeConfig = registry.getCompositeConfig(compositeName);
      
      console.log(`\n=== Combinatorial Composite Generator ===`);
      console.log(`Composite:  ${compositeName}`);
      
      const renderPromises = compositeConfig.layers.map((layer: any) => {
        return renderEffectLayer(registry, layer.effect, layer.variant, layer.duration, outDir, layerOptions);
      });

      const outputs = await Promise.all(renderPromises);
      console.log(`\n✅ Composite '${compositeName}' successfully generated!`);
      outputs.forEach((o: any) => console.log(` - Video:    ${o}`));
    } else if (values.effect) {
      const effectName = values.effect.toLowerCase();
      const variantName = values.variant || 'default';
      const duration = values.duration ? parseFloat(values.duration) : 3.0;

      console.log(`\n=== Single Dynamic Effect Generator ===`);
      const output = await renderEffectLayer(registry, effectName, variantName, duration, outDir, layerOptions);
      console.log(`\n✅ Successfully completed rendering!\nVideo:    ${output}`);
    }
  } catch (err: any) {
    console.error(`\n❌ Error: ${err.message}`);
    process.exit(1);
  }
}

async function startWizard() {
  console.log('\n============================================');
  console.log('🎥 Overlay Effects Interactive Console');
  console.log('============================================\n');

  const registry = new RegistryManager();
  const outDir = './autogenerated/overlay-effects';
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }

  while (true) {
    const mode = await askChoice('Generation Mode:', ['Single Video Overlay Effect', 'Composite Overlay (Multi-layer Mix)']);

    try {
      if (mode.startsWith('Composite')) {
        const compositeName = await askQuestion('Enter composite name (e.g., retro_vcr_startup): ');
        if (!compositeName) throw new Error('Name cannot be empty.');
        
        const compositeConfig = registry.getCompositeConfig(compositeName);
        console.log(`\nGenerating composite: ${compositeName}...`);
        
        const renderPromises = compositeConfig.layers.map((layer: any) => {
          return renderEffectLayer(registry, layer.effect, layer.variant, layer.duration, outDir, {});
        });

        const outputs = await Promise.all(renderPromises);
        console.log(`\n✅ Composite successfully generated!`);
        outputs.forEach(o => console.log(` - Video:    ${o}`));
      } else {
        const effect = await askChoice('Select Overlay Effect:', ['vhs', 'crt', 'glitch', 'film_grain', 'scanline', 'bloom', 'chromatic_aberration', 'cinematic_borders']);
        const variant = await askQuestion(`Enter variant [default]: `);
        const durationStr = await askQuestion(`Enter duration in seconds [3.0]: `);
        const duration = durationStr.trim() ? parseFloat(durationStr) : 3.0;

        console.log(`\nGenerating [${effect} > ${variant || 'default'}] for ${duration}s...`);
        const output = await renderEffectLayer(registry, effect, variant || 'default', duration, outDir, {});
        console.log(`\n✅ Successfully completed rendering!\nVideo:    ${output}`);
      }
    } catch (err: any) {
      console.error(`\n❌ Error: ${err.message}`);
    }

    const continueLoop = await askYesNo('\nDo you want to generate another overlay effect?');
    if (!continueLoop) {
      console.log('Goodbye!');
      break;
    }
  }

  closeInteractiveConsole();
  process.exit(0);
}

async function main() {
  await FFmpegManager.prepare();
  
  const args = process.argv.slice(2);
  if (args.length > 0) {
    const { values } = parseArgs({
      args: args,
      options: {
        effect: { type: 'string', short: 'e' },
        variant: { type: 'string', short: 'v', default: 'default' },
        composite: { type: 'string', short: 'c' },
        duration: { type: 'string', short: 'd' },
        output: { type: 'string', short: 'o' },
        fps: { type: 'string' },
        width: { type: 'string' },
        height: { type: 'string' }
      },
      allowPositionals: true,
    });
    await generateHeadless(values);
    process.exit(0);
  } else {
    await startWizard();
  }
}

main();
