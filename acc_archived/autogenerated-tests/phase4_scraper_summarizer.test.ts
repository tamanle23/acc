import { describe, it, expect, beforeAll } from 'bun:test';
import path from 'path';
import fs from 'fs';
import { ScraperEngine, IngestedEvent } from '../apps/cli/src/pipelines/01-scraper/ScraperEngine';
import { ScraperPipeline } from '../apps/cli/src/pipelines/01-scraper/ScraperPipeline';
import { IPCFacade, FallbackAIStrategy } from '../packages/core/src/ipc/IPCFacade';
import { FFmpegManager } from '../packages/core/src/FFmpegManager';

describe('Phase 4: Pipeline 1 (Event-Driven Scraper & Summarizer - Priority 1)', () => {
  const testOutputDir = path.resolve(process.cwd(), 'autogenerated', 'tests', 'phase4');

  beforeAll(async () => {
    if (!fs.existsSync(testOutputDir)) {
      fs.mkdirSync(testOutputDir, { recursive: true });
    }
    await FFmpegManager.prepare();
  });

  describe('ScraperEngine Ingestion Suite', () => {
    it('ingests manual text event and dispatches to registered listener', async () => {
      const engine = new ScraperEngine();
      let capturedEvent: IngestedEvent | null = null;
      engine.onEvent((ev) => {
        capturedEvent = ev;
      });

      const event = await engine.ingestManual('BREAKING: Major open-source AI engine reaches 100k GitHub stars with real-time video generation.');
      expect(event.sourceType).toBe('manual');
      expect(event.rawText).toContain('BREAKING: Major open-source AI');
      expect(capturedEvent).not.toBeNull();
      expect((capturedEvent as any).rawText).toBe(event.rawText);
    });

    it('receives webhook HTTP POST payloads through Bun.serve server', async () => {
      const engine = new ScraperEngine();
      const testPort = 3099;
      let webhookReceived: IngestedEvent | null = null;

      engine.onEvent((ev) => {
        webhookReceived = ev;
      });

      const server = engine.startWebhookServer(testPort, '/test-webhook');
      expect(server).toBeDefined();

      try {
        const response = await fetch(`http://127.0.0.1:${testPort}/test-webhook`, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            content: 'CRITICAL ALERT: Bitcoin breaks all-time high amidst institutional ETF inflows.',
            author: 'CryptoDesk',
          }),
        });

        expect(response.status).toBe(200);
        const data = await response.json();
        expect(data.status).toBe('ACK');

        // Allow microtask cycle for asynchronous listener notification
        await new Promise((r) => setTimeout(r, 80));
        expect(webhookReceived).not.toBeNull();
        expect((webhookReceived as any).sourceType).toBe('webhook');
        expect((webhookReceived as any).rawText).toContain('CRITICAL ALERT');
      } finally {
        engine.stopWebhookServer();
      }
    });
  });

  describe('ScraperPipeline End-to-End Orchestration', () => {
    it('orchestrates ingestion -> LLM grammar extraction -> TTS audio -> 4-way exporter fanning', async () => {
      const outDir = path.resolve(testOutputDir, 'e2e_run');
      const pipeline = new ScraperPipeline();

      const sampleEvent: IngestedEvent = {
        sourceType: 'webhook',
        rawText: `
          URGENT: Global Tech Consortium announces revolutionary multi-model architecture.
          Key milestone 1: Zero-latency streaming video rendering with pure bun:ffi memory muxing.
          Key milestone 2: Universal cross-platform AI daemon running local Qwen 2.5 3B and Kokoro-82M.
          Key milestone 3: 4-way branching multi-channel distribution generating social, static web, audio podcast, and video shorts.
        `,
        sourceUrl: 'https://news.example.com/multi-model-revolution',
        receivedAt: new Date().toISOString(),
      };

      const { ir, exportResults } = await pipeline.run(sampleEvent, outDir);

      // 1. Verify PipelineIR integrity
      expect(ir).toBeDefined();
      expect(ir.schemaVersion).toBe('3.0.0');
      expect(ir.pipelineId).toBe('scraper-summarizer');
      expect(ir.chunks.length).toBeGreaterThan(0);
      expect(ir.chunks[0].spokenAudioPath).toBeDefined();
      expect(fs.existsSync(ir.chunks[0].spokenAudioPath!)).toBe(true);

      // 2. Verify Canvas breaking alert card
      const alertCardPath = path.join(outDir, 'alert_card.png');
      expect(fs.existsSync(alertCardPath)).toBe(true);
      expect(fs.statSync(alertCardPath).size).toBeGreaterThan(1000);

      // 3. Verify all 4 Exporters output artifacts
      expect(exportResults).toBeDefined();

      // Channel 1: Static Web
      expect(exportResults.staticWeb).toBeDefined();
      const webPaths = Array.isArray(exportResults.staticWeb!.outputPath) ? exportResults.staticWeb!.outputPath : [exportResults.staticWeb!.outputPath];
      expect(webPaths.length).toBeGreaterThanOrEqual(2);
      expect(fs.existsSync(webPaths[0])).toBe(true); // .md
      expect(fs.existsSync(webPaths[1])).toBe(true); // .json

      // Channel 2: Social
      expect(exportResults.social).toBeDefined();
      const socialPaths = Array.isArray(exportResults.social!.outputPath) ? exportResults.social!.outputPath : [exportResults.social!.outputPath];
      expect(socialPaths.length).toBeGreaterThanOrEqual(1);
      expect(fs.existsSync(socialPaths[0])).toBe(true);

      // Channel 3: Audio Podcast
      expect(exportResults.audio).toBeDefined();
      const audioPath = Array.isArray(exportResults.audio!.outputPath) ? exportResults.audio!.outputPath[0] : exportResults.audio!.outputPath;
      expect(fs.existsSync(audioPath)).toBe(true); // .mp3

      // Channel 4: Video Shorts (9:16)
      expect(exportResults.video).toBeDefined();
      const videoPath = Array.isArray(exportResults.video!.outputPath) ? exportResults.video!.outputPath[0] : exportResults.video!.outputPath;
      expect(fs.existsSync(videoPath)).toBe(true); // .mp4
      expect(fs.statSync(videoPath).size).toBeGreaterThan(500);
    });

    it('gracefully handles empty or corrupted rawText with fallback strategy', async () => {
      const outDir = path.resolve(testOutputDir, 'fallback_run');
      const fallbackFacade = new IPCFacade(new FallbackAIStrategy());
      const pipeline = new ScraperPipeline(fallbackFacade);

      const emptyEvent: IngestedEvent = {
        sourceType: 'manual',
        rawText: '',
        receivedAt: new Date().toISOString(),
      };

      const { ir, exportResults } = await pipeline.run(emptyEvent, outDir);
      expect(ir).toBeDefined();
      expect(ir.metadata.title).toBeDefined();
      expect(exportResults.staticWeb).toBeDefined();
      expect(exportResults.social).toBeDefined();
    });
  });
});
