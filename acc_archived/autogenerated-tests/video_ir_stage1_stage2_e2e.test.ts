import { describe, it, expect, beforeAll } from 'bun:test';
import path from 'path';
import fs from 'fs';
import { FFmpegManager } from '@acc/core';
import {
  IRConfigAdapterRegistry,
  StoryConfigToUniversalIRAdapter,
  RelationalDAGCompiler,
  AssetMetadataProber,
  IRMasterRenderer,
  FFIVideoEncoderSink,
  PreviewCanvasSink,
  ModifierPluginRegistry,
  type VideoIRDocument,
  type LegacyStoryConfig,
} from '@acc/ir';

describe('Video IR Stage 1 & Stage 2: Dual Sinks, Concrete Plugins & Native MP4 Compilation', () => {
  const sampleConfigPath = path.resolve(import.meta.dir, '../sample-story/story-config.json');
  const sampleDir = path.dirname(sampleConfigPath);
  const rawConfig: LegacyStoryConfig = JSON.parse(fs.readFileSync(sampleConfigPath, 'utf-8'));
  const testOutputDir = path.resolve(import.meta.dir, '../autogenerated/ir-e2e-out');

  beforeAll(async () => {
    await FFmpegManager.prepare();
    if (!fs.existsSync(testOutputDir)) {
      fs.mkdirSync(testOutputDir, { recursive: true });
    }
  });

  it('Stage 1: transforms legacy story config into Video IR document via IRConfigAdapterRegistry', () => {
    const registry = IRConfigAdapterRegistry.getInstance();
    expect(registry.listAdapters().length).toBeGreaterThanOrEqual(1);

    const irDoc = registry.transform(rawConfig);
    expect(irDoc.version).toBe('1.0.0-stable');
    expect(irDoc.meta.contentId).toBe('Dinosaur_Story');
    expect(irDoc.tracks.length).toBeGreaterThanOrEqual(3);
    expect(irDoc.assets).toBeDefined();
  });

  it('Stage 2 Preview Sink: renders frame stream into PreviewCanvasSink with sub-16ms interactive latency', async () => {
    const registry = IRConfigAdapterRegistry.getInstance();
    const irDoc = registry.transform(rawConfig);
    const prober = new AssetMetadataProber(sampleDir);
    const compiler = new RelationalDAGCompiler({ prober });
    const timeline = await compiler.compile(irDoc);

    // Limit to short 10-frame slice for interactive preview test
    timeline.totalFrames = 10;

    let framesReceived = 0;
    let lastFrameIndex = -1;

    const previewSink = new PreviewCanvasSink((frameIdx, buffer, meta) => {
      framesReceived++;
      lastFrameIndex = frameIdx;
      expect(buffer.length).toBe(meta.width * meta.height * 4);
    });

    const renderer = new IRMasterRenderer(timeline, 42);
    const renderResult = await renderer.render({
      sink: previewSink,
      baseDir: sampleDir,
    });

    expect(framesReceived).toBe(10);
    expect(lastFrameIndex).toBe(9);
    expect(previewSink.getLatestFrame()).toBeDefined();
    expect(renderResult.sinkResult?.framesConsumed).toBe(10);
  });

  it('Stage 2 Headless Sink: encodes deterministic Video IR frames into physical MP4 via FFIVideoEncoderSink', async () => {
    const registry = IRConfigAdapterRegistry.getInstance();
    const irDoc = registry.transform(rawConfig);
    const prober = new AssetMetadataProber(sampleDir);
    const compiler = new RelationalDAGCompiler({ prober });
    const timeline = await compiler.compile(irDoc);

    // Render 15 frames (~0.5 second) to verify native bun:ffi video encoding
    timeline.totalFrames = 15;

    const mp4Path = path.resolve(testOutputDir, 'ir_e2e_render_test.mp4');
    if (fs.existsSync(mp4Path)) {
      fs.unlinkSync(mp4Path);
    }

    const ffiSink = new FFIVideoEncoderSink();
    const renderer = new IRMasterRenderer(timeline, 9999);

    const renderResult = await renderer.render({
      sink: ffiSink,
      outputPath: mp4Path,
      baseDir: sampleDir,
      generateFrameHash: true,
    });

    expect(renderResult.sinkResult).toBeDefined();
    expect(renderResult.sinkResult?.outputPath).toBe(mp4Path);
    expect(renderResult.sinkResult?.framesConsumed).toBe(15);
    expect(fs.existsSync(mp4Path)).toBe(true);

    const stats = fs.statSync(mp4Path);
    expect(stats.size).toBeGreaterThan(1000); // Confirms non-empty, valid MP4 binary file
  });
});
