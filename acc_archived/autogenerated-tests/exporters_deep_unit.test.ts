import { describe, it, expect, beforeAll } from 'bun:test';
import fs from 'fs';
import path from 'path';
import type { PipelineIR } from '@acc/ir';
import { VideoExporter, AudioExporter, SocialExporter, StaticWebExporter } from '@acc/exporters';
import { FFmpegManager } from '@acc/core';

describe('Deep Unit & Edge-Case Test Suite for Exporters', () => {
  const testBaseDir = path.resolve(process.cwd(), 'autogenerated', 'exports', 'deep_tests');

  beforeAll(async () => {
    await FFmpegManager.prepare();
    if (!fs.existsSync(testBaseDir)) {
      fs.mkdirSync(testBaseDir, { recursive: true });
    }
  });

  // ==========================================
  // 1. SocialExporter Edge Cases
  // ==========================================
  describe('SocialExporter Unit & Edge Cases', () => {
    const socialExporter = new SocialExporter();

    it('handles extremely long texts without throwing or clipping fatally', async () => {
      const longTextIR: PipelineIR = {
        schemaVersion: '3.0.0',
        pipelineId: 'scraper-summarizer',
        metadata: {
          jobId: 'long_text_job',
          title: 'A'.repeat(120) + ' Extra Long Headline That Stretches Beyond Standard Limits',
          createdAt: new Date().toISOString(),
          tags: ['stress', 'typography'],
        },
        chunks: [
          {
            id: 'c1',
            order: 1,
            text: 'Lorem ipsum dolor sit amet, consectetur adipiscing elit. '.repeat(15),
            durationMs: 3000,
          },
        ],
        audioComposition: { sfxMarkers: [], ducking: { enabled: false, attenuationDb: -16, attackMs: 100, releaseMs: 300 } },
        distributionHints: { supportedExporters: ['social'], targetAspectRatios: ['1:1'] },
      };

      const result = await socialExporter.export(longTextIR, {
        outputDir: path.join(testBaseDir, 'social_long_text'),
      });

      expect(result.format).toBe('png');
      const files = result.outputPath as string[];
      expect(files.length).toBe(2); // Cover + 1 Chunk
      files.forEach((f) => expect(fs.existsSync(f)).toBe(true));
    });

    it('generates a thread markdown file with correct numbering and hashtags', async () => {
      const multiChunkIR: PipelineIR = {
        schemaVersion: '3.0.0',
        pipelineId: 'repurposing-recycler',
        metadata: {
          jobId: 'thread_job',
          title: '3 Lessons from Building Monorepos',
          createdAt: new Date().toISOString(),
          tags: ['monorepo', 'engineering', 'bun'],
        },
        chunks: [
          { id: 'c1', order: 1, text: 'Lesson 1: Strong typing prevents schema drift.', durationMs: 1000 },
          { id: 'c2', order: 2, text: 'Lesson 2: Shared memory zero-copy beats process spawning.', durationMs: 1000 },
          { id: 'c3', order: 3, text: 'Lesson 3: Decouple domain engines from distribution exporters.', durationMs: 1000 },
        ],
        audioComposition: { sfxMarkers: [], ducking: { enabled: false, attenuationDb: -16, attackMs: 100, releaseMs: 300 } },
        distributionHints: { supportedExporters: ['social'], targetAspectRatios: ['1:1'] },
      };

      const result = await socialExporter.export(multiChunkIR, {
        outputDir: path.join(testBaseDir, 'social_thread'),
      });

      const threadPath = result.metadata?.threadPath as string;
      expect(fs.existsSync(threadPath)).toBe(true);
      const content = fs.readFileSync(threadPath, 'utf-8');
      expect(content).toContain('1/ Lesson 1');
      expect(content).toContain('2/ Lesson 2');
      expect(content).toContain('3/ Lesson 3');
      expect(content).toContain('#monorepo #engineering #bun');
    });
  });

  // ==========================================
  // 2. StaticWebExporter Edge Cases
  // ==========================================
  describe('StaticWebExporter Unit & Edge Cases', () => {
    const webExporter = new StaticWebExporter();

    it('correctly serializes structured JSONB data alongside Markdown article', async () => {
      const structuredIR: PipelineIR = {
        schemaVersion: '3.0.0',
        pipelineId: 'db-templating',
        metadata: {
          jobId: 'specs_comparison',
          title: 'Smartphone Flagship Benchmark Comparison',
          createdAt: new Date().toISOString(),
          tags: ['benchmarks', 'hardware'],
        },
        chunks: [
          { id: 'c1', order: 1, summary: 'GPU Compute scores show 28% uplift.', text: 'Detailed analysis below.', durationMs: 2000 },
        ],
        audioComposition: { sfxMarkers: [], ducking: { enabled: false, attenuationDb: -16, attackMs: 100, releaseMs: 300 } },
        structuredData: {
          models: [
            { name: 'Model A', geekbenchMulti: 7450, tdpWatts: 12 },
            { name: 'Model B', geekbenchMulti: 6980, tdpWatts: 14 },
          ],
        },
        distributionHints: { supportedExporters: ['static-web'], targetAspectRatios: ['16:9'] },
      };

      const result = await webExporter.export(structuredIR, {
        outputDir: path.join(testBaseDir, 'web_structured'),
      });

      const [mdPath, jsonPath] = result.outputPath as string[];
      expect(fs.existsSync(mdPath)).toBe(true);
      expect(fs.existsSync(jsonPath)).toBe(true);

      const jsonContent = JSON.parse(fs.readFileSync(jsonPath, 'utf-8'));
      expect(jsonContent.structuredData.models.length).toBe(2);
      expect(jsonContent.structuredData.models[0].name).toBe('Model A');

      const mdContent = fs.readFileSync(mdPath, 'utf-8');
      expect(mdContent).toContain('geekbenchMulti');
    });
  });

  // ==========================================
  // 3. AudioExporter Unit & Edge Cases
  // ==========================================
  describe('AudioExporter Unit & Edge Cases', () => {
    const audioExporter = new AudioExporter();

    it('generates podcast chapter markers JSON accurately across variable duration chunks', async () => {
      const chapterIR: PipelineIR = {
        schemaVersion: '3.0.0',
        pipelineId: 'scraper-summarizer',
        metadata: {
          jobId: 'podcast_chapters',
          title: 'Daily Morning Digest',
          createdAt: new Date().toISOString(),
          tags: ['podcast', 'news'],
        },
        chunks: [
          { id: 'c1', order: 1, summary: 'Intro & Markets', durationMs: 4500 },
          { id: 'c2', order: 2, summary: 'Tech Acquisitions', durationMs: 8200 },
          { id: 'c3', order: 3, summary: 'Weather & Closing', durationMs: 3100 },
        ],
        audioComposition: { sfxMarkers: [], ducking: { enabled: false, attenuationDb: -16, attackMs: 100, releaseMs: 300 } },
        distributionHints: { supportedExporters: ['audio'], targetAspectRatios: ['1:1'] },
      };

      const result = await audioExporter.export(chapterIR, {
        outputDir: path.join(testBaseDir, 'audio_chapters'),
      });

      expect(result.format).toBe('mp3');
      const chaptersPath = result.metadata?.chaptersPath as string;
      expect(fs.existsSync(chaptersPath)).toBe(true);

      const chapters = JSON.parse(fs.readFileSync(chaptersPath, 'utf-8'));
      expect(chapters.length).toBe(3);
      expect(chapters[0].startTimeMs).toBe(0);
      expect(chapters[1].startTimeMs).toBe(4500);
      expect(chapters[2].startTimeMs).toBe(12700); // 4500 + 8200
    });
  });

  // ==========================================
  // 4. VideoExporter Unit & Edge Cases
  // ==========================================
  describe('VideoExporter Unit & Edge Cases', () => {
    const videoExporter = new VideoExporter();

    it('renders vertical 9:16 aspect ratio (1080x1920) for TikTok/Shorts cleanly', async () => {
      const verticalIR: PipelineIR = {
        schemaVersion: '3.0.0',
        pipelineId: 'scraper-summarizer',
        metadata: {
          jobId: 'vertical_shorts',
          title: 'Breaking AI Update in 60s',
          createdAt: new Date().toISOString(),
          tags: ['shorts', 'vertical'],
        },
        chunks: [
          {
            id: 'c1',
            order: 1,
            summary: 'New Local AI Model Outperforms Cloud APIs',
            durationMs: 1000, // 1.0s (30 frames)
          },
        ],
        audioComposition: { sfxMarkers: [], ducking: { enabled: false, attenuationDb: -16, attackMs: 100, releaseMs: 300 } },
        distributionHints: { supportedExporters: ['video'], targetAspectRatios: ['9:16'] },
      };

      const result = await videoExporter.export(verticalIR, {
        outputDir: path.join(testBaseDir, 'video_vertical'),
        aspectRatio: '9:16',
        fps: 30,
      });

      expect(result.format).toBe('mp4');
      expect(result.metadata?.aspectRatio).toBe('9:16');
      expect(result.metadata?.width).toBe(1080);
      expect(result.metadata?.height).toBe(1920);
      expect(result.metadata?.totalFrames).toBe(30);

      const videoPath = result.outputPath as string;
      expect(fs.existsSync(videoPath)).toBe(true);
      expect(fs.statSync(videoPath).size).toBeGreaterThan(5000);
    }, 15000);

    it('renders MKV container format when container is configured as mkv', async () => {
      const mkvIR: PipelineIR = {
        schemaVersion: '3.0.0',
        pipelineId: 'generative-storytelling',
        metadata: {
          jobId: 'mkv_test',
          title: 'MKV Container Export Test',
          createdAt: new Date().toISOString(),
          tags: ['mkv', 'container'],
        },
        chunks: [
          {
            id: 'c1',
            order: 1,
            summary: 'Testing MKV Output Format',
            durationMs: 500, // 0.5s (15 frames)
          },
        ],
        audioComposition: { sfxMarkers: [], ducking: { enabled: false, attenuationDb: 0, attackMs: 0, releaseMs: 0 } },
      };

      const result = await videoExporter.export(mkvIR, {
        outputDir: path.join(testBaseDir, 'video_mkv'),
        container: 'mkv',
        fps: 30,
      });

      expect(result.format).toBe('mkv');
      const videoPath = result.outputPath as string;
      expect(videoPath.endsWith('.mkv')).toBe(true);
      expect(fs.existsSync(videoPath)).toBe(true);
      expect(fs.statSync(videoPath).size).toBeGreaterThan(1000);
    }, 15000);
  });
});
