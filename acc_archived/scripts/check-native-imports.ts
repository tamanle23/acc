import fs from 'fs';
import path from 'path';

/**
 * CI / Linter Guardrail:
 * Statically asserts zero unauthorized platform-dependent native library leaks.
 * - @napi-rs/canvas is banned outside @acc/core-native (packages/core/src/native)
 * - bun:ffi is banned in client packages (apps/studio, packages/effect-engines, packages/ir, packages/core/src/isomorphic, packages/core/src/web)
 */

interface Violation {
  file: string;
  line: number;
  content: string;
  rule: string;
}

const VIOLATIONS: Violation[] = [];

function checkFile(filePath: string) {
  if (
    filePath.includes('node_modules') ||
    filePath.includes('dist') ||
    filePath.includes('.git') ||
    filePath.includes('autogenerated-tests') ||
    filePath.includes('benchmarks') ||
    filePath.includes('scripts') ||
    filePath.includes('.hutch') ||
    filePath.endsWith('.d.ts') ||
    filePath.endsWith('.md')
  ) {
    return;
  }

  const content = fs.readFileSync(filePath, 'utf-8');
  const lines = content.split('\n');

  const normalized = filePath.replace(/\\/g, '/');

  // Allow native adapters to import native libraries
  const isAllowedNapi =
    normalized.includes('packages/core/src/native') ||
    normalized.includes('packages/core-native');

  const isAllowedFFI =
    normalized.includes('packages/core/src/ffmpeg-ffi') ||
    normalized.includes('packages/core/src/native') ||
    normalized.includes('packages/core-native');

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const lineNum = i + 1;

    // Check @napi-rs/canvas import or require
    if (!isAllowedNapi && /['"]@napi-rs\/canvas['"]/.test(line)) {
      VIOLATIONS.push({
        file: filePath,
        line: lineNum,
        content: line.trim(),
        rule: 'Direct @napi-rs/canvas import forbidden outside @acc/core-native. Use UniversalCanvasProvider from @acc/core-isomorphic instead.',
      });
    }

    // Check bun:ffi import in client/isomorphic files
    if (
      !isAllowedFFI &&
      (normalized.includes('apps/studio') ||
        normalized.includes('packages/effect-engines') ||
        normalized.includes('packages/ir') ||
        normalized.includes('packages/core/src/isomorphic') ||
        normalized.includes('packages/core/src/web') ||
        normalized.includes('packages/core-isomorphic') ||
        normalized.includes('packages/core-web')) &&
      /['"]bun:ffi['"]/.test(line)
    ) {
      VIOLATIONS.push({
        file: filePath,
        line: lineNum,
        content: line.trim(),
        rule: 'Direct bun:ffi import forbidden in client/isomorphic packages. Use MediaEngineRegistry and IMediaEngineStrategy.',
      });
    }
  }
}

function scanDir(dir: string) {
  if (!fs.existsSync(dir)) return;
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      scanDir(full);
    } else if (entry.isFile() && (entry.name.endsWith('.ts') || entry.name.endsWith('.tsx') || entry.name.endsWith('.js'))) {
      checkFile(full);
    }
  }
}

console.log('[Linter Guardrail] Scanning apps/ and packages/ for native import boundaries...');
scanDir(path.resolve(process.cwd(), 'apps'));
scanDir(path.resolve(process.cwd(), 'packages'));

if (VIOLATIONS.length > 0) {
  console.error(`\x1b[31m[FAILED] Found ${VIOLATIONS.length} unauthorized platform-dependent import violation(s):\x1b[0m`);
  for (const v of VIOLATIONS) {
    console.error(`  - \x1b[33m${v.file}:${v.line}\x1b[0m`);
    console.error(`    ${v.content}`);
    console.error(`    \x1b[31m--> ${v.rule}\x1b[0m\n`);
  }
  process.exit(1);
} else {
  console.log('\x1b[32m[PASSED] 0 unauthorized native import leaks detected across monorepo.\x1b[0m');
  process.exit(0);
}
