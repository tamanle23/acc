import fs from 'fs';
import path from 'path';
import { fileExists, UniversalCanvasProvider } from '@acc/core';
import type { PipelineIR, ContentChunk } from '@acc/ir';
import type { IExporter, ExportOptions, ExportResult } from '../base/BaseExporter';

export interface SocialExportOptions extends ExportOptions {
  theme?: 'dark' | 'light' | 'cinematic';
  format?: 'carousel' | 'alert_card' | 'thread';
}

export class SocialExporter implements IExporter<SocialExportOptions> {
  public readonly id = 'social';

  public async export(ir: PipelineIR, options: SocialExportOptions = {}): Promise<ExportResult> {
    const outDir = options.outputDir || path.resolve(process.cwd(), 'autogenerated', 'exports', 'social');
    if (!(await fileExists(outDir))) {
      await fs.promises.mkdir(outDir, { recursive: true });
    }

    const prefix = options.fileNamePrefix || ir.metadata.jobId || 'social';
    const generatedImages: string[] = [];

    // 1. Render Cover Slide (1080x1350)
    const coverPath = path.join(outDir, `${prefix}_slide_01_cover.png`);
    await this.renderCoverSlide(ir.metadata.title, ir.metadata.tags, coverPath);
    generatedImages.push(coverPath);

    // 2. Render Content Chunk Slides
    for (let index = 0; index < ir.chunks.length; index++) {
      const chunk = ir.chunks[index];
      const slideNum = String(index + 2).padStart(2, '0');
      const slidePath = path.join(outDir, `${prefix}_slide_${slideNum}.png`);
      await this.renderChunkSlide(chunk, index + 1, ir.chunks.length, slidePath);
      generatedImages.push(slidePath);
    }

    // 3. Write Twitter/Threads Thread File
    const threadPath = path.join(outDir, `${prefix}_thread.md`);
    const threadContent = this.generateThreadMarkdown(ir);
    await fs.promises.writeFile(threadPath, threadContent, 'utf-8');

    return {
      exporterId: this.id,
      outputPath: generatedImages,
      format: 'png',
      metadata: {
        slideCount: generatedImages.length,
        threadPath,
      },
    };
  }

  private async renderCoverSlide(title: string, tags: string[], outputPath: string) {
    const canvas = UniversalCanvasProvider.createCanvas(1080, 1350);
    const ctx = canvas.getContext('2d');

    // Background gradient
    const grad = ctx.createLinearGradient(0, 0, 1080, 1350);
    grad.addColorStop(0, '#0f172a');
    grad.addColorStop(1, '#020617');
    ctx.fillStyle = grad;
    ctx.fillRect(0, 0, 1080, 1350);

    // Accent line
    ctx.fillStyle = '#38bdf8';
    ctx.fillRect(80, 120, 120, 8);

    // Category / Tag badge
    ctx.font = 'bold 32px sans-serif';
    ctx.fillStyle = '#38bdf8';
    ctx.fillText(tags[0] ? `#${tags[0].toUpperCase()}` : '#BREAKING', 80, 180);

    // Title text wrapped
    ctx.font = 'bold 72px sans-serif';
    ctx.fillStyle = '#f8fafc';
    this.wrapText(ctx, title, 80, 320, 920, 96);

    // Footer swipe prompt
    ctx.font = '500 36px sans-serif';
    ctx.fillStyle = '#94a3b8';
    ctx.fillText('Swipe to read more ➔', 80, 1220);

    const buffer = canvas.toBuffer('image/png');
    await fs.promises.writeFile(outputPath, buffer);
  }

  private async renderChunkSlide(chunk: ContentChunk, step: number, total: number, outputPath: string) {
    const canvas = UniversalCanvasProvider.createCanvas(1080, 1350);
    const ctx = canvas.getContext('2d');

    ctx.fillStyle = '#0b0f19';
    ctx.fillRect(0, 0, 1080, 1350);

    // Step indicator
    ctx.font = 'bold 36px sans-serif';
    ctx.fillStyle = '#38bdf8';
    ctx.fillText(`0${step} / 0${total}`, 80, 160);

    // Divider
    ctx.fillStyle = '#1e293b';
    ctx.fillRect(80, 190, 920, 2);

    // Chunk text
    ctx.font = '500 48px sans-serif';
    ctx.fillStyle = '#e2e8f0';
    const textToRender = chunk.text || chunk.summary || '';
    this.wrapText(ctx, textToRender, 80, 300, 920, 72);

    const buffer = canvas.toBuffer('image/png');
    await fs.promises.writeFile(outputPath, buffer);
  }

  private wrapText(ctx: any, text: string, x: number, y: number, maxWidth: number, lineHeight: number) {
    const words = text.split(' ');
    let line = '';
    let currentY = y;

    for (let n = 0; n < words.length; n++) {
      const testLine = line + words[n] + ' ';
      const metrics = ctx.measureText(testLine);
      if (metrics.width > maxWidth && n > 0) {
        ctx.fillText(line, x, currentY);
        line = words[n] + ' ';
        currentY += lineHeight;
      } else {
        line = testLine;
      }
    }
    ctx.fillText(line, x, currentY);
  }

  private generateThreadMarkdown(ir: PipelineIR): string {
    let md = `🧵 **${ir.metadata.title}**\n\n`;
    ir.chunks.forEach((c, idx) => {
      md += `${idx + 1}/ ${c.text || c.summary}\n\n`;
    });
    md += `Tags: ${ir.metadata.tags.map((t) => '#' + t).join(' ')}\n`;
    return md;
  }
}
