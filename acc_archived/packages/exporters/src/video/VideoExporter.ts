import fs from 'fs';
import path from 'path';
import type { PipelineIR, ContentChunk } from '@acc/ir';
import type { IExporter, ExportOptions, ExportResult } from '../base/BaseExporter';
import { FFmpegManager, initFFI, FFIVideoEncoder, fileExists, Logger, UniversalCanvasProvider } from '@acc/core';

import type { MediaEngineType } from '@acc/core';

export interface VideoExportOptions extends ExportOptions {
  engine?: MediaEngineType;
  width?: number;
  height?: number;
  fps?: number;
  crf?: number;
  container?: 'mp4' | 'mkv' | 'mov' | 'webm';
  format?: 'mp4' | 'mkv' | 'mov' | 'webm';
  fastStart?: boolean;
}

export class VideoExporter implements IExporter<VideoExportOptions> {
  public readonly id = 'video';

  public async export(ir: PipelineIR, options: VideoExportOptions = {}): Promise<ExportResult> {
    await FFmpegManager.prepare();
    initFFI();

    const isVertical = options.aspectRatio === '9:16';
    const width = options.width || (isVertical ? 1080 : 1920);
    const height = options.height || (isVertical ? 1920 : 1080);
    const fps = options.fps || 30;
    const crf = options.crf || 20;

    const outDir = options.outputDir || path.resolve(process.cwd(), 'autogenerated', 'exports', 'video');
    if (!(await fileExists(outDir))) {
      await fs.promises.mkdir(outDir, { recursive: true });
    }

    const container = options.container || options.format || (ir.distributionHints as any)?.targetFormat || 'mp4';
    const prefix = options.fileNamePrefix || ir.metadata.jobId || 'video';
    const outputPath = path.join(outDir, `${prefix}.${container}`);

    // Phase 4 Omnichannel Upgrade: Route video output directly through Universal Video IR
    try {
      const {
        PipelineIRToUniversalIRAdapter,
        RelationalDAGCompiler,
        AssetMetadataProber,
        IRMasterRenderer,
      } = await import('@acc/ir');
      type IIRFrameSinkType = import('@acc/ir').IIRFrameSink;
      const { MediaEngineRegistry } = await import('@acc/core-isomorphic');

      Logger.info('VideoExporter', `⚡ Compiling PipelineIR [${ir.pipelineId}] to Universal Video IR...`);
      const directorConfig = (options as any)?.directorConfig || (options as any)?.videoConfig;
      const irDoc = PipelineIRToUniversalIRAdapter.adapt(ir, undefined, outDir, directorConfig);
      irDoc.meta.canvasSize = { w: width, h: height };
      irDoc.meta.globalFps = fps;

      // Persist canonical video-ir.json by default in output directory
      const irPersistPath = path.join(outDir, 'video-ir.json');
      await fs.promises.writeFile(irPersistPath, JSON.stringify(irDoc, null, 2), 'utf-8');
      Logger.info('VideoExporter', `📄 Persisted canonical Video IR: ${irPersistPath}`);

      const prober = new AssetMetadataProber(outDir);
      const compiler = new RelationalDAGCompiler({ prober });
      const timeline = await compiler.compile(irDoc);

      const renderer = new IRMasterRenderer(timeline, 42);
      const sink = MediaEngineRegistry.get(options.engine).createVideoSink() as IIRFrameSinkType;

      const renderResult = await renderer.render({
        sink,
        outputPath,
        baseDir: outDir,
      });

      return {
        exporterId: this.id,
        outputPath,
        format: container,
        durationMs: Math.round(renderResult.durationSeconds * 1000),
        metadata: {
          width,
          height,
          fps,
          totalFrames: renderResult.totalFrames,
          aspectRatio: isVertical ? '9:16' : '16:9',
          container,
          irCumulativeHash: renderResult.cumulativeHash,
        },
      };
    } catch (irErr: any) {
      Logger.warn('VideoExporter', `Universal Video IR export fallback triggered: ${irErr.message}. Running canvas encoder...`);
    }

    // Fallback path
    let primaryAudio: string | undefined = undefined;
    for (const chunk of ir.chunks) {
      if (chunk.spokenAudioPath && (await fileExists(chunk.spokenAudioPath))) {
        primaryAudio = chunk.spokenAudioPath;
        break;
      }
    }

    const encoder = new FFIVideoEncoder(width, height, fps, outputPath, crf, primaryAudio, undefined, {
      container,
      fastStart: options.fastStart ?? true,
    });
    encoder.initialize();

    let totalEncodedFrames = 0;
    let totalDurationMs = 0;

    for (let cIdx = 0; cIdx < ir.chunks.length; cIdx++) {
      const chunk = ir.chunks[cIdx];
      const durationMs = chunk.durationMs > 0 ? chunk.durationMs : 3000;
      totalDurationMs += durationMs;

      // Deterministic frame calculation
      const frameCount = Math.max(1, Math.ceil((durationMs * fps) / 1000));

      // Render slide on Canvas
      const canvas = UniversalCanvasProvider.createCanvas(width, height);
      const ctx = canvas.getContext('2d');
      this.drawChunkFrame(ctx, chunk, cIdx + 1, ir.chunks.length, width, height, ir.metadata.title);

      const frameBuffer = typeof canvas.data === 'function' ? canvas.data() : canvas.toBuffer('raw');

      for (let f = 0; f < frameCount; f++) {
        encoder.encodeRgbaFrame(frameBuffer);
        totalEncodedFrames++;
      }
    }

    encoder.close();

    return {
      exporterId: this.id,
      outputPath,
      format: container,
      durationMs: totalDurationMs,
      metadata: {
        width,
        height,
        fps,
        totalFrames: totalEncodedFrames,
        aspectRatio: isVertical ? '9:16' : '16:9',
        container,
      },
    };
  }

  private drawChunkFrame(
    ctx: any,
    chunk: ContentChunk,
    index: number,
    total: number,
    width: number,
    height: number,
    title: string
  ) {
    // 1. Dark modern gradient background
    const grad = ctx.createLinearGradient(0, 0, width, height);
    grad.addColorStop(0, '#090d16');
    grad.addColorStop(1, '#020617');
    ctx.fillStyle = grad;
    ctx.fillRect(0, 0, width, height);

    // 2. Header bar with category / series title
    ctx.font = 'bold 36px sans-serif';
    ctx.fillStyle = '#38bdf8';
    ctx.fillText(`NEWS RECAP • ${index}/${total}`, 80, 100);

    // 3. Main Title
    ctx.font = 'bold 54px sans-serif';
    ctx.fillStyle = '#f8fafc';
    this.wrapText(ctx, title, 80, 190, width - 160, 68);

    // 4. Content card container
    const cardY = 320;
    const cardH = height - cardY - 160;
    ctx.fillStyle = '#0f172a';
    ctx.roundRect(80, cardY, width - 160, cardH, 24);
    ctx.fill();

    // 5. Card text
    ctx.font = '500 48px sans-serif';
    ctx.fillStyle = '#e2e8f0';
    const text = chunk.text || chunk.summary || '';
    this.wrapText(ctx, text, 120, cardY + 120, width - 240, 72);

    // 6. Accent bottom highlight bar
    ctx.fillStyle = '#38bdf8';
    ctx.fillRect(80, height - 100, width - 160, 6);
  }

  private wrapText(ctx: any, text: string, x: number, y: number, maxWidth: number, lineHeight: number) {
    const words = text.split(' ');
    let line = '';
    let currentY = y;

    for (let n = 0; n < words.length; n++) {
      const testLine = line + words[n] + ' ';
      const metrics = ctx.measureText(testLine);
      if (metrics.width > maxWidth && n > 0) {
        ctx.fillText(line, x, currentY);
        line = words[n] + ' ';
        currentY += lineHeight;
      } else {
        line = testLine;
      }
    }
    ctx.fillText(line, x, currentY);
  }
}
