import { BaseContentTaskStrategy, StrategyDescriptor } from '../BaseContentTaskStrategy';
import type { UnifiedPipelineContext } from '../../../pipeline/UnifiedPipelineContext';
import type { PipelineIR } from '@acc/ir';

export interface StaticWebOutput {
  contentTypeId: string;
  pipelineId: string;
  targetModality: 'static-web';
  markdown: string;
  html: string;
  ir: PipelineIR;
  seoMetadata: {
    title: string;
    description: string;
    keywords: string[];
    canonicalUrl?: string;
  };
  timestamp: number;
}

export class StaticWebContentStrategy extends BaseContentTaskStrategy<any, StaticWebOutput> {
  constructor(descriptor: StrategyDescriptor) {
    super({
      ...descriptor,
      targetModality: 'static-web',
    });
  }

  protected override async produceOutput(
    ctx: UnifiedPipelineContext<any>,
    ir: PipelineIR
  ): Promise<StaticWebOutput> {
    const title = ir.metadata.title;
    const bodyText = ir.chunks[0]?.text || '';
    const keywords = (ir.metadata.tags || []).concat(['cms', 'ssg', 'static-web']);

    const markdown = `# ${title}\n\n${bodyText}\n\n*Generated by ACC Strategy: ${this.contentTypeId}*`;
    const html = `<article class="acc-article" data-content-id="${this.contentTypeId}"><h1>${title}</h1><p>${bodyText}</p></article>`;

    return {
      contentTypeId: this.contentTypeId,
      pipelineId: this.pipelineId,
      targetModality: 'static-web',
      markdown,
      html,
      ir,
      seoMetadata: {
        title,
        description: bodyText.slice(0, 160),
        keywords,
      },
      timestamp: Date.now(),
    };
  }
}
