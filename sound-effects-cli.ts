import { parseArgs } from 'util';
import { RegistryManager } from './src/sound-effects/core/Registry';
import path from 'path';
import fs from 'fs';
import { renderSoundEffect, renderCompositeSound } from './src/sound-effects/engine';
import { FFmpegManager } from './src/core/FFmpegManager';
import { askChoice, askQuestion, askYesNo, closeInteractiveConsole } from './src/core/interactive';

async function generateHeadless(values: any) {
  if (!values.composite && !values['custom-prompt'] && (!values.effect || !values.variant || !values['sub-variant'])) {
    console.error('Error: Either --composite, --custom-prompt, OR (--effect, --variant, and --sub-variant) is required.');
    process.exit(1);
  }

  const aiModel = values['ai-model'] || 'audioldm2-base';

  // Instantiate Registry WITHOUT engine mode (Smart Routing applies)
  const registry = new RegistryManager(aiModel);
  const outDir = path.resolve(process.cwd(), 'autogenerated', 'sound-effects', 'mixed');
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }

  try {
    if (values.composite) {
      const compositeName = values.composite.toLowerCase();
      console.log(`\n=== Sound Effects Composite Generator ===`);
      console.log(`Composite:  ${compositeName}`);
      
      const outputs = await renderCompositeSound(registry, compositeName, outDir);
      console.log(`\n✅ Composite '${compositeName}' successfully generated!`);
      outputs.forEach(o => console.log(` - Audio:    ${o}`));
    } else if (values['custom-prompt']) {
      const duration = values.duration ? parseFloat(values.duration) : 3.0;
      const customPrompt = values['custom-prompt'];
      
      console.log(`\n=== Sound Effect Generator (Custom Prompt) ===`);
      console.log(`Prompt:     ${customPrompt}`);
      
      const output = await renderSoundEffect(registry, 'custom', 'custom', 'custom', duration, outDir, customPrompt);
      console.log(`\n✅ Successfully completed audio synthesis!\nAudio:    ${output}`);
    } else if (values.effect) {
      const effectName = values.effect.toLowerCase();
      const variantName = values.variant!.toLowerCase();
      const subVariantName = values['sub-variant']!.toLowerCase();
      const duration = values.duration ? parseFloat(values.duration) : 3.0;

      console.log(`\n=== Sound Effect Generator ===`);
      
      const output = await renderSoundEffect(registry, effectName, variantName, subVariantName, duration, outDir);
      console.log(`\n✅ Successfully completed audio synthesis!\nAudio:    ${output}`);
    }
  } catch (err: any) {
    console.error(`\n❌ Error: ${err.message}`);
    process.exit(1);
  }
}

async function startWizard() {
  console.log('\n============================================');
  console.log('🎹 Sound Effects Interactive Console (Smart Routing)');
  console.log('============================================\n');

  while (true) {
    const aiModel = await askChoice('Select Background AI Model (used if Smart Router selects AI):', ['audioldm2-base', 'audioldm2-large']);

    const registry = new RegistryManager(aiModel);
    const outDir = path.resolve(process.cwd(), 'autogenerated', 'sound-effects', 'mixed');
    if (!fs.existsSync(outDir)) {
      fs.mkdirSync(outDir, { recursive: true });
    }

    const mode = await askChoice('Generation Mode:', ['Single Sound Effect', 'Composite Sound (Multi-layer Mix)', 'Custom Prompt (Freeform Text)']);

    try {
      if (mode.startsWith('Composite')) {
        const compositeName = await askQuestion('Enter composite name (e.g., cinematic_trailer_hit): ');
        if (!compositeName) throw new Error('Name cannot be empty.');
        
        console.log(`\nGenerating composite: ${compositeName}...`);
        const outputs = await renderCompositeSound(registry, compositeName, outDir);
        console.log(`\n✅ Composite successfully generated!`);
        outputs.forEach(o => console.log(` - Audio:    ${o}`));
      } else if (mode.startsWith('Custom')) {
        // --- ADDED TIPS FOR CUSTOM PROMPT AS REQUESTED ---
        console.log(`\n💡 [PROMPT TIPS] For the best results, use descriptive acoustic adjectives:`);
        console.log(`  - Good (AI): "Cinematic heavy sub bass impact, deep reverb, dramatic"`);
        console.log(`  - Good (AI): "Sci-fi alien laser gun, high pitch energy blast"`);
        console.log(`  - Avoid single vague words like "explosion" or "sound".\n`);

        const customPrompt = await askQuestion('Enter your custom prompt / search query: ');
        const durationStr = await askQuestion('Enter duration in seconds [3.0]: ');
        const duration = durationStr.trim() ? parseFloat(durationStr) : 3.0;
        
        console.log(`\nGenerating custom sound for ${duration}s...`);
        const output = await renderSoundEffect(registry, 'custom', 'custom', 'custom', duration, outDir, customPrompt);
        console.log(`\n✅ Successfully completed audio synthesis!\nAudio:    ${output}`);
      } else {
        // Pre-defined categories for the wizard to make it easy
        const effect = await askChoice('Select Category (Effect):', ['foley', 'diegetic', 'cinematic', 'scifi', 'ui', 'fauna']);
        const variant = await askQuestion(`Enter variant (e.g., for foley: footsteps, cloth): `);
        const subVariant = await askQuestion(`Enter sub-variant (e.g., gravel, heavy_blast): `);
        const durationStr = await askQuestion(`Enter duration in seconds [3.0]: `);
        const duration = durationStr.trim() ? parseFloat(durationStr) : 3.0;

        console.log(`\nGenerating [${effect} > ${variant} > ${subVariant}] for ${duration}s...`);
        const output = await renderSoundEffect(registry, effect, variant, subVariant, duration, outDir);
        console.log(`\n✅ Successfully completed audio synthesis!\nAudio:    ${output}`);
      }
    } catch (err: any) {
      console.error(`\n❌ Error: ${err.message}`);
    }

    const continueLoop = await askYesNo('\nDo you want to generate another sound effect?');
    if (!continueLoop) {
      console.log('Goodbye!');
      break;
    }
  }

  closeInteractiveConsole();
  process.exit(0);
}

async function main() {
  await FFmpegManager.prepare();
  
  const args = process.argv.slice(2);
  if (args.length > 0) {
    // Headless mode
    const { values } = parseArgs({
      args: args,
      options: {
        effect: { type: 'string', short: 'e' },
        variant: { type: 'string', short: 'v' },
        'sub-variant': { type: 'string', short: 's' },
        composite: { type: 'string', short: 'c' },
        duration: { type: 'string', short: 'd' },
        'ai-model': { type: 'string', default: 'audioldm2-base' },
        'custom-prompt': { type: 'string', short: 'p' }
      },
      allowPositionals: true,
    });
    await generateHeadless(values);
    process.exit(0);
  } else {
    // Interactive Wizard mode
    await startWizard();
  }
}

main();
