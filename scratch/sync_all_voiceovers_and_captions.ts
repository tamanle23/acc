import fs from 'fs';
import path from 'path';
import { FFmpegManager, Utils } from '@acc/core';
import { tts } from '@acc/cli/src/pipelines/04-generative-story/tts';
import { transcribeAudio } from '@acc/cli/src/pipelines/04-generative-story/whisper';

async function main() {
  await FFmpegManager.prepare();

  const configPath = path.resolve('sample-story/story-config.json');
  const cfg = JSON.parse(fs.readFileSync(configPath, 'utf8'));
  const voiceDir = path.resolve('sample-story/autogenerated/voiceovers');
  fs.mkdirSync(voiceDir, { recursive: true });

  const ttsVoice = cfg.settings.tts?.voice || 'Ngọc Trân';
  const ttsSpeed = cfg.settings.tts?.speed || 1.0;

  console.log(`Synchronizing ${cfg.scenes.length} scenes with TTS voice "${ttsVoice}"...`);

  for (let i = 0; i < cfg.scenes.length; i++) {
    const scene = cfg.scenes[i];
    const visual = scene.image || scene.video || `scene_${i + 1}`;
    
    // Determine the exact narration text for this scene
    let sceneText = scene.text;
    if (!sceneText && scene.captions && scene.captions.length > 0) {
      sceneText = scene.captions.map((c: any) => c.text).join(' ');
    }

    if (!sceneText || sceneText.trim().length === 0) {
      console.warn(`[Scene ${i + 1}] No text found. Skipping TTS.`);
      continue;
    }

    sceneText = sceneText.trim();
    scene.text = sceneText;

    // For scenes 1 and 2, they already have real custom recordings voiceover1.mp3 and voiceover2.mp3
    if (i === 0 && fs.existsSync('sample-story/assets/voiceover1.mp3')) {
      scene.audio = 'assets/voiceover1.mp3';
      const fullAudioPath = path.resolve('sample-story', scene.audio);
      console.log(`[Scene 1] Aligning captions for existing asset: ${scene.audio}`);
      scene.captions = await transcribeAudio(fullAudioPath, 'vietnamese', true, sceneText);
      console.log(`[Scene 1] Result captions:`, scene.captions.map((c: any) => `${c.text}(${c.start}-${c.end})`).join(' '));
      continue;
    }

    if (i === 1 && fs.existsSync('sample-story/assets/voiceover2.mp3')) {
      scene.audio = 'assets/voiceover2.mp3';
      const fullAudioPath = path.resolve('sample-story', scene.audio);
      console.log(`[Scene 2] Aligning captions for existing asset: ${scene.audio}`);
      scene.captions = await transcribeAudio(fullAudioPath, 'vietnamese', true, sceneText);
      console.log(`[Scene 2] Result captions:`, scene.captions.map((c: any) => `${c.text}(${c.start}-${c.end})`).join(' '));
      continue;
    }

    // For all other scenes (3 through 28): generate distinct TTS voiceovers matching sceneText
    const baseName = path.basename(visual, path.extname(visual));
    const checksum = Utils.getChecksum(`${sceneText}-${ttsVoice}-${ttsSpeed}-${i}`);
    const outputName = `${baseName}_s${i + 1}.${checksum}`;
    const targetWav = path.join(voiceDir, `${outputName}.wav`);

    console.log(`\n[Scene ${i + 1}/${cfg.scenes.length}] Synthesizing TTS: "${sceneText}"`);
    let finalAudioPath = targetWav;
    if (!fs.existsSync(targetWav)) {
      const res = await tts(sceneText, { voice: ttsVoice, speed: ttsSpeed }, outputName, voiceDir);
      finalAudioPath = res.file;
    }

    const relAudioPath = path.relative('sample-story', finalAudioPath).replace(/\\/g, '/');
    scene.audio = relAudioPath;

    // Run transcription / alignment for precise word timestamps
    console.log(`[Scene ${i + 1}] Aligning captions with audio: ${relAudioPath}`);
    scene.captions = await transcribeAudio(finalAudioPath, 'vietnamese', true, sceneText);
    console.log(`[Scene ${i + 1}] Timestamps: span [${scene.captions[0]?.start}..${scene.captions[scene.captions.length - 1]?.end}]s (${scene.captions.length} words)`);
  }

  fs.writeFileSync(configPath, JSON.stringify(cfg, null, 2), 'utf8');
  console.log(`\n✅ All ${cfg.scenes.length} scenes updated and synchronized in ${configPath}`);
}

main().catch(err => {
  console.error('Error:', err);
  process.exit(1);
});
