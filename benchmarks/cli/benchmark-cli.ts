import { spawn } from 'child_process';
import fs from 'fs';
import path from 'path';

interface HyperfineResult {
  command: string;
  mean: number;
  stddev: number;
  median: number;
  user: number;
  system: number;
  min: number;
  max: number;
}

interface HyperfineExport {
  results: HyperfineResult[];
}

async function main() {
  const outDir = path.join(process.cwd(), 'autogenerated', 'benchmarks');
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }

  const jsonExportPath = path.join(outDir, 'cli-benchmark-results.json');
  const mdExportPath = path.join(outDir, 'cli-benchmark-results.md');

  console.log('=====================================================');
  console.log('⏱️ ACC CLI Macro Benchmarks (hyperfine)');
  console.log('=====================================================\n');

  const hyperfinePath = process.env.HYPERFINE_PATH || 'hyperfine';

  const benchmarkCommands = [
    'bun run cli.ts list',
    'bun run cli.ts help',
    'bun run cli.ts run db --dry-run',
    'bun run cli.ts run story --dry-run',
    'bun run cli.ts overlay --effect rain --variant storm --duration 1',
    'bun run cli.ts sfx --effect ui --variant click --sub-variant plastic_pop',
  ];

  console.log('[CLI-Bench] Commands to benchmark:');
  benchmarkCommands.forEach((cmd, idx) => console.log(`  ${idx + 1}. ${cmd}`));
  console.log('\n[CLI-Bench] Executing hyperfine benchmark suite...\n');

  const hyperfineArgs = [
    '--warmup', '1',
    '--runs', '3',
    '--export-json', jsonExportPath,
    '--export-markdown', mdExportPath,
    ...benchmarkCommands,
  ];

  const proc = spawn(hyperfinePath, hyperfineArgs, {
    stdio: 'inherit',
  });

  await new Promise<void>((resolve, reject) => {
    proc.on('close', (code) => {
      if (code === 0) resolve();
      else reject(new Error(`hyperfine exited with code ${code}`));
    });
  });

  console.log('\n=====================================================');
  console.log('📊 HYPERFINE CLI BENCHMARK SUMMARY');
  console.log('=====================================================');

  if (fs.existsSync(jsonExportPath)) {
    const data: HyperfineExport = JSON.parse(fs.readFileSync(jsonExportPath, 'utf-8'));
    data.results.forEach((res, i) => {
      console.log(`Command ${i + 1}: ${res.command}`);
      console.log(`  Mean Execution Time: ${(res.mean * 1000).toFixed(2)} ms (± ${(res.stddev * 1000).toFixed(2)} ms)`);
      console.log(`  Min .. Max:          ${(res.min * 1000).toFixed(2)} ms .. ${(res.max * 1000).toFixed(2)} ms`);
    });
  }

  console.log('=====================================================');
  console.log(`✅ Saved JSON report to:     ${jsonExportPath}`);
  console.log(`✅ Saved Markdown report to: ${mdExportPath}\n`);
}

main().catch((err) => {
  console.error('[CLI-Bench] Error:', err);
  process.exit(1);
});
