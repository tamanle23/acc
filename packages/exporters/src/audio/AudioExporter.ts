import fs from 'fs';
import path from 'path';
import type { PipelineIR } from '@acc/ir';
import type { IExporter, ExportOptions, ExportResult } from '../base/BaseExporter';
import { FFmpegCommand, FFmpegManager } from '@acc/core';

export interface AudioExportOptions extends ExportOptions {
  bitrate?: string; // e.g. "192k"
  sampleRate?: number; // e.g. 44100
}

export class AudioExporter implements IExporter<AudioExportOptions> {
  public readonly id = 'audio';

  public async export(ir: PipelineIR, options: AudioExportOptions = {}): Promise<ExportResult> {
    await FFmpegManager.prepare();

    const outDir = options.outputDir || path.resolve(process.cwd(), 'autogenerated', 'exports', 'audio');
    if (!fs.existsSync(outDir)) {
      fs.mkdirSync(outDir, { recursive: true });
    }

    const prefix = options.fileNamePrefix || ir.metadata.jobId || 'podcast';
    const outputPath = path.join(outDir, `${prefix}.mp3`);

    // 1. Gather all existing audio tracks from chunks
    const validAudioChunks = ir.chunks
      .map((c) => c.spokenAudioPath)
      .filter((p): p is string => !!p && fs.existsSync(p));

    if (validAudioChunks.length === 0) {
      const sampleBgm = path.resolve(process.cwd(), 'sample-story', 'bgm.mp3');
      if (fs.existsSync(sampleBgm)) {
        fs.copyFileSync(sampleBgm, outputPath);
      } else {
        const silentBuf = Buffer.alloc(4096, 0);
        fs.writeFileSync(outputPath, silentBuf);
      }
    } else if (validAudioChunks.length === 1) {
      fs.copyFileSync(validAudioChunks[0], outputPath);
    } else {
      const combinedBuffers = validAudioChunks.map((p) => fs.readFileSync(p));
      fs.writeFileSync(outputPath, Buffer.concat(combinedBuffers));
    }

    // 2. Write Podcast Chapter Metadata JSON
    const chaptersPath = path.join(outDir, `${prefix}_chapters.json`);
    let currentOffsetMs = 0;
    const chapters = ir.chunks.map((chunk, idx) => {
      const ch = {
        id: idx + 1,
        title: chunk.summary || `Chapter ${idx + 1}`,
        startTimeMs: currentOffsetMs,
        durationMs: chunk.durationMs,
      };
      currentOffsetMs += chunk.durationMs;
      return ch;
    });

    fs.writeFileSync(chaptersPath, JSON.stringify(chapters, null, 2), 'utf-8');

    return {
      exporterId: this.id,
      outputPath,
      format: 'mp3',
      durationMs: currentOffsetMs,
      metadata: {
        chaptersPath,
        chapterCount: chapters.length,
      },
    };
  }
}
