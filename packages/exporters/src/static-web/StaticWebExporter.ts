import fs from 'fs';
import path from 'path';
import type { PipelineIR } from '@acc/ir';
import type { IExporter, ExportOptions, ExportResult } from '../base/BaseExporter';

export class StaticWebExporter implements IExporter {
  public readonly id = 'static-web';

  public async export(ir: PipelineIR, options: ExportOptions = {}): Promise<ExportResult> {
    const outDir = options.outputDir || path.resolve(process.cwd(), 'autogenerated', 'exports', 'web');
    if (!fs.existsSync(outDir)) {
      fs.mkdirSync(outDir, { recursive: true });
    }

    const prefix = options.fileNamePrefix || ir.metadata.jobId || 'post';
    const mdPath = path.join(outDir, `${prefix}.md`);
    const jsonPath = path.join(outDir, `${prefix}.json`);

    // 1. Generate Markdown with Frontmatter
    let md = `---\n`;
    md += `title: "${ir.metadata.title.replace(/"/g, '\\"')}"\n`;
    md += `date: ${ir.metadata.createdAt}\n`;
    md += `tags: [${ir.metadata.tags.map((t) => `"${t}"`).join(', ')}]\n`;
    md += `pipelineId: "${ir.pipelineId}"\n`;
    md += `---\n\n`;

    md += `# ${ir.metadata.title}\n\n`;

    ir.chunks.forEach((chunk, index) => {
      md += `### ${index + 1}. Key Insight\n\n`;
      if (chunk.summary) {
        md += `> **TL;DR:** ${chunk.summary}\n\n`;
      }
      if (chunk.text) {
        md += `${chunk.text}\n\n`;
      }
    });

    if (ir.structuredData && Object.keys(ir.structuredData).length > 0) {
      md += `## Data Specifications\n\n\`\`\`json\n${JSON.stringify(ir.structuredData, null, 2)}\n\`\`\`\n\n`;
    }

    fs.writeFileSync(mdPath, md, 'utf-8');

    // 2. Generate JSON API payload
    fs.writeFileSync(jsonPath, JSON.stringify(ir, null, 2), 'utf-8');

    return {
      exporterId: this.id,
      outputPath: [mdPath, jsonPath],
      format: 'markdown+json',
      metadata: {
        markdownPath: mdPath,
        jsonPath,
      },
    };
  }
}
