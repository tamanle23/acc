import fs from 'fs';
import path from 'path';
import type {
  IMediaAssetProberHandler,
  DiscoveredAssetManifest,
  ProberScanOptions,
} from './types';
import { ImageProberHandler } from './probers/ImageProberHandler';
import { VideoProberHandler } from './probers/VideoProberHandler';
import { AudioProberHandler } from './probers/AudioProberHandler';
import { ScriptProberHandler } from './probers/ScriptProberHandler';
import { DataProberHandler } from './probers/DataProberHandler';

const DEFAULT_IGNORE_DIRS = new Set([
  'node_modules',
  '.git',
  'dist',
  'output',
  'build',
  '.turbo',
  '.venv',
  '__pycache__',
  'autogenerated',
]);

function naturalSort(a: string, b: string): number {
  return a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' });
}

export class MediaAssetProberChain {
  private rootHandler: IMediaAssetProberHandler;

  constructor(customRootHandler?: IMediaAssetProberHandler) {
    this.rootHandler = customRootHandler || MediaAssetProberChain.buildDefaultChain();
  }

  public static createDefault(): MediaAssetProberChain {
    return new MediaAssetProberChain();
  }

  public static buildDefaultChain(): IMediaAssetProberHandler {
    const imageProber = new ImageProberHandler();
    const videoProber = new VideoProberHandler();
    const audioProber = new AudioProberHandler();
    const scriptProber = new ScriptProberHandler();
    const dataProber = new DataProberHandler();

    imageProber
      .setNext(videoProber)
      .setNext(audioProber)
      .setNext(scriptProber)
      .setNext(dataProber);

    return imageProber;
  }

  public async probeDirectory(
    dirPath: string,
    options: ProberScanOptions = {}
  ): Promise<DiscoveredAssetManifest> {
    const resolvedBase = path.resolve(dirPath);
    if (!fs.existsSync(resolvedBase)) {
      throw new Error(`[MediaAssetProberChain] Target directory does not exist: ${resolvedBase}`);
    }

    const manifest: DiscoveredAssetManifest = {
      baseDir: resolvedBase,
      scannedAt: Date.now(),
      visuals: [],
      audio: [],
      scripts: [],
      data: [],
      pairedPairs: [],
      suggestedTitle: path.basename(resolvedBase).replace(/[-_]/g, ' '),
      totalVisualCount: 0,
      totalAudioCount: 0,
      hasVoiceover: false,
      hasBackgroundMusic: false,
    };

    const filesToProbe: string[] = [];
    const ignoreSet = new Set(
      (options.ignoreDirectories || []).concat(Array.from(DEFAULT_IGNORE_DIRS))
    );

    const crawl = (currentDir: string) => {
      const entries = fs.readdirSync(currentDir, { withFileTypes: true });
      for (const entry of entries) {
        if (entry.isDirectory()) {
          if (!ignoreSet.has(entry.name)) {
            crawl(path.join(currentDir, entry.name));
          }
        } else if (entry.isFile()) {
          filesToProbe.push(path.join(currentDir, entry.name));
        }
      }
    };

    crawl(resolvedBase);

    // Sort files naturally before probing
    filesToProbe.sort(naturalSort);

    // Process all files through the Chain of Responsibility
    for (const filePath of filesToProbe) {
      await this.rootHandler.handle(filePath, resolvedBase, manifest, options);
    }

    // ─── Post-Processing & Semantic Pairings ─────────────────────────────
    manifest.visuals.sort((a, b) => naturalSort(a.relativePath, b.relativePath));
    manifest.audio.sort((a, b) => naturalSort(a.relativePath, b.relativePath));
    manifest.totalVisualCount = manifest.visuals.length;
    manifest.totalAudioCount = manifest.audio.length;

    manifest.hasBackgroundMusic = manifest.audio.some((a) => a.classification === 'music');
    manifest.hasVoiceover = manifest.audio.some((a) => a.classification === 'voiceover');

    // Calculate dominant visual aspect ratio
    const aspectCounts: Record<string, number> = {};
    for (const vis of manifest.visuals) {
      if (vis.aspectRatio && vis.aspectRatio !== 'custom') {
        aspectCounts[vis.aspectRatio] = (aspectCounts[vis.aspectRatio] || 0) + 1;
      }
    }
    const dominant = Object.entries(aspectCounts).sort((a, b) => b[1] - a[1])[0];
    if (dominant) {
      manifest.dominantVisualAspect = dominant[0] as '9:16' | '16:9' | '1:1';
    }

    // Attempt intelligent 1-to-1 pairings between Visuals and Voiceovers/Scripts
    const voiceovers = manifest.audio.filter((a) => a.classification === 'voiceover');
    const primaryScript = manifest.scripts[0];

    const maxItems = Math.max(manifest.visuals.length, voiceovers.length);
    for (let i = 0; i < maxItems; i++) {
      const visual = manifest.visuals[i];
      // Try to match voiceover by numeric basename or index
      let audio = voiceovers[i];
      if (visual) {
        const visualNum = visual.baseName.replace(/\D/g, '');
        if (visualNum) {
          const directNumMatch = voiceovers.find(
            (v) => v.baseName.replace(/\D/g, '') === visualNum
          );
          if (directNumMatch) audio = directNumMatch;
        }
      }

      const scriptText = primaryScript?.lines?.[i];

      manifest.pairedPairs.push({
        index: i + 1,
        visual,
        audio,
        scriptText,
      });
    }

    return manifest;
  }
}
