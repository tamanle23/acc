export interface Depth3DSceneOptions {
  scene: ResolvedSceneConfig;
  duration: number;
  assPath: string | null;
  config: ResolvedStoryConfig;
  outputPath: string;
  fallbackAudioPath?: string;
  paddingTime?: number;
  useHighQualityIntermediate?: boolean;
}

export async function getStoryRootAndCacheDir(
  resolvedImagePath: string,
): Promise<{ storyRoot: string; depthCacheDir: string }> {
  let currDir = path.dirname(resolvedImagePath);
  let storyRoot = currDir;

  for (let i = 0; i < 3; i++) {
    if (await checkExists(path.join(currDir, "story-config.json"))) {
      storyRoot = currDir;
      break;
    }
    const parent = path.dirname(currDir);
    if (parent === currDir) break;
    currDir = parent;
  }

  const depthCacheDir = path.join(storyRoot, "autogenerated", "depth-3d");
  if (!(await checkExists(depthCacheDir))) {
    try {
      await fs.promises.mkdir(depthCacheDir, { recursive: true });
    } catch {}
  }

  return { storyRoot, depthCacheDir };
}

/**
 * Unified Runner for all 3D Depth & Visual Pop-Out rendering engines.
 * Supports: 'frame_breaker', 'parallax_25d', 'volumetric_sandwich', 'depth_map_3d', 'wigglegram'.
 */
export async function renderDepth3DScene(
  options: Depth3DSceneOptions,
): Promise<{ path: string; duration: number }> {
  const {
    scene,
    duration,
    assPath,
    config,
    outputPath,
    fallbackAudioPath,
    paddingTime = 0,
    useHighQualityIntermediate = false,
  } = options;
  const { width, height, fps, captions, container } = config.settings;
  const depthConfig: Depth3DConfig = scene.depth3d ||
    config.settings.depth3d || { enabled: true, mode: "frame_breaker" };
  const mode = depthConfig.mode || "frame_breaker";

  const totalDuration = duration + paddingTime;
  const totalFrames = Math.ceil(fps * totalDuration);

  // 1. Load primary image and optional subject cutout safely
  const imgBuffer = await fs.promises.readFile(scene.resolvedImage);
  const img = await loadImage(imgBuffer);
  let subjectImg: Image | null = null;
  let subjectBBox: any = null;
  const shouldAutoSegment =
    depthConfig.autoSegment !== undefined
      ? depthConfig.autoSegment
      : mode === "frame_breaker" ||
        mode === "volumetric_sandwich" ||
        mode === "sandwich";

  const sceneDir = path.dirname(scene.resolvedImage);
  const { storyRoot, depthCacheDir } = await getStoryRootAndCacheDir(
    scene.resolvedImage,
  );
  const baseName = path.parse(scene.resolvedImage).name;
  const imageChecksum = crypto
    .createHash("md5")
    .update(imgBuffer)
    .digest("hex")
    .slice(0, 8);
  const segContext = SubjectSegmentationContext.getInstance();
  const segStratName = segContext
    .getActiveStrategyName()
    .replace(/[^a-zA-Z0-9_-]/g, "_");

  let resolvedSubPath: string | null = null;
  // A. Explicit user configuration in story-config takes precedence
  if (depthConfig.subjectImage) {
    const candidate = path.isAbsolute(depthConfig.subjectImage)
      ? depthConfig.subjectImage
      : path.resolve(sceneDir, depthConfig.subjectImage);
    if (await checkExists(candidate)) {
      resolvedSubPath = candidate;
    } else {
      const rootCandidate = path.resolve(storyRoot, depthConfig.subjectImage);
      if (await checkExists(rootCandidate)) resolvedSubPath = rootCandidate;
      else {
        const cacheCandidate = path.resolve(
          depthCacheDir,
          depthConfig.subjectImage,
        );
        if (await checkExists(cacheCandidate)) resolvedSubPath = cacheCandidate;
      }
    }
  }

  // B. Strategy & content-checksum specific cache hit in autogenerated/depth-3d
  if (!resolvedSubPath) {
    const stratCandidate = path.resolve(
      depthCacheDir,
      `${baseName}_subject_${segStratName}_${imageChecksum}.png`,
    );
    if (await checkExists(stratCandidate)) {
      resolvedSubPath = stratCandidate;
    }
  }

  // C. Fallback checksum candidate in autogenerated/depth-3d
  if (!resolvedSubPath) {
    const checksumCandidate = path.resolve(
      depthCacheDir,
      `${baseName}_subject_${imageChecksum}.png`,
    );
    if (await checkExists(checksumCandidate)) {
      resolvedSubPath = checksumCandidate;
    }
  }

  // D. Base subject candidate in autogenerated/depth-3d
  if (!resolvedSubPath) {
    const baseCandidate = path.resolve(
      depthCacheDir,
      `${baseName}_subject.png`,
    );
    if (await checkExists(baseCandidate)) {
      resolvedSubPath = baseCandidate;
    }
  }

  // E. Backward-compatibility candidates in sceneDir or storyRoot
  if (!resolvedSubPath) {
    const legacyCandidates = [
      path.resolve(
        sceneDir,
        `${baseName}_subject_${segStratName}_${imageChecksum}.png`,
      ),
      path.resolve(sceneDir, `${baseName}_subject_${imageChecksum}.png`),
      path.resolve(sceneDir, `${baseName}_subject.png`),
      path.resolve(
        storyRoot,
        `${baseName}_subject_${segStratName}_${imageChecksum}.png`,
      ),
      path.resolve(storyRoot, `${baseName}_subject_${imageChecksum}.png`),
      path.resolve(storyRoot, `${baseName}_subject.png`),
    ];
    for (const cand of legacyCandidates) {
      if (await checkExists(cand)) {
        resolvedSubPath = cand;
        break;
      }
    }
  }

  if (resolvedSubPath) {
    try {
      subjectImg = await loadImage(await fs.promises.readFile(resolvedSubPath));
      // Check for companion bbox json
      const jsonCandidate = resolvedSubPath.replace(/\.png$/i, ".json");
      if (await checkExists(jsonCandidate)) {
        try {
          const meta = JSON.parse(
            await fs.promises.readFile(jsonCandidate, "utf-8"),
          );
          if (meta.boundingBox) subjectBBox = meta.boundingBox;
        } catch {}
      }
    } catch {}
  } else if (shouldAutoSegment && scene.resolvedImage) {
    try {
      const segRes = await segContext.segment(imgBuffer);
      if (segRes && segRes.maskRgbaBuffer && segRes.maskRgbaBuffer.length > 0) {
        subjectImg = await loadImage(segRes.maskRgbaBuffer);
        subjectBBox = segRes.boundingBox;
        // Persist cached cutout with checksum, strategy name and companion bbox JSON into autogenerated/depth-3d
        const cachePath = path.resolve(
          depthCacheDir,
          `${baseName}_subject_${segStratName}_${imageChecksum}.png`,
        );
        const metaPath = path.resolve(
          depthCacheDir,
          `${baseName}_subject_${segStratName}_${imageChecksum}.json`,
        );
        try {
          await fs.promises.writeFile(cachePath, segRes.maskRgbaBuffer);
          await fs.promises.writeFile(
            metaPath,
            JSON.stringify(
              { boundingBox: segRes.boundingBox, strategy: segStratName },
              null,
              2,
            ),
          );
        } catch {}
      }
    } catch {}
  }

  // 2. Setup Mode-Specific Pre-Allocated Data Structures
  let bgImg: Image | null = null;
  let particles: any[] = [];
  let dustParticles: any[] = [];
  let srcCanvas: Canvas | null = null;
  let depthData: Uint8ClampedArray | null = null;
  let gridX = 32;
  let gridY = 18;
  let cellW = width / gridX;
  let cellH = height / gridY;
  let baseCanvas: Canvas | null = null;
  let bgCanvas: Canvas | null = null;
  let depthLayers: any = null;

  if (mode === "parallax_25d" || mode === "parallax_dolly") {
    if (
      depthConfig.parallax?.backgroundImage &&
      (await checkExists(depthConfig.parallax.backgroundImage))
    ) {
      try {
        bgImg = await loadImage(depthConfig.parallax.backgroundImage);
      } catch {}
    }
    particles = Array.from({ length: 28 }, (_, i) => ({
      x: (Math.sin(i * 99) * 0.5 + 0.5) * width,
      y: (Math.cos(i * 33) * 0.5 + 0.5) * height,
      size: 3 + (i % 6) * 3,
      speedX: (0.4 + (i % 3) * 0.3) * (i % 2 === 0 ? 1 : -1),
      speedY: -0.5 - (i % 4) * 0.4,
      opacity: 0.2 + (i % 5) * 0.12,
      pulseSpeed: 1.5 + (i % 3),
    }));
  } else if (mode === "volumetric_sandwich" || mode === "sandwich") {
    dustParticles = Array.from({ length: 35 }, (_, i) => ({
      x: (Math.sin(i * 47) * 0.5 + 0.5) * width,
      y: (Math.cos(i * 83) * 0.5 + 0.5) * height,
      size: 2 + (i % 4) * 2,
      speedX: (0.2 + (i % 3) * 0.2) * (i % 2 === 0 ? 1 : -1),
      speedY: -0.3 - (i % 3) * 0.2,
      opacity: 0.15 + (i % 4) * 0.1,
    }));
  } else if (mode === "depth_map_3d" || mode === "mesh_displacement") {
    srcCanvas = createCanvas(width, height);
    const sCtx = srcCanvas.getContext("2d");
    drawImageCover(sCtx, img, 0, 0, width, height);

    const dCanvas = createCanvas(width, height);
    const dCtx = dCanvas.getContext("2d");

    const depthContext = DepthEstimationContext.getInstance();
    const depthStratName = depthContext
      .getActiveStrategyName()
      .replace(/[^a-zA-Z0-9_-]/g, "_");
    let loadedDepth = false;

    if (depthConfig.depthMesh?.depthMapPath) {
      const candidateDm = path.isAbsolute(depthConfig.depthMesh.depthMapPath)
        ? depthConfig.depthMesh.depthMapPath
        : path.resolve(sceneDir, depthConfig.depthMesh.depthMapPath);
      if (await checkExists(candidateDm)) {
        try {
          const dm = await loadImage(await fs.promises.readFile(candidateDm));
          drawImageCover(dCtx, dm, 0, 0, width, height);
          loadedDepth = true;
        } catch {}
      } else {
        const rootCandidateDm = path.resolve(
          storyRoot,
          depthConfig.depthMesh.depthMapPath,
        );
        if (await checkExists(rootCandidateDm)) {
          try {
            const dm = await loadImage(
              await fs.promises.readFile(rootCandidateDm),
            );
            drawImageCover(dCtx, dm, 0, 0, width, height);
            loadedDepth = true;
          } catch {}
        } else {
          const cacheCandidateDm = path.resolve(
            depthCacheDir,
            depthConfig.depthMesh.depthMapPath,
          );
          if (await checkExists(cacheCandidateDm)) {
            try {
              const dm = await loadImage(
                await fs.promises.readFile(cacheCandidateDm),
              );
              drawImageCover(dCtx, dm, 0, 0, width, height);
              loadedDepth = true;
            } catch {}
          }
        }
      }
    }

    // Strategy & content-checksum specific depth cache hit in autogenerated/depth-3d
    if (!loadedDepth) {
      const stratDepthCandidate = path.resolve(
        depthCacheDir,
        `${baseName}_depth_${depthStratName}_${imageChecksum}.png`,
      );
      if (await checkExists(stratDepthCandidate)) {
        try {
          const dm = await loadImage(
            await fs.promises.readFile(stratDepthCandidate),
          );
          drawImageCover(dCtx, dm, 0, 0, width, height);
          loadedDepth = true;
        } catch {}
      }
    }

    // Checksum candidate in autogenerated/depth-3d
    if (!loadedDepth) {
      const checksumDepthCandidate = path.resolve(
        depthCacheDir,
        `${baseName}_depth_${imageChecksum}.png`,
      );
      if (await checkExists(checksumDepthCandidate)) {
        try {
          const dm = await loadImage(
            await fs.promises.readFile(checksumDepthCandidate),
          );
          drawImageCover(dCtx, dm, 0, 0, width, height);
          loadedDepth = true;
        } catch {}
      }
    }

    // Legacy fallback candidates in sceneDir or storyRoot
    if (!loadedDepth) {
      const legacyDepthCandidates = [
        path.resolve(
          sceneDir,
          `${baseName}_depth_${depthStratName}_${imageChecksum}.png`,
        ),
        path.resolve(sceneDir, `${baseName}_depth_${imageChecksum}.png`),
        path.resolve(sceneDir, `${baseName}_depth.png`),
        path.resolve(
          storyRoot,
          `${baseName}_depth_${depthStratName}_${imageChecksum}.png`,
        ),
        path.resolve(storyRoot, `${baseName}_depth_${imageChecksum}.png`),
        path.resolve(storyRoot, `${baseName}_depth.png`),
      ];
      for (const cand of legacyDepthCandidates) {
        if (await checkExists(cand)) {
          try {
            const dm = await loadImage(await fs.promises.readFile(cand));
            drawImageCover(dCtx, dm, 0, 0, width, height);
            loadedDepth = true;
            break;
          } catch {}
        }
      }
    }

    if (!loadedDepth && depthConfig.autoDepth && scene.resolvedImage) {
      try {
        const depthRes = await depthContext.estimateDepth(imgBuffer);
        if (
          depthRes &&
          depthRes.depth16Buffer &&
          depthRes.depth16Buffer.length > 0
        ) {
          const dm = await loadImage(depthRes.depth16Buffer);
          drawImageCover(dCtx, dm, 0, 0, width, height);
          loadedDepth = true;
          // Persist cached depth map with checksum and strategy name into autogenerated/depth-3d
          const cacheDepthPath = path.resolve(
            depthCacheDir,
            `${baseName}_depth_${depthStratName}_${imageChecksum}.png`,
          );
          try {
            await fs.promises.writeFile(cacheDepthPath, depthRes.depth16Buffer);
          } catch {}
        }
      } catch {}
    }

    if (!loadedDepth) {
      const radGrad = dCtx.createRadialGradient(
        width / 2,
        height * 0.52,
        width * 0.05,
        width / 2,
        height * 0.52,
        width * 0.65,
      );
      radGrad.addColorStop(0, "rgb(255, 255, 255)");
      radGrad.addColorStop(0.5, "rgb(180, 180, 180)");
      radGrad.addColorStop(1, "rgb(30, 30, 30)");
      dCtx.fillStyle = radGrad;
      dCtx.fillRect(0, 0, width, height);
    }

    // Build Continuous Multi-Plane Depth Layers (Zero grid tearing)
    try {
      const depthDataFull = dCtx.getImageData(0, 0, width, height).data;
      const srcDataFull = sCtx.getImageData(0, 0, width, height).data;

      const mgCanvas = createCanvas(width, height);
      const mgCtx = mgCanvas.getContext("2d");
      const mgImgData = mgCtx.createImageData(width, height);
      const mgData = mgImgData.data;

      const fgCanvas = createCanvas(width, height);
      const fgCtx = fgCanvas.getContext("2d");
      const fgImgData = fgCtx.createImageData(width, height);
      const fgData = fgImgData.data;

      for (let i = 0; i < depthDataFull.length; i += 4) {
        const d = depthDataFull[i] / 255.0; // 0 (far) to 1 (near)
        const r = srcDataFull[i];
        const g = srcDataFull[i + 1];
        const b = srcDataFull[i + 2];

        // Midground layer: soft bell curve around 0.30 - 0.70
        let mgAlpha = 0;
        if (d >= 0.25 && d <= 0.75) {
          mgAlpha = Math.sin(((d - 0.25) / 0.5) * Math.PI) * 255;
        }
        mgData[i] = r;
        mgData[i + 1] = g;
        mgData[i + 2] = b;
        mgData[i + 3] = mgAlpha;

        // Foreground subject layer: depth > 0.48
        let fgAlpha = 0;
        if (d > 0.48) {
          fgAlpha = Math.min(255, ((d - 0.48) / 0.35) * 255);
        }
        fgData[i] = r;
        fgData[i + 1] = g;
        fgData[i + 2] = b;
        fgData[i + 3] = fgAlpha;
      }

      mgCtx.putImageData(mgImgData, 0, 0);
      fgCtx.putImageData(fgImgData, 0, 0);

      depthLayers = {
        bgCanvas: srcCanvas,
        mgCanvas,
        fgCanvas,
      };
    } catch {
      depthLayers = { bgCanvas: srcCanvas };
    }
  } else if (mode === "wigglegram") {
    baseCanvas = createCanvas(width, height);
    const bCtx = baseCanvas.getContext("2d");
    drawImageCover(bCtx, img, 0, 0, width, height);
  } else if (mode === "frame_breaker") {
    bgCanvas = createCanvas(width, height);
    const bgCtx = bgCanvas.getContext("2d");

    // Fill canvas with deep cinematic dark backdrop
    bgCtx.fillStyle = "#06060c";
    bgCtx.fillRect(0, 0, width, height);

    // Compute letterbox / pillarbox bounds strictly preserving original image aspect ratio
    const imgRatio = img.width / img.height;
    const canvasRatio = width / height;
    let bgW = width;
    let bgH = height;
    let bgX = 0;
    let bgY = 0;

    if (imgRatio > canvasRatio) {
      bgW = width;
      bgH = width / imgRatio;
      bgY = (height - bgH) / 2;
    } else {
      bgH = height;
      bgW = height * imgRatio;
      bgX = (width - bgW) / 2;
    }

    // Draw uncropped source image plate in exact original aspect ratio
    bgCtx.drawImage(img, 0, 0, img.width, img.height, bgX, bgY, bgW, bgH);
    bgCtx.fillStyle = "rgba(10, 10, 18, 0.65)";
    bgCtx.fillRect(bgX, bgY, bgW, bgH);
  }

  // 3. Setup Canvas and Zero-Copy FFIVideoEncoder Pipeline
  const canvas = createCanvas(width, height);
  const ctx = canvas.getContext("2d");

  const { FFIVideoEncoder } = await import("@acc/core");
  const audioInput = scene.resolvedAudio || fallbackAudioPath;
  const encoder = new FFIVideoEncoder(
    width,
    height,
    fps,
    outputPath,
    20,
    audioInput,
  );

  const renderPromise = new Promise<{ path: string; duration: number }>(
    async (resolve, reject) => {
      try {
        encoder.initialize();

        const timeline = new TimelineEngine();
        if (scene.captions && scene.captions.length > 0) {
          timeline.addTrack({
            id: 'subtitles',
            type: 'caption',
            items: scene.captions,
            strategy: new BoundedAcousticCaptionStrategy(),
            duration: totalDuration,
          });
        }

        // 4. Render and stream frames via FFI
        for (let frame = 0; frame < totalFrames; frame++) {
          const progress = frame / totalFrames;
          const timeSec = frame / fps;

          ctx.clearRect(0, 0, width, height);

          const renderer = Depth3DFactory.getRenderer(mode);
          renderer.renderFrame(ctx, {
            img,
            subjectImg,
            subjectBBox,
            bgImg,
            bgCanvas,
            srcCanvas,
            baseCanvas,
            depthLayers,
            width,
            height,
            frame,
            totalFrames,
            timeSec,
            progress,
            depthConfig,
            captions: scene.captions,
            particles,
            dustParticles,
          });

          // Draw Canvas Subtitles / Captions via SSOT TimelineEngine
          if (scene.captions && scene.captions.length > 0) {
            const snapshot = timeline.getTrackState<CaptionTrackSnapshot>(
              'subtitles',
              timeSec,
              config.settings.captions
            );
            drawCanvasCaptionsFromSnapshot(
              ctx,
              snapshot,
              config.settings.captions,
              width,
              height,
              config.settings.platform as any
            );
          }

          // ZERO-COPY FFI INGESTION
          const buffer = canvas.data();
          encoder.encodeRgbaFrame(buffer);

          // Periodic yield to allow event loop & GC reclamation of dereferenced frames
          if (frame % 15 === 0) {
            if (typeof Bun !== "undefined" && (Bun as any).gc) {
              (Bun as any).gc(true);
            }
            await new Promise((r) => setTimeout(r, 0));
          }
        }

        encoder.close();

        // Note: In Phase 4/5, audio remuxing would happen here via FFI Muxer
        // For now, video is fully encoded without spawn or fluent-ffmpeg!

        resolve({ path: outputPath, duration: totalDuration });
      } catch (err: any) {
        reject(
          new Error(`FFI Render 3D Depth (${mode}) failed: ${err.message}`),
        );
      }
    },
  );

  return renderPromise;
}

/**
 * Resolves cached or auto-segmented subject cutout image and bounding box for a given image path.
 */
export async function resolveSubjectCutout(
  imagePath: string,
  depthConfig?: Depth3DConfig
): Promise<{ subjectImg: Image | null; subjectBBox: any | null }> {
  try {
    const imgBuffer = await fs.promises.readFile(imagePath);
    const { storyRoot, depthCacheDir } = await getStoryRootAndCacheDir(imagePath);
    const sceneDir = path.dirname(imagePath);
    const baseName = path.parse(imagePath).name;
    const imageChecksum = crypto.createHash("md5").update(imgBuffer).digest("hex").slice(0, 8);
    const segContext = SubjectSegmentationContext.getInstance();
    const segStratName = segContext.getActiveStrategyName().replace(/[^a-zA-Z0-9_-]/g, "_");

    let resolvedSubPath: string | null = null;
    if (depthConfig?.subjectImage) {
      const candidate = path.isAbsolute(depthConfig.subjectImage)
        ? depthConfig.subjectImage
        : path.resolve(sceneDir, depthConfig.subjectImage);
      if (await checkExists(candidate)) resolvedSubPath = candidate;
      else {
        const rootCand = path.resolve(storyRoot, depthConfig.subjectImage);
        if (await checkExists(rootCand)) resolvedSubPath = rootCand;
        else {
          const cacheCand = path.resolve(depthCacheDir, depthConfig.subjectImage);
          if (await checkExists(cacheCand)) resolvedSubPath = cacheCand;
        }
      }
    }

    if (!resolvedSubPath) {
      const candidates = [
        path.resolve(depthCacheDir, `${baseName}_subject_${segStratName}_${imageChecksum}.png`),
        path.resolve(depthCacheDir, `${baseName}_subject_${imageChecksum}.png`),
        path.resolve(depthCacheDir, `${baseName}_subject.png`),
        path.resolve(sceneDir, `${baseName}_subject.png`),
        path.resolve(storyRoot, `${baseName}_subject.png`),
      ];
      for (const cand of candidates) {
        if (await checkExists(cand)) {
          resolvedSubPath = cand;
          break;
        }
      }
    }

    if (resolvedSubPath) {
      const subjectImg = await loadImage(await fs.promises.readFile(resolvedSubPath));
      let subjectBBox: any = null;
      const jsonCandidate = resolvedSubPath.replace(/\.png$/i, ".json");
      if (await checkExists(jsonCandidate)) {
        try {
          const meta = JSON.parse(await fs.promises.readFile(jsonCandidate, "utf-8"));
          if (meta.boundingBox) subjectBBox = meta.boundingBox;
        } catch {}
      }
      return { subjectImg, subjectBBox };
    }
  } catch {}

  return { subjectImg: null, subjectBBox: null };
}
