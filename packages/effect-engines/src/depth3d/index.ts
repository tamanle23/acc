export async function checkExists(p: string): Promise<boolean> {
  if (typeof process !== "undefined" && process.versions?.node) {
    try {
      const fs = require("fs");
      await fs.promises.access(p, fs.constants.F_OK);
      return true;
    } catch {
      return false;
    }
  }
  return ContentCacheRegistry.get().has(p);
}

