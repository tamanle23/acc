export interface Depth3DSceneOptions {
  scene: ResolvedSceneConfig;
  duration: number;
  assPath: string | null;
  config: ResolvedStoryConfig;
  outputPath: string;
  fallbackAudioPath?: string;
  paddingTime?: number;
  useHighQualityIntermediate?: boolean;
  sink?: IMediaFrameSink;
}

async function getStoryRootAndCacheDir(
  resolvedImagePath: string,
): Promise<{ storyRoot: string; depthCacheDir: string }> {
  let storyRoot = ".";
  let depthCacheDir = "autogenerated/depth-3d";

  if (typeof process !== "undefined" && process.versions?.node) {
    try {
      const path = require("path");
      const fs = require("fs");
      let currDir = path.dirname(resolvedImagePath);
      for (let i = 0; i < 5; i++) {
        if (await checkExists(path.join(currDir, "story-config.json"))) {
          storyRoot = currDir;
          break;
        }
        const parent = path.dirname(currDir);
        if (parent === currDir) break;
        currDir = parent;
      }

      if (!(await checkExists(path.join(storyRoot, "story-config.json")))) {
        if (await checkExists(path.join(process.cwd(), "story-config.json"))) {
          storyRoot = process.cwd();
        }
      }

      depthCacheDir = path.join(storyRoot, "autogenerated", "depth-3d");
      if (!(await checkExists(depthCacheDir))) {
        try {
          await fs.promises.mkdir(depthCacheDir, { recursive: true });
        } catch {}
      }
    } catch {}
  }

  return { storyRoot, depthCacheDir };
}

/**
 * Unified Runner for all 3D Depth & Visual Pop-Out rendering engines.
 * Pure isomorphic execution leveraging MediaEngineRegistry, ContentCacheRegistry, and UniversalCanvasProvider.
 */
export async function renderDepth3DScene(
  options: Depth3DSceneOptions,
): Promise<{ path: string; duration: number }> {
  const {
    scene,
    duration,
    config,
    outputPath,
    fallbackAudioPath,
    paddingTime = 0,
  } = options;
  const { width, height, fps } = config.settings;
  const depthConfig: Depth3DConfig = scene.depth3d ||
    config.settings.depth3d || { enabled: true, mode: "frame_breaker" };
  const mode = depthConfig.mode || "frame_breaker";

  const totalDuration = duration + paddingTime;
  const totalFrames = Math.ceil(fps * totalDuration);

  // 1. Read input image buffer isomorphically
  let imgBuffer: Uint8Array;
  if (typeof process !== "undefined" && process.versions?.node) {
    const fs = require("fs");
    imgBuffer = await fs.promises.readFile(scene.resolvedImage);
  } else {
    const cache = ContentCacheRegistry.get();
    const cached = await cache.get(scene.resolvedImage);
    if (!cached) {
      throw new Error(`[renderDepth3DScene] Asset not found in cache: ${scene.resolvedImage}`);
    }
    imgBuffer = cached;
  }

  const img = await CanvasAssetLoader.loadImage(imgBuffer);
  let subjectImg: any | null = null;
  let subjectBBox: any = null;
  const shouldAutoSegment =
    depthConfig.autoSegment !== undefined
      ? depthConfig.autoSegment
      : mode === "frame_breaker" ||
        mode === "volumetric_sandwich" ||
        mode === "sandwich";

  const { storyRoot, depthCacheDir } = await getStoryRootAndCacheDir(scene.resolvedImage);
  const imageChecksum = fastChecksum(imgBuffer);
  const segContext = SubjectSegmentationContext.getInstance();
  const segStratName = segContext
    .getActiveStrategyName()
    .replace(/[^a-zA-Z0-9_-]/g, "_");

  // Load subject cutout if available
  try {
    const cutoutRes = await resolveSubjectCutout(scene.resolvedImage, depthConfig);
    if (cutoutRes.subjectImg) {
      subjectImg = cutoutRes.subjectImg;
      subjectBBox = cutoutRes.subjectBBox;
    }
  } catch {}

  // Auto-segmentation fallback
  if (!subjectImg && shouldAutoSegment) {
    try {
      const segRes = await segContext.segmentSubject(imgBuffer);
      if (segRes && segRes.maskRgbaBuffer) {
        subjectImg = await CanvasAssetLoader.loadImage(segRes.maskRgbaBuffer);
        subjectBBox = segRes.boundingBox;
      }
    } catch {}
  }

  // 2. Setup Mode-Specific Canvas Layers
  let bgImg: any | null = null;
  let particles: any[] = [];
  let dustParticles: any[] = [];
  let srcCanvas: ICanvasInstance | any | null = null;
  let depthLayers: any = null;

  if (mode === "parallax_25d" || mode === "parallax_dolly") {
    particles = Array.from({ length: 28 }, (_, i) => ({
      x: (Math.sin(i * 99) * 0.5 + 0.5) * width,
      y: (Math.cos(i * 33) * 0.5 + 0.5) * height,
      size: 3 + (i % 6) * 3,
      speedX: (0.4 + (i % 3) * 0.3) * (i % 2 === 0 ? 1 : -1),
      speedY: -0.5 - (i % 4) * 0.4,
      opacity: 0.2 + (i % 5) * 0.15,
      layer: i % 3,
      parallaxFactor: 0.15 + (i % 4) * 0.1,
    }));
  }

  // Depth-3D Depth Map loading
  let loadedDepth = false;
  const dCanvas = UniversalCanvasProvider.createCanvas(width, height);
  const dCtx = dCanvas.getContext("2d");

  const sCanvas = UniversalCanvasProvider.createCanvas(width, height);
  const sCtx = sCanvas.getContext("2d");
  drawImageCover(sCtx, img, 0, 0, width, height);

  const depthContext = DepthEstimationContext.getInstance();
  const depthStratName = depthContext.getActiveStrategyName().replace(/[^a-zA-Z0-9_-]/g, "_");

  if (!loadedDepth && depthConfig.autoDepth) {
    try {
      const depthRes = await depthContext.estimateDepth(imgBuffer);
      if (depthRes && depthRes.depth16Buffer && depthRes.depth16Buffer.length > 0) {
        const dm = await CanvasAssetLoader.loadImage(depthRes.depth16Buffer);
        drawImageCover(dCtx, dm, 0, 0, width, height);
        loadedDepth = true;
      }
    } catch {}
  }

  if (!loadedDepth) {
    const radGrad = dCtx.createRadialGradient(
      width / 2,
      height * 0.52,
      width * 0.05,
      width / 2,
      height * 0.52,
      width * 0.65,
    );
    radGrad.addColorStop(0, "rgb(255, 255, 255)");
    radGrad.addColorStop(0.5, "rgb(180, 180, 180)");
    radGrad.addColorStop(1, "rgb(30, 30, 30)");
    dCtx.fillStyle = radGrad;
    dCtx.fillRect(0, 0, width, height);
  }

  // Build Continuous Multi-Plane Depth Layers
  try {
    const depthDataFull = dCtx.getImageData(0, 0, width, height).data;
    const srcDataFull = sCtx.getImageData(0, 0, width, height).data;

    const mgCanvas = UniversalCanvasProvider.createCanvas(width, height);
    const mgCtx = mgCanvas.getContext("2d");
    const mgImgData = mgCtx.createImageData(width, height);
    const mgData = mgImgData.data;

    const fgCanvas = UniversalCanvasProvider.createCanvas(width, height);
    const fgCtx = fgCanvas.getContext("2d");
    const fgImgData = fgCtx.createImageData(width, height);
    const fgData = fgImgData.data;

    const bgC = UniversalCanvasProvider.createCanvas(width, height);
    const bgCctx = bgC.getContext("2d");
    const bgImgData = bgCctx.createImageData(width, height);
    const bgData = bgImgData.data;

    const totalPixels = width * height;
    for (let p = 0; p < totalPixels; p++) {
      const idx = p * 4;
      const dVal = depthDataFull[idx];
      const r = srcDataFull[idx];
      const g = srcDataFull[idx + 1];
      const b = srcDataFull[idx + 2];
      const a = srcDataFull[idx + 3];

      if (dVal < 90) {
        bgData[idx] = r;
        bgData[idx + 1] = g;
        bgData[idx + 2] = b;
        bgData[idx + 3] = a;
      } else if (dVal < 170) {
        mgData[idx] = r;
        mgData[idx + 1] = g;
        mgData[idx + 2] = b;
        mgData[idx + 3] = a;
      } else {
        fgData[idx] = r;
        fgData[idx + 1] = g;
        fgData[idx + 2] = b;
        fgData[idx + 3] = a;
      }
    }

    mgCtx.putImageData(mgImgData, 0, 0);
    fgCtx.putImageData(fgImgData, 0, 0);
    bgCctx.putImageData(bgImgData, 0, 0);

    depthLayers = {
      bg: bgC,
      mg: mgCanvas,
      fg: fgCanvas,
    };
  } catch {}

  // 3. Resolve Video Sink via MediaEngineRegistry (Decoupled from native FFIVideoEncoder)
  const canvas = UniversalCanvasProvider.createCanvas(width, height);
  const ctx = canvas.getContext("2d");

  let sink: IMediaFrameSink = options.sink!;
  if (!sink) {
    const strategy = MediaEngineRegistry.has('bun-ffi')
      ? MediaEngineRegistry.get('bun-ffi')
      : MediaEngineRegistry.get();
    sink = strategy.createVideoSink({
      width,
      height,
      fps,
      totalFrames,
      durationSeconds: totalDuration,
      outputPath,
      audioPath: scene.resolvedAudio || fallbackAudioPath,
    });
  }

  await sink.initialize({
    width,
    height,
    fps,
    totalFrames,
    durationSeconds: totalDuration,
    outputPath,
    audioPath: scene.resolvedAudio || fallbackAudioPath,
  });

  const captionStrategy = new BoundedAcousticCaptionStrategy();

  // 4. Render and stream frames via sink
  for (let frame = 0; frame < totalFrames; frame++) {
    const progress = frame / totalFrames;
    const timeSec = frame / fps;

    ctx.clearRect(0, 0, width, height);

    const renderer = Depth3DFactory.getRenderer(mode);
    renderer.renderFrame(ctx, {
      img,
      subjectImg,
      subjectBBox,
      bgImg,
      srcCanvas,
      depthLayers,
      width,
      height,
      frame,
      totalFrames,
      timeSec,
      progress,
      depthConfig,
      captions: scene.captions,
      particles,
      dustParticles,
    });

    // Draw Canvas Subtitles / Captions isomorphically
    if (scene.captions && scene.captions.length > 0) {
      const snapshot: CaptionTrackSnapshot = captionStrategy.evaluate(
        scene.captions,
        timeSec,
        config.settings.captions
      );
      drawCanvasCaptionsFromSnapshot(
        ctx,
        snapshot,
        config.settings.captions,
        width,
        height,
        config.settings.platform as any
      );
    }

    // Ingest frame into sink
    const frameData = canvas.data();
    await sink.consumeFrame(frame, frameData);

    if (frame % 15 === 0) {
      await new Promise((r) => setTimeout(r, 0));
    }
  }

  await sink.finalize();
  return { path: outputPath, duration: totalDuration };
}

/**
 * Resolves cached or auto-segmented subject cutout image and bounding box for a given image path.
 */
export async function resolveSubjectCutout(
  imagePath: string,
  depthConfig?: Depth3DConfig
): Promise<{ subjectImg: any | null; subjectBBox: any | null }> {
  try {
    let imgBuffer: Uint8Array;
    if (typeof process !== "undefined" && process.versions?.node) {
      const fs = require("fs");
      imgBuffer = await fs.promises.readFile(imagePath);
    } else {
      const cache = ContentCacheRegistry.get();
      const cached = await cache.get(imagePath);
      if (!cached) return { subjectImg: null, subjectBBox: null };
      imgBuffer = cached;
    }

    const { depthCacheDir } = await getStoryRootAndCacheDir(imagePath);
    const imageChecksum = fastChecksum(imgBuffer);
    const segContext = SubjectSegmentationContext.getInstance();
    const segStratName = segContext.getActiveStrategyName().replace(/[^a-zA-Z0-9_-]/g, "_");

    const cacheKey = `cutout_${segStratName}_${imageChecksum}`;
    const cache = ContentCacheRegistry.get();
    if (await cache.has(cacheKey)) {
      const data = await cache.get(cacheKey);
      if (data) {
        const subjectImg = await CanvasAssetLoader.loadImage(data);
        return { subjectImg, subjectBBox: null };
      }
    }

    // Auto-segmentation
    const segRes = await segContext.segmentSubject(imgBuffer);
    if (segRes && segRes.maskRgbaBuffer) {
      await cache.set(cacheKey, segRes.maskRgbaBuffer, { mimeType: 'image/png' });
      const subjectImg = await CanvasAssetLoader.loadImage(segRes.maskRgbaBuffer);
      return { subjectImg, subjectBBox: segRes.boundingBox };
    }

    return { subjectImg: null, subjectBBox: null };
  } catch {
    return { subjectImg: null, subjectBBox: null };
  }
}

/**
 * Resolves pre-computed or on-demand depth map data for mesh displacement & 3D re-lighting.
 */
export async function resolveDepthMapData(
  imagePath: string,
  targetWidth: number,
  targetHeight: number,
  depthConfig?: Depth3DConfig
): Promise<{ depthCanvas: ICanvasInstance; depthData: Uint8ClampedArray; normalMap?: any }> {
  let imgBuffer: Uint8Array;
  if (typeof process !== "undefined" && process.versions?.node) {
    const fs = require("fs");
    imgBuffer = await fs.promises.readFile(imagePath);
  } else {
    const cache = ContentCacheRegistry.get();
    const cached = await cache.get(imagePath);
    if (!cached) throw new Error(`[resolveDepthMapData] Asset not in cache: ${imagePath}`);
    imgBuffer = cached;
  }

  const dCanvas = UniversalCanvasProvider.createCanvas(targetWidth, targetHeight);
  const dCtx = dCanvas.getContext("2d");

  const depthContext = DepthEstimationContext.getInstance();
  const depthStratName = depthContext.getActiveStrategyName().replace(/[^a-zA-Z0-9_-]/g, "_");
  const imageChecksum = fastChecksum(imgBuffer);
  const cacheKey = `depth_${depthStratName}_${imageChecksum}`;
  const cache = ContentCacheRegistry.get();

  let loadedDepth = false;
  if (await cache.has(cacheKey)) {
    const cached = await cache.get(cacheKey);
    if (cached) {
      const dm = await CanvasAssetLoader.loadImage(cached);
      drawImageCover(dCtx, dm, 0, 0, targetWidth, targetHeight);
      loadedDepth = true;
    }
  }

  if (!loadedDepth) {
    try {
      const depthRes = await depthContext.estimateDepth(imgBuffer);
      if (depthRes && depthRes.depth16Buffer && depthRes.depth16Buffer.length > 0) {
        await cache.set(cacheKey, depthRes.depth16Buffer, { mimeType: 'image/png' });
        const dm = await CanvasAssetLoader.loadImage(depthRes.depth16Buffer);
        drawImageCover(dCtx, dm, 0, 0, targetWidth, targetHeight);
        loadedDepth = true;
      }
    } catch {}
  }

  if (!loadedDepth) {
    const radGrad = dCtx.createRadialGradient(
      targetWidth / 2,
      targetHeight * 0.52,
      targetWidth * 0.05,
      targetWidth / 2,
      targetHeight * 0.52,
      targetWidth * 0.65,
    );
    radGrad.addColorStop(0, "rgb(255, 255, 255)");
    radGrad.addColorStop(0.5, "rgb(180, 180, 180)");
    radGrad.addColorStop(1, "rgb(30, 30, 30)");
    dCtx.fillStyle = radGrad;
    dCtx.fillRect(0, 0, targetWidth, targetHeight);
  }

  const depthData = dCtx.getImageData(0, 0, targetWidth, targetHeight).data;
  return { depthCanvas: dCanvas, depthData };
}
