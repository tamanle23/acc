import { describe, it, expect, beforeAll } from 'bun:test';
import path from 'path';
import fs from 'fs';
import {
  PipelineRunner,
  createUnifiedPipelineContext,
  defaultPipelineRegistry,
  IPipelineMiddleware,
  FFmpegManager,
} from '@acc/core';
import {
  ScraperPipeline,
  DBTemplatingPipeline,
  RepurposingPipeline,
  GenerativeStoryPipeline,
  RuleLogicPipeline,
  AmbientStreamPipeline,
  registerAllPipelines,
} from '../apps/cli/src/pipelines';

describe('Universal Pipeline Orchestrator & Decoupled 6-Pipeline Suite', () => {
  const testOutDir = path.resolve(process.cwd(), 'autogenerated', 'orchestrator-tests');

  beforeAll(async () => {
    registerAllPipelines();
    if (!fs.existsSync(testOutDir)) {
      fs.mkdirSync(testOutDir, { recursive: true });
    }
    await FFmpegManager.prepare();
  });

  describe('Core PipelineRunner & Context Primitives', () => {
    it('executes middleware chain with timing metrics and context propagation', async () => {
      const runner = new PipelineRunner();
      const ctx = createUnifiedPipelineContext({
        pipelineId: 'test-pipeline',
        input: { data: 'hello' },
        outDir: testOutDir,
      });

      runner.use({
        name: 'StepA',
        execute: async (c, next) => {
          c.metadata.stepA = true;
          await new Promise((res) => setTimeout(res, 20));
          await next();
        },
      });

      runner.use({
        name: 'StepB',
        execute: async (c, next) => {
          c.metadata.stepB = true;
          await next();
        },
      });

      const result = await runner.run(ctx);

      expect(result.metadata.stepA).toBe(true);
      expect(result.metadata.stepB).toBe(true);
      expect(result.timings.StepA).toBeGreaterThanOrEqual(15);
      expect(result.timings.StepB).toBeDefined();
      expect(result.errors.length).toBe(0);
    });

    it('isolates stage errors defensively and allows downstream fallbacks to execute', async () => {
      const runner = new PipelineRunner();
      const ctx = createUnifiedPipelineContext({
        pipelineId: 'fault-tolerant-pipeline',
        input: {},
        outDir: testOutDir,
      });

      runner.use({
        name: 'FailingStage',
        execute: async () => {
          throw new Error('Simulated transient AI model failure');
        },
      });

      runner.use({
        name: 'FallbackStage',
        execute: async (c, next) => {
          c.metadata.recovered = true;
          await next();
        },
      });

      const result = await runner.run(ctx);

      expect(result.errors.length).toBe(1);
      expect(result.errors[0].stage).toBe('FailingStage');
      expect(result.errors[0].error.message).toContain('Simulated transient AI model failure');
      expect(result.metadata.recovered).toBe(true);
    });
  });

  describe('Pipeline Registry & Unified Discovery', () => {
    it('verifies all 6 pipelines are registered and resolvable via IDs and aliases', () => {
      expect(defaultPipelineRegistry.has('scraper')).toBe(true);
      expect(defaultPipelineRegistry.has('1')).toBe(true);

      expect(defaultPipelineRegistry.has('db')).toBe(true);
      expect(defaultPipelineRegistry.has('2')).toBe(true);

      expect(defaultPipelineRegistry.has('repurposing')).toBe(true);
      expect(defaultPipelineRegistry.has('3')).toBe(true);

      expect(defaultPipelineRegistry.has('story')).toBe(true);
      expect(defaultPipelineRegistry.has('4')).toBe(true);

      expect(defaultPipelineRegistry.has('rule-logic')).toBe(true);
      expect(defaultPipelineRegistry.has('5')).toBe(true);
      expect(defaultPipelineRegistry.has('math')).toBe(true);

      expect(defaultPipelineRegistry.has('ambient')).toBe(true);
      expect(defaultPipelineRegistry.has('6')).toBe(true);
    });
  });

  describe('End-to-End Orchestrated Pipeline Executions', () => {
    it('Pipeline 1 (Scraper): executes middleware stages and generates PipelineIR & exports', async () => {
      const pipeline = defaultPipelineRegistry.get('scraper') as ScraperPipeline;
      expect(pipeline).toBeDefined();

      const outDir = path.join(testOutDir, 'scraper_run');
      const event = {
        eventId: 'evt_test_101',
        sourceUrl: 'https://news.ycombinator.com',
        rawText: 'Breakthrough in AI video engines achieves 60fps real-time diffusion rendering with zero VRAM spikes.',
        receivedAt: new Date().toISOString(),
      };

      const ctx = await pipeline.execute(event, { outDir });

      expect(ctx.pipelineId).toBe('scraper');
      expect(ctx.ir).toBeDefined();
      expect(ctx.ir?.pipelineId).toBe('scraper-summarizer');
      expect(ctx.ir?.chunks.length).toBe(1);
      expect(ctx.exportResults).toBeDefined();
      expect(ctx.timings.ScraperLLMSummarizeStage).toBeDefined();
      expect(ctx.timings.ScraperTTSSynthesisStage).toBeDefined();
      expect(ctx.timings.ScraperCardCompositionStage).toBeDefined();
      expect(ctx.timings.ExporterDispatcherMiddleware).toBeDefined();
    });

    it('Pipeline 2 (DB Templating): normalizes records and renders bar chart ranking via orchestrator', async () => {
      const pipeline = defaultPipelineRegistry.get('db') as DBTemplatingPipeline;
      expect(pipeline).toBeDefined();

      const outDir = path.join(testOutDir, 'db_run');
      const payload = {
        title: 'Cloud Database Throughput 2026',
        category: 'Databases',
        highlightMetric: 'qps',
        entities: [
          { id: '1', name: 'PostgreSQL JSONB', category: 'SQL', metrics: { qps: 85000 }, highlightMetric: 'qps' },
          { id: '2', name: 'Redis Cache', category: 'In-Memory', metrics: { qps: 210000 }, highlightMetric: 'qps' },
          { id: '3', name: 'Cassandra Node', category: 'NoSQL', metrics: { qps: 130000 }, highlightMetric: 'qps' },
        ],
        summaryConclusion: 'Redis leads raw QPS while PostgreSQL provides richest querying flexibility.',
      };

      const ctx = await pipeline.execute(payload, { outDir });

      expect(ctx.pipelineId).toBe('db');
      expect(ctx.ir?.pipelineId).toBe('db-templating');
      expect(ctx.ir?.structuredData.entities[0].name).toBe('Redis Cache');
      expect(ctx.exportResults?.video).toBeDefined();
      expect(ctx.timings.DBDataNormalizationStage).toBeDefined();
      expect(ctx.timings.DBBarChartCompositionStage).toBeDefined();
    });

    it('Pipeline 3 (Repurposing): extracts viral hook and formats 9:16 smart-crop via orchestrator', async () => {
      const pipeline = defaultPipelineRegistry.get('repurposing') as RepurposingPipeline;
      expect(pipeline).toBeDefined();

      const outDir = path.join(testOutDir, 'repurpose_run');
      const input = {
        title: 'Building Resilient Systems',
        rawTranscript: 'You must always structure media engines with bounded backpressure. Never let fast producers overflow memory. Decoupled pipeline architectures are the future.',
        activeSpeakerPosition: { x: 0.5, y: 0.4 },
      };

      const ctx = await pipeline.execute(input, { outDir });

      expect(ctx.pipelineId).toBe('repurposing');
      expect(ctx.ir?.pipelineId).toBe('repurposing-recycler');
      expect(ctx.ir?.distributionHints.targetAspectRatios).toContain('9:16');
      expect(ctx.exportResults).toBeDefined();
      expect(ctx.timings.RepurposingHookExtractionStage).toBeDefined();
      expect(ctx.timings.RepurposingCompositionStage).toBeDefined();
    });

    it('Pipeline 4 (Generative Story): processes story folder through orchestrated AST stages', async () => {
      const pipeline = defaultPipelineRegistry.get('story') as GenerativeStoryPipeline;
      expect(pipeline).toBeDefined();

      const sampleStoryDir = path.resolve(process.cwd(), 'sample-story');
      const outDir = path.join(testOutDir, 'story_run');

      const result = await pipeline.execute(sampleStoryDir, { outDir, dryRun: true });

      expect(typeof result).toBe('string');
      expect(result.length).toBeGreaterThan(0);
    });

    it('Pipeline 5 (Rule & Math Logic): validates proof equations and renders chalkboard slide', async () => {
      const pipeline = defaultPipelineRegistry.get('rule-logic') as RuleLogicPipeline;
      expect(pipeline).toBeDefined();

      const outDir = path.join(testOutDir, 'rule_run');
      const payload = {
        problemTitle: 'Euler Identity Verification',
        category: 'calculus',
        problemStatement: 'Evaluate e^(i*pi) + 1 = 0',
        steps: [
          { stepNumber: 1, explanation: 'Apply Euler formula e^(ix) = cos(x) + i*sin(x)', latexFormula: 'e^(i*pi) = cos(pi) + i*sin(pi)' },
          { stepNumber: 2, explanation: 'Evaluate trigonometric points', latexFormula: 'cos(pi) = -1, sin(pi) = 0', evaluatedResult: '-1 + 0' },
          { stepNumber: 3, explanation: 'Add unity to both sides', latexFormula: '-1 + 1 = 0', evaluatedResult: '0' },
        ],
        finalAnswer: '0 (Q.E.D.)',
      };

      const ctx = await pipeline.execute(payload, { outDir });

      expect(ctx.pipelineId).toBe('rule-logic');
      expect(ctx.ir?.pipelineId).toBe('rule-logic');
      expect(ctx.exportResults).toBeDefined();
      expect(ctx.timings.RuleLogicProofValidationStage).toBeDefined();
      expect(ctx.timings.RuleLogicChalkboardCompositionStage).toBeDefined();
    });

    it('Pipeline 6 (Ambient Stream): renders procedural shader loop and emits stream-ready IR', async () => {
      const pipeline = defaultPipelineRegistry.get('ambient') as AmbientStreamPipeline;
      expect(pipeline).toBeDefined();

      const outDir = path.join(testOutDir, 'ambient_run');
      const config = {
        title: 'Deep Space Relaxing Loop',
        theme: 'deep_space' as const,
        loopDurationSeconds: 4,
        particleCount: 120,
      };

      const ctx = await pipeline.execute(config, { outDir });

      expect(ctx.pipelineId).toBe('ambient');
      expect(ctx.ir?.pipelineId).toBe('ambient-loops');
      expect(ctx.exportResults).toBeDefined();
      expect(ctx.timings.AmbientParticleShaderCompositionStage).toBeDefined();
    });
  });
});
