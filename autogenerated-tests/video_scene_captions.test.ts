import { describe, expect, it, beforeAll } from 'bun:test';
import path from 'path';
import fs from 'fs';
import { FFmpegManager } from '../packages/core/src/FFmpegManager';
import { FFISceneEngine } from '../apps/legacy-story-renderer/src/FFISceneEngine';
import { getMediaDurationFFI } from '../packages/core/src/ffmpeg-ffi';

describe('Video Scene Captions & B-Roll Burning', () => {
  const sampleVideoPath = path.resolve('sample-story/assets/b-roll-nature.mp4');
  const sampleAudioPath = path.resolve('sample-story/assets/voiceover1.mp3');
  const testOutputDir = path.resolve('autogenerated/test-output');

  beforeAll(async () => {
    await FFmpegManager.prepare();
    if (!fs.existsSync(testOutputDir)) {
      fs.mkdirSync(testOutputDir, { recursive: true });
    }
  });

  it('should render a video scene with captions burned onto frames', async () => {
    const outputPath = path.join(testOutputDir, 'test_video_with_captions.mp4');
    if (fs.existsSync(outputPath)) fs.unlinkSync(outputPath);

    const result = await FFISceneEngine.renderScene({
      scene: {
        resolvedVideo: sampleVideoPath,
        resolvedAudio: sampleAudioPath,
        captions: [
          { text: 'Nature', start: 0.0, end: 0.8 },
          { text: 'waterfall', start: 0.8, end: 1.5 },
          { text: 'scenery', start: 1.5, end: 2.0 },
        ],
      } as any,
      duration: 2.0,
      assPath: null,
      config: {
        settings: {
          width: 640,
          height: 360,
          fps: 15,
          captions: {
            activeWordHighlight: true,
            highlightColor: '#00FFFF',
          },
        },
      } as any,
      outputPath,
      fallbackImagePath: '',
      fallbackAudioPath: sampleAudioPath,
    });

    expect(fs.existsSync(outputPath)).toBe(true);
    expect(fs.statSync(outputPath).size).toBeGreaterThan(1000);
    const dur = getMediaDurationFFI(outputPath);
    expect(dur).toBeGreaterThan(1.5);
  });

  it('should render a video scene without captions using fast raw path', async () => {
    const outputPath = path.join(testOutputDir, 'test_video_no_captions.mp4');
    if (fs.existsSync(outputPath)) fs.unlinkSync(outputPath);

    const result = await FFISceneEngine.renderScene({
      scene: {
        resolvedVideo: sampleVideoPath,
        resolvedAudio: sampleAudioPath,
        captions: [],
      } as any,
      duration: 1.5,
      assPath: null,
      config: {
        settings: {
          width: 640,
          height: 360,
          fps: 15,
        },
      } as any,
      outputPath,
      fallbackImagePath: '',
      fallbackAudioPath: sampleAudioPath,
    });

    expect(fs.existsSync(outputPath)).toBe(true);
    expect(fs.statSync(outputPath).size).toBeGreaterThan(1000);
    const dur = getMediaDurationFFI(outputPath);
    expect(dur).toBeGreaterThan(1.0);
  });
});
