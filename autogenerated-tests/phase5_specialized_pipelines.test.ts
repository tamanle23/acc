import { describe, it, expect, beforeAll } from 'bun:test';
import path from 'path';
import fs from 'fs';
import { DBTemplatingPipeline, DBTemplatePayload } from '../apps/cli/src/pipelines/02-db-templating';
import { RepurposingPipeline, RepurposingInput } from '../apps/cli/src/pipelines/03-repurposing';
import { RuleLogicPipeline, RuleLogicPayload } from '../apps/cli/src/pipelines/05-rule-logic';
import { AmbientStreamPipeline, AmbientLoopConfig } from '../apps/cli/src/pipelines/06-ambient-stream';
import { FFmpegManager } from '../packages/core/src/FFmpegManager';

describe('Phase 5: Specialized Pipelines Suite (Pipelines 2, 3, 5, 6)', () => {
  const testOutputDir = path.resolve(process.cwd(), 'autogenerated', 'tests', 'phase5');

  beforeAll(async () => {
    if (!fs.existsSync(testOutputDir)) {
      fs.mkdirSync(testOutputDir, { recursive: true });
    }
    await FFmpegManager.prepare();
  });

  describe('Pipeline 2: DB Templating Engine', () => {
    it('generates comparison chart, PipelineIR, and multi-channel exports', async () => {
      const outDir = path.resolve(testOutputDir, 'db_templating');
      const pipeline = new DBTemplatingPipeline();

      const payload: DBTemplatePayload = {
        title: 'Smartphone Flagship AnTuTu Benchmark 2026',
        category: 'mobile',
        highlightMetric: 'score',
        summaryConclusion: 'Snapdragon Gen 5 dominates with unprecedented multicore efficiency.',
        entities: [
          { id: '1', name: 'Titan Phone Pro Max', category: 'mobile', metrics: { score: 3200000, ram: 24 }, highlightMetric: 'score' },
          { id: '2', name: 'Apex Ultra 10', category: 'mobile', metrics: { score: 2950000, ram: 16 }, highlightMetric: 'score' },
          { id: '3', name: 'Nexus Velocity X', category: 'mobile', metrics: { score: 2780000, ram: 16 }, highlightMetric: 'score' },
        ],
      };

      const { ir, exportResults } = await pipeline.run(payload, outDir);

      expect(ir).toBeDefined();
      expect(ir.pipelineId).toBe('db-templating');
      expect(ir.structuredData?.entities).toBeDefined();
      expect(ir.chunks.length).toBe(1);

      const chartPath = path.join(outDir, 'comparison_chart.png');
      expect(fs.existsSync(chartPath)).toBe(true);

      expect(exportResults.staticWeb).toBeDefined();
      expect(exportResults.social).toBeDefined();
      expect(exportResults.video).toBeDefined();
    });
  });

  describe('Pipeline 3: Repurposing Recycler Engine', () => {
    it('extracts viral hook, applies 9:16 smart-crop with karaoke typography', async () => {
      const outDir = path.resolve(testOutputDir, 'repurposing');
      const pipeline = new RepurposingPipeline();

      const input: RepurposingInput = {
        title: 'The Future of Agentic Coding',
        rawTranscript: `
          Here is why traditional programming is changing forever.
          Autonomous coding agents don't just complete syntax; they orchestrate full-stack architectures.
          Zero-latency multi-pipeline systems replace monolithic rendering stacks.
          And the developer becomes the principal systems architect directing a fleet of specialized sub-engines.
        `,
        sourceMediaUrl: 'https://youtube.com/watch?v=agentic123',
        activeSpeakerPosition: { x: 0.5, y: 0.35 },
      };

      const { ir, exportResults } = await pipeline.run(input, outDir);

      expect(ir).toBeDefined();
      expect(ir.pipelineId).toBe('repurposing-recycler');
      expect(ir.structuredData?.viralHook).toBeDefined();

      const framePath = path.join(outDir, 'repurposed_frame.png');
      expect(fs.existsSync(framePath)).toBe(true);

      expect(exportResults.social).toBeDefined();
      expect(exportResults.video).toBeDefined();
    });
  });

  describe('Pipeline 5: Rule & Math Logic Engine', () => {
    it('renders step-by-step chalkboard proof and emits verified mathematical PipelineIR', async () => {
      const outDir = path.resolve(testOutputDir, 'rule_logic');
      const pipeline = new RuleLogicPipeline();

      const payload: RuleLogicPayload = {
        problemTitle: 'Evaluate Integral of x * e^(2x) dx',
        problemStatement: 'Compute the indefinite integral using integration by parts.',
        category: 'calculus',
        finalAnswer: '(1/2)x*e^(2x) - (1/4)e^(2x) + C',
        steps: [
          { stepNumber: 1, explanation: 'Choose u = x and dv = e^(2x) dx', latexFormula: 'du = dx,  v = (1/2)e^(2x)' },
          { stepNumber: 2, explanation: 'Apply formula: integral(u dv) = u*v - integral(v du)', latexFormula: 'I = (1/2)x*e^(2x) - integral((1/2)e^(2x) dx)' },
          { stepNumber: 3, explanation: 'Integrate remaining term (1/2)e^(2x)', latexFormula: 'integral((1/2)e^(2x) dx) = (1/4)e^(2x)', evaluatedResult: 'Confirmed' },
        ],
      };

      const { ir, exportResults } = await pipeline.run(payload, outDir);

      expect(ir).toBeDefined();
      expect(ir.pipelineId).toBe('rule-logic');
      expect(ir.structuredData?.steps).toBeDefined();

      const boardPath = path.join(outDir, 'chalkboard_solution.png');
      expect(fs.existsSync(boardPath)).toBe(true);

      expect(exportResults.staticWeb).toBeDefined();
      expect(exportResults.social).toBeDefined();
      expect(exportResults.video).toBeDefined();
    });
  });

  describe('Pipeline 6: Ambient Stream Engine', () => {
    it('generates procedural particle loop frame and emits 24/7 stream PipelineIR', async () => {
      const outDir = path.resolve(testOutputDir, 'ambient_stream');
      const pipeline = new AmbientStreamPipeline();

      const config: AmbientLoopConfig = {
        title: 'Deep Space Relaxing Focus Stream',
        theme: 'deep_space',
        loopDurationSeconds: 1, // Short duration for fast unit test execution
        particleCount: 50,
      };

      const { ir, exportResults } = await pipeline.run(config, outDir);

      expect(ir).toBeDefined();
      expect(ir.pipelineId).toBe('ambient-loops');
      expect(ir.structuredData?.theme).toBe('deep_space');

      const loopFrame = path.join(outDir, 'ambient_loop_frame.png');
      expect(fs.existsSync(loopFrame)).toBe(true);

      expect(exportResults.video).toBeDefined();
      expect(exportResults.audio).toBeDefined();
    });
  });
});
