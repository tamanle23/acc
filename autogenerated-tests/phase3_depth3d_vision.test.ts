import { describe, it, expect, beforeAll } from 'bun:test';
import path from 'path';
import fs from 'fs';
import { createCanvas } from '@napi-rs/canvas';
import { IPCFacade, FallbackAIStrategy, GRPCAIStrategy } from '../packages/core/src/ipc/IPCFacade';
import { renderDepth3DScene } from '../packages/effect-engines/src/depth3d';
import { FFmpegManager } from '../packages/core/src/FFmpegManager';
import { runSFXCommand } from '../apps/cli/src/commands/sfx';
import { runOverlayCommand } from '../apps/cli/src/commands/overlay';

describe('Phase 3: Pipeline 4 Refinement (Depth Anything v2 + SAM 2 + Depth3D)', () => {
  const testOutputDir = path.resolve(process.cwd(), 'autogenerated', 'tests', 'phase3');
  const sampleImgPath = path.resolve(testOutputDir, 'test_input.jpg');
  const sampleAudioPath = path.resolve(process.cwd(), 'sample-story', 'voiceover1.mp3');

  beforeAll(async () => {
    if (!fs.existsSync(testOutputDir)) {
      fs.mkdirSync(testOutputDir, { recursive: true });
    }
    await FFmpegManager.prepare();

    // Create a deterministic dummy image for visual tests
    const canvas = createCanvas(320, 240);
    const ctx = canvas.getContext('2d');
    ctx.fillStyle = '#223344';
    ctx.fillRect(0, 0, 320, 240);
    ctx.fillStyle = '#ffaa33';
    ctx.beginPath();
    ctx.arc(160, 120, 60, 0, Math.PI * 2);
    ctx.fill();
    fs.writeFileSync(sampleImgPath, canvas.toBuffer('image/jpeg'));
  });

  describe('VisionService & IPCFacade Contracts', () => {
    it('should support FallbackAIStrategy for depth estimation and segmentation', async () => {
      const fallbackFacade = new IPCFacade(new FallbackAIStrategy());
      expect(fallbackFacade.getStrategyName()).toBe('fallback');

      const depthRes = await fallbackFacade.estimateDepth(sampleImgPath);
      expect(depthRes).toBeDefined();
      expect(depthRes.minDepth).toBe(0);
      expect(depthRes.maxDepth).toBe(1);
      expect(Buffer.isBuffer(depthRes.depthMapBuffer)).toBe(true);

      const segRes = await fallbackFacade.segmentSubject(sampleImgPath);
      expect(segRes).toBeDefined();
      expect(segRes.confidence).toBe(1);
      expect(segRes.boundingBox).toBeDefined();
      expect(Buffer.isBuffer(segRes.maskBuffer)).toBe(true);
    });

    it('should defensively handle buffer and path inputs in IPCFacade', async () => {
      const facade = new IPCFacade(new FallbackAIStrategy());
      const imgBuffer = fs.readFileSync(sampleImgPath);

      const depthFromBuf = await facade.estimateDepth(imgBuffer);
      expect(depthFromBuf).toBeDefined();

      const segFromBuf = await facade.segmentSubject(imgBuffer);
      expect(segFromBuf).toBeDefined();
    });

    it('should gracefully switch to fallback strategy if gRPC daemon connection fails', async () => {
      // Point to an inactive port
      const deadGRPCStrategy = new GRPCAIStrategy('127.0.0.1:59999');
      const resilientFacade = new IPCFacade(deadGRPCStrategy);

      const pong = await resilientFacade.ping('test_resilience');
      expect(pong).toContain('Fallback in-process pong: test_resilience');
      expect(resilientFacade.getStrategyName()).toBe('fallback');
    });
  });

  describe('Depth3D Enhanced Engines Integration', () => {
    it('should render frame_breaker with autoSegment enabled', async () => {
      const outVideo = path.resolve(testOutputDir, 'fb_auto_segment.mp4');
      const result = await renderDepth3DScene({
        scene: {
          image: sampleImgPath,
          resolvedImage: sampleImgPath,
          audio: sampleAudioPath,
          resolvedAudio: sampleAudioPath,
          captions: [],
          depth3d: {
            enabled: true,
            mode: 'frame_breaker',
            frameStyle: 'polaroid',
            autoSegment: true,
            popOutIntensity: 1.2
          }
        },
        duration: 0.5,
        assPath: null,
        config: {
          name: 'Test',
          settings: {
            width: 320,
            height: 240,
            fps: 15,
            videoCodec: 'h264',
            audioCodec: 'aac',
            platform: 'youtube',
            concurrency: 1,
            fastIntermediate: true
          } as any,
          scenes: []
        },
        outputPath: outVideo
      });

      expect(result).toBeDefined();
      expect(fs.existsSync(result.path)).toBe(true);
      expect(fs.statSync(result.path).size).toBeGreaterThan(500);
    }, 60000);

    it('should render depth_map_3d with autoDepth enabled', async () => {
      const outVideo = path.resolve(testOutputDir, 'depth_map_auto.mp4');
      const result = await renderDepth3DScene({
        scene: {
          image: sampleImgPath,
          resolvedImage: sampleImgPath,
          audio: sampleAudioPath,
          resolvedAudio: sampleAudioPath,
          captions: [],
          depth3d: {
            enabled: true,
            mode: 'depth_map_3d',
            autoDepth: true
          }
        },
        duration: 0.5,
        assPath: null,
        config: {
          name: 'Test',
          settings: {
            width: 320,
            height: 240,
            fps: 15,
            videoCodec: 'h264',
            audioCodec: 'aac',
            platform: 'youtube',
            concurrency: 1,
            fastIntermediate: true
          } as any,
          scenes: []
        },
        outputPath: outVideo
      });

      expect(result).toBeDefined();
      expect(fs.existsSync(result.path)).toBe(true);
      expect(fs.statSync(result.path).size).toBeGreaterThan(500);
    }, 60000);

    it('should render volumetric_sandwich with caption integration', async () => {
      const outVideo = path.resolve(testOutputDir, 'sandwich_caption.mp4');
      const result = await renderDepth3DScene({
        scene: {
          image: sampleImgPath,
          resolvedImage: sampleImgPath,
          audio: sampleAudioPath,
          resolvedAudio: sampleAudioPath,
          captions: [{ text: 'Deep 3D Text', start: 0, end: 1 }],
          depth3d: {
            enabled: true,
            mode: 'volumetric_sandwich',
            sandwich: {
              ambientDust: true,
              vignette: true
            }
          }
        },
        duration: 0.5,
        assPath: null,
        config: {
          name: 'Test',
          settings: {
            width: 320,
            height: 240,
            fps: 15,
            videoCodec: 'h264',
            audioCodec: 'aac',
            platform: 'youtube',
            concurrency: 1,
            fastIntermediate: true
          } as any,
          scenes: []
        },
        outputPath: outVideo
      });

      expect(result).toBeDefined();
      expect(fs.existsSync(result.path)).toBe(true);
      expect(fs.statSync(result.path).size).toBeGreaterThan(500);
    });

    it('should render wigglegram with stereoscopic disparity', async () => {
      const outVideo = path.resolve(testOutputDir, 'wigglegram.mp4');
      const result = await renderDepth3DScene({
        scene: {
          image: sampleImgPath,
          resolvedImage: sampleImgPath,
          audio: sampleAudioPath,
          resolvedAudio: sampleAudioPath,
          captions: [],
          depth3d: {
            enabled: true,
            mode: 'wigglegram',
            wigglegram: {
              frequency: 6,
              amplitude: 8,
              chromaticAberration: true
            }
          }
        },
        duration: 0.5,
        assPath: null,
        config: {
          name: 'Test',
          settings: {
            width: 320,
            height: 240,
            fps: 15,
            videoCodec: 'h264',
            audioCodec: 'aac',
            platform: 'youtube',
            concurrency: 1,
            fastIntermediate: true
          } as any,
          scenes: []
        },
        outputPath: outVideo
      });

      expect(result).toBeDefined();
      expect(fs.existsSync(result.path)).toBe(true);
      expect(fs.statSync(result.path).size).toBeGreaterThan(500);
    });
  });

  describe('Migrated CLI Command Handlers', () => {
    it('should export runSFXCommand and generateHeadless from apps/cli/src/commands/sfx', () => {
      expect(typeof runSFXCommand).toBe('function');
    });

    it('should export runOverlayCommand and generateHeadless from apps/cli/src/commands/overlay', () => {
      expect(typeof runOverlayCommand).toBe('function');
    });
  });
});
