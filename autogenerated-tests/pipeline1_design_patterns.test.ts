import { describe, it, expect } from 'bun:test';
import path from 'path';
import fs from 'fs';
import {
  ScraperEngine,
  ScraperPipeline,
  IngestedEvent,
} from '../apps/cli/src/pipelines/01-scraper';
import {
  BoundedQueue,
  AssetContext,
  FlyweightModelRegistry,
  RenderLowerThirdTickerCommand,
  PipelineRunner,
  IPCFacade,
  FallbackAIStrategy,
} from '@acc/core';

describe('Pipeline 1 Design Patterns Unit Test Suite', () => {
  it('ScraperEngine utilizes BoundedQueue for event ingestion', async () => {
    const engine = new ScraperEngine(5);
    const queue = engine.getQueue();
    expect(queue).toBeInstanceOf(BoundedQueue);
    expect(queue.getCapacity()).toBe(5);

    const event = await engine.ingestManual('Test event for BoundedQueue');
    expect(event.sourceType).toBe('manual');
  });

  it('RenderLowerThirdTickerCommand validates and generates filter graph node', async () => {
    const assets = new AssetContext();
    const sceneId = 'scene_test_ticker';
    assets.register(sceneId, 'canvas', '/tmp/test_canvas.png');

    const cmd = new RenderLowerThirdTickerCommand('ticker_01', sceneId, 'Breaking market alert', 'FINANCE');
    const validation = cmd.validate(assets);
    expect(validation.valid).toBe(true);

    const cost = cmd.estimateCost();
    expect(cost.cpuScore).toBe(1);
    expect(cost.vramMB).toBe(32);
  });

  it('ScraperPipeline executes stages via PipelineRunner and registers assets in AssetContext', async () => {
    const fallbackFacade = new IPCFacade(new FallbackAIStrategy());
    const mockDispatcher = {
      exportAll: async (ir: any) => ({
        staticWeb: { exporterId: 'static-web', outputPath: ['/tmp/web.md'], durationMs: 2500 },
        social: { exporterId: 'social', outputPath: ['/tmp/social.json'], durationMs: 2500 },
        audio: { exporterId: 'audio', outputPath: ['/tmp/audio.mp3'], durationMs: 2500 },
        video: { exporterId: 'video', outputPath: ['/tmp/video.mp4'], durationMs: 2500 },
      }),
    } as any;

    const pipeline = new ScraperPipeline(fallbackFacade, mockDispatcher);
    const event: IngestedEvent = {
      sourceType: 'manual',
      rawText: 'Urgent: Federal Reserve announces rate adjustment.',
      receivedAt: new Date().toISOString(),
    };

    const outDir = path.resolve(process.cwd(), 'autogenerated', 'tests', 'p1_patterns_unit');
    const { ir, exportResults } = await pipeline.run(event, outDir);

    expect(ir).toBeDefined();
    expect(ir.pipelineId).toBe('scraper-summarizer');
    expect(exportResults.staticWeb).toBeDefined();
    expect(exportResults.social).toBeDefined();
  });
});
