import { describe, it, expect } from 'bun:test';
import path from 'path';
import fs from 'fs';
import {
  RelationalDAGCompiler,
  AssetMetadataProber,
  IRMasterRenderer,
  type VideoIRDocument,
  } from '@acc/ir';
import { StoryConfigToUniversalIRAdapter, LegacyStoryConfigAdapter, type LegacyStoryConfig } from '@acc/legacy-story-renderer';
import { parseCliArgs } from '../apps/cli/src/index';

describe('Phase 6: Distributed Temporal Slicing & CLI Execution Parity', () => {
  const sampleConfigPath = path.resolve(import.meta.dir, '../sample-story/story-config.json');
  const rawConfig: LegacyStoryConfig = JSON.parse(fs.readFileSync(sampleConfigPath, 'utf-8'));

  it('correctly parses CLI arguments for ir-render with chunk boundaries', () => {
    const args = [
      'ir-render',
      '--config',
      './sample-story/story-config.json',
      '--chunk-start',
      '100',
      '--chunk-end',
      '200',
      '--dry-run',
    ];

    const parsed = parseCliArgs(args);
    expect(parsed.command).toBe('ir-render');
    expect(parsed.configPath).toBe('./sample-story/story-config.json');
    expect(parsed.chunkStart).toBe(100);
    expect(parsed.chunkEnd).toBe(200);
    expect(parsed.dryRun).toBe(true);
  });

  it('supports temporal chunk rendering slicing deterministically without state leakage', async () => {
    const irDoc: VideoIRDocument = StoryConfigToUniversalIRAdapter.adapt(rawConfig);
    const prober = new AssetMetadataProber(path.dirname(sampleConfigPath));
    const compiler = new RelationalDAGCompiler({ prober });
    const timeline = await compiler.compile(irDoc);

    const totalFramesOriginal = timeline.totalFrames;
    expect(totalFramesOriginal).toBe(5040); // 28 scenes * 6.0s durationPerSlide * 30 fps

    // Simulate Chunk 0: Frames 0..5
    const chunk0Timeline = await compiler.compile(irDoc);
    chunk0Timeline.totalFrames = 5;
    const renderer0 = new IRMasterRenderer(chunk0Timeline, 12345);
    const result0 = await renderer0.render({ generateFrameHash: true });

    expect(result0.totalFrames).toBe(5);
    expect(result0.cumulativeHash).toBeDefined();

    // Verify chunk 0 run 2 determinism with same seed
    const chunk0TimelineRepeat = await compiler.compile(irDoc);
    chunk0TimelineRepeat.totalFrames = 5;
    const renderer0Repeat = new IRMasterRenderer(chunk0TimelineRepeat, 12345);
    const result0Repeat = await renderer0Repeat.render({ generateFrameHash: true });

    expect(result0.cumulativeHash).toBe(result0Repeat.cumulativeHash);
  });

  it('executes handleIrRenderCommand in dry-run mode without allocating compute', async () => {
    const { handleIrRenderCommand } = await import('../apps/cli/src/commands/ir-render');
    const validVideoIrPath = path.resolve('./autogenerated/tests/phase4/e2e_run/video-ir.json');
    
    // Dry-run should succeed without errors and return cleanly
    await expect(
      handleIrRenderCommand({
        input: validVideoIrPath,
        dryRun: true,
        chunkStart: 0,
        chunkEnd: 50,
      })
    ).resolves.toBeUndefined();
  });
});
