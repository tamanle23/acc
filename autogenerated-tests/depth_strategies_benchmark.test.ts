import { describe, it, expect, beforeAll } from 'bun:test';
import fs from 'fs';
import path from 'path';
import { bootstrapNode } from '../packages/core/src/bootstrap';
import { VisionEngineRegistry, DepthStrategyId } from '@acc/core-isomorphic';
import {
  DepthAnythingV2SmallStrategy,
  DepthAnythingV2BaseStrategy,
  GlpnMetricStrategy,
  DptLargeStrategy,
  HeuristicDepthStrategy
} from '../packages/effect-engines/src/vision';

describe('Depth Estimation Multi-Strategy Benchmark Suite', () => {
  const sampleImagePath = fs.existsSync(path.resolve(process.cwd(), 'sample-story', 'assets', 'scene1.jpg'))
    ? path.resolve(process.cwd(), 'sample-story', 'assets', 'scene1.jpg')
    : path.resolve(process.cwd(), 'sample-story', 'scene1.jpg');
  let imageBuffer: Buffer;
  const outDepthDir = path.resolve(process.cwd(), 'sample-story', 'autogenerated', 'depth-3d');

  beforeAll(async () => {
    await bootstrapNode();
    if (!fs.existsSync(outDepthDir)) {
      fs.mkdirSync(outDepthDir, { recursive: true });
    }
    imageBuffer = fs.readFileSync(sampleImagePath);
  });

  it('should benchmark HeuristicDepthStrategy (0ms baseline)', async () => {
    const strat = new HeuristicDepthStrategy();
    const t0 = Date.now();
    const res = await strat.estimateDepth(imageBuffer);
    const dt = Date.now() - t0;

    expect(res).toBeDefined();
    expect(res.width).toBeGreaterThan(0);
    expect(res.height).toBeGreaterThan(0);
    expect(Buffer.isBuffer(res.depth16Buffer)).toBe(true);
    expect(res.minDepth).toBe(0.5);
    expect(res.maxDepth).toBe(8.5);
    console.log(`[Depth Benchmark] Heuristic: ${dt} ms | size: ${res.depth16Buffer.length} bytes`);
  });

  it('should benchmark DepthAnythingV2SmallStrategy (SOTA Default, ~95MB)', async () => {
    const strat = new DepthAnythingV2SmallStrategy();
    const t0 = Date.now();
    const res = await strat.estimateDepth(imageBuffer);
    const dt = Date.now() - t0;

    expect(res).toBeDefined();
    expect(res.width).toBeGreaterThan(0);
    expect(res.height).toBeGreaterThan(0);
    expect(Buffer.isBuffer(res.depth16Buffer)).toBe(true);
    fs.writeFileSync(path.join(outDepthDir, 'scene1_depth_benchmark_v2small.png'), res.depth16Buffer);
    console.log(`[Depth Benchmark] Depth-Anything-v2-Small: ${dt} ms | size: ${res.depth16Buffer.length} bytes`);
  }, 45000);

  it('should benchmark GlpnMetricStrategy (Metric Depth in meters, ~60MB)', async () => {
    const strat = new GlpnMetricStrategy();
    const t0 = Date.now();
    const res = await strat.estimateDepth(imageBuffer);
    const dt = Date.now() - t0;

    expect(res).toBeDefined();
    expect(res.width).toBeGreaterThan(0);
    expect(res.height).toBeGreaterThan(0);
    expect(Buffer.isBuffer(res.depth16Buffer)).toBe(true);
    fs.writeFileSync(path.join(outDepthDir, 'scene1_depth_benchmark_glpn_metric.png'), res.depth16Buffer);
    console.log(`[Depth Benchmark] GLPN Metric Depth: ${dt} ms | size: ${res.depth16Buffer.length} bytes`);
  }, 45000);

  it('should benchmark DptLargeStrategy (Dense Prediction Transformer, ~130MB)', async () => {
    const strat = new DptLargeStrategy();
    const t0 = Date.now();
    const res = await strat.estimateDepth(imageBuffer);
    const dt = Date.now() - t0;

    expect(res).toBeDefined();
    expect(res.width).toBeGreaterThan(0);
    expect(res.height).toBeGreaterThan(0);
    expect(Buffer.isBuffer(res.depth16Buffer)).toBe(true);
    fs.writeFileSync(path.join(outDepthDir, 'scene1_depth_benchmark_dpt_large.png'), res.depth16Buffer);
    console.log(`[Depth Benchmark] DPT Large: ${dt} ms | size: ${res.depth16Buffer.length} bytes`);
  }, 45000);

  it('should seamlessly route through VisionEngineRegistry', async () => {
    VisionEngineRegistry.registerDepthStrategy(new GlpnMetricStrategy());
    VisionEngineRegistry.registerDepthStrategy(new DptLargeStrategy());
    VisionEngineRegistry.registerDepthStrategy(new DepthAnythingV2SmallStrategy());

    VisionEngineRegistry.setDefaultDepthStrategy(DepthStrategyId.GlpnMetric);
    expect(VisionEngineRegistry.getDepthStrategy().name).toBe('glpn-metric');

    VisionEngineRegistry.setDefaultDepthStrategy(DepthStrategyId.DptLarge);
    expect(VisionEngineRegistry.getDepthStrategy().name).toBe('dpt-large');

    VisionEngineRegistry.setDefaultDepthStrategy(DepthStrategyId.DepthAnythingV2Small);
    expect(VisionEngineRegistry.getDepthStrategy().name).toBe('depth-anything-v2-small');
  });
});
