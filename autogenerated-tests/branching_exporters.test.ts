import { describe, it, expect, beforeAll } from 'bun:test';
import fs from 'fs';
import path from 'path';
import type { PipelineIR } from '@acc/ir';
import { defaultExporterDispatcher } from '@acc/exporters';
import { FFmpegManager } from '@acc/core';

describe('Branching Exporter Suite (Video, Audio, Social Canvas, Static Web)', () => {
  const testOutDir = path.resolve(process.cwd(), 'autogenerated', 'exports', 'test_suite');

  const mockIR: PipelineIR = {
    schemaVersion: '3.0.0',
    pipelineId: 'scraper-summarizer',
    metadata: {
      jobId: 'test_job_42',
      title: 'Global Tech Breakthrough: Quantum AI Processor Announced',
      createdAt: new Date().toISOString(),
      tags: ['quantum', 'ai', 'hardware'],
      author: 'ACC Automated System',
    },
    chunks: [
      {
        id: 'chunk_1',
        order: 1,
        summary: 'Quantum Computing breakthrough achieved with 99.9% gate fidelity.',
        text: 'Researchers have demonstrated a fault-tolerant quantum processor capable of running real-time AI workloads at room temperature.',
        durationMs: 1500, // 1.5s
      },
      {
        id: 'chunk_2',
        order: 2,
        summary: 'Commercial deployment planned for Q3 2027.',
        text: 'Major cloud providers have initiated pilot integrations to benchmark LLM inference on quantum tensor accelerators.',
        durationMs: 1500, // 1.5s
      },
    ],
    audioComposition: {
      narrationTrack: {
        sampleRate: 44100,
        channels: 2,
        loudnessLufs: -14,
      },
      sfxMarkers: [],
      ducking: {
        enabled: false,
        attenuationDb: -16,
        attackMs: 100,
        releaseMs: 300,
      },
    },
    structuredData: {
      specs: {
        qubits: 1024,
        fidelity: '99.9%',
        operatingTempKelvin: 295,
      },
    },
    distributionHints: {
      supportedExporters: ['video', 'audio', 'social', 'static-web'],
      targetAspectRatios: ['16:9', '9:16'],
    },
  };

  beforeAll(async () => {
    await FFmpegManager.prepare();
  });

  it('Fans out PipelineIR to all 4 exporters simultaneously', async () => {
    const results = await defaultExporterDispatcher.exportAll(mockIR, {
      outputDir: testOutDir,
      fileNamePrefix: 'quantum_news',
      aspectRatio: '16:9',
      fps: 30,
    });

    // 1. Social Exporter Verification
    expect(results.social).toBeDefined();
    expect(results.social?.format).toBe('png');
    const images = results.social?.outputPath as string[];
    expect(images.length).toBe(3); // 1 cover + 2 chunks
    images.forEach((imgPath) => {
      expect(fs.existsSync(imgPath)).toBe(true);
      expect(fs.statSync(imgPath).size).toBeGreaterThan(1000);
    });

    // 2. Static Web Exporter Verification
    expect(results.staticWeb).toBeDefined();
    const webPaths = results.staticWeb?.outputPath as string[];
    expect(webPaths.length).toBe(2); // .md and .json
    expect(fs.existsSync(webPaths[0])).toBe(true);
    expect(fs.existsSync(webPaths[1])).toBe(true);
    const mdContent = fs.readFileSync(webPaths[0], 'utf-8');
    expect(mdContent).toContain('Quantum AI Processor Announced');
    expect(mdContent).toContain('---'); // Frontmatter

    // 3. Audio Exporter Verification
    expect(results.audio).toBeDefined();
    expect(results.audio?.format).toBe('mp3');
    const audioPath = results.audio?.outputPath as string;
    expect(fs.existsSync(audioPath)).toBe(true);
    expect(fs.statSync(audioPath).size).toBeGreaterThan(1000);

    // 4. Video Exporter Verification (bun:ffi zero-copy H.264 MP4)
    expect(results.video).toBeDefined();
    expect(results.video?.format).toBe('mp4');
    const videoPath = results.video?.outputPath as string;
    expect(fs.existsSync(videoPath)).toBe(true);
    expect(fs.statSync(videoPath).size).toBeGreaterThan(10000);
  }, 20000);
});
