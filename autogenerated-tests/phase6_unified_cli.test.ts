import { describe, it, expect } from 'bun:test';
import { parseCliArgs, runCli } from '../apps/cli/src/index';
import fs from 'fs';
import path from 'path';

describe('Phase 6: Unified CLI Dispatcher & Production Tooling Suite', () => {
  it('correctly parses CLI subcommands and optional flags', () => {
    const parsedRun = parseCliArgs(['run', 'scraper', '--config', 'test.json', '--exporters', 'video,audio', '--out', './dist']);
    expect(parsedRun.command).toBe('run');
    expect(parsedRun.pipelineId).toBe('scraper');
    expect(parsedRun.configPath).toBe('test.json');
    expect(parsedRun.exporters).toEqual(['video', 'audio']);
    expect(parsedRun.outDir).toBe('./dist');

    const parsedStream = parseCliArgs(['stream', 'ambient', '--rtmp', 'rtmp://live.twitch.tv/app/streamkey', '--duration', '30']);
    expect(parsedStream.command).toBe('stream');
    expect(parsedStream.pipelineId).toBe('ambient');
    expect(parsedStream.rtmpUrl).toBe('rtmp://live.twitch.tv/app/streamkey');
    expect(parsedStream.duration).toBe(30);

    const parsedServe = parseCliArgs(['serve', '--port', '8080']);
    expect(parsedServe.command).toBe('serve');
    expect(parsedServe.port).toBe(8080);

    const parsedHelp = parseCliArgs(['--help']);
    expect(parsedHelp.command).toBe('help');

    const parsedList = parseCliArgs(['list']);
    expect(parsedList.command).toBe('list');
  });

  it('preserves legacy story folder arguments seamlessly', () => {
    const parsedLegacy = parseCliArgs(['./sample-story']);
    expect(parsedLegacy.command).toBe('run');
    expect(parsedLegacy.pipelineId).toBe('story');
    expect(parsedLegacy.configPath).toBe('./sample-story');
  });

  it('executes list and help commands with clean success return', async () => {
    const listRes = await runCli(['list']);
    expect(listRes.success).toBe(true);
    expect(listRes.command).toBe('list');

    const helpRes = await runCli(['help']);
    expect(helpRes.success).toBe(true);
    expect(helpRes.command).toBe('help');
  });

  it('validates missing RTMP url for stream command defensively', async () => {
    const streamRes = await runCli(['stream', 'ambient']);
    expect(streamRes.success).toBe(false);
    expect(streamRes.error).toBe('Missing --rtmp flag');
  });

  it('runs Database Templating pipeline (run 2) via CLI dispatcher', async () => {
    const testOut = path.resolve(process.cwd(), 'autogenerated', 'cli-tests', 'db');
    const res = await runCli(['run', '2', '--out', testOut]);
    expect(res.ir).toBeDefined();
    expect(res.ir.pipelineId).toBe('db-templating');
    expect(res.outputPaths.length).toBeGreaterThan(0);
  });

  it('runs Rule & Math Logic pipeline (run 5) via CLI dispatcher', async () => {
    const testOut = path.resolve(process.cwd(), 'autogenerated', 'cli-tests', 'math');
    const res = await runCli(['run', '5', '--out', testOut]);
    expect(res.ir).toBeDefined();
    expect(res.ir.pipelineId).toBe('rule-logic');
    expect(res.outputPaths.length).toBeGreaterThan(0);
  });

  it('runs Ambient Stream pipeline (run 6) via CLI dispatcher', async () => {
    const testOut = path.resolve(process.cwd(), 'autogenerated', 'cli-tests', 'ambient');
    const res = await runCli(['run', '6', '--out', testOut, '--duration', '3']);
    expect(res.ir).toBeDefined();
    expect(res.ir.pipelineId).toBe('ambient-loops');
    expect(res.outputPaths.length).toBeGreaterThan(0);
  });

  it('starts Webhook Ingestion daemon via CLI serve command', async () => {
    const serveRes = await runCli(['serve', '--port', '3999']);
    expect(serveRes.success).toBe(true);
    expect(serveRes.port).toBe(3999);
    expect(serveRes.server).toBeDefined();
    serveRes.server.stop();
  });
});
