import { describe, test, expect } from 'bun:test';
import fs from 'fs';
import path from 'path';
import { ModelHandleRegistry } from '../packages/core/src/AssetContext';
import { LegacyStoryConfigAdapter } from '../packages/ir/src/LegacyStoryConfigAdapter';
import { FFmpegManager } from '../packages/core/src/FFmpegManager';
import { FFI, freePtr, makeAVRational, safeArrayBuffer } from '../packages/core/src/ffmpeg-ffi';

describe('Performance Benchmarking Suite Tests', () => {
  test('Benchmark files exist in benchmarks directory tree', () => {
    const root = process.cwd();
    expect(fs.existsSync(path.join(root, 'benchmarks', 'run-all.ts'))).toBe(true);
    expect(fs.existsSync(path.join(root, 'benchmarks', 'micro', 'runner.ts'))).toBe(true);
    expect(fs.existsSync(path.join(root, 'benchmarks', 'micro', 'ffi-dsp.bench.ts'))).toBe(true);
    expect(fs.existsSync(path.join(root, 'benchmarks', 'micro', 'ir-adaptation.bench.ts'))).toBe(true);
    expect(fs.existsSync(path.join(root, 'benchmarks', 'micro', 'canvas-overlay.bench.ts'))).toBe(true);
    expect(fs.existsSync(path.join(root, 'benchmarks', 'micro', 'model-registry.bench.ts'))).toBe(true);
    expect(fs.existsSync(path.join(root, 'benchmarks', 'micro', 'ffmpeg-ffi.bench.ts'))).toBe(true);
    expect(fs.existsSync(path.join(root, 'benchmarks', 'http', 'load-test-webhook.ts'))).toBe(true);
    expect(fs.existsSync(path.join(root, 'benchmarks', 'cli', 'benchmark-cli.ts'))).toBe(true);
  });

  test('Package.json benchmark scripts are configured', () => {
    const pkg = JSON.parse(fs.readFileSync(path.join(process.cwd(), 'package.json'), 'utf-8'));
    expect(pkg.scripts.bench).toBe('bun run benchmarks/run-all.ts');
    expect(pkg.scripts['bench:micro']).toBe('bun run benchmarks/micro/runner.ts');
    expect(pkg.scripts['bench:http']).toBe('bun run benchmarks/http/load-test-webhook.ts');
    expect(pkg.scripts['bench:cli']).toBe('bun run benchmarks/cli/benchmark-cli.ts');
    expect(pkg.devDependencies.mitata).toBeDefined();
  });

  test('Microbenchmark targets execute without throwing errors', () => {
    // Test ModelHandleRegistry microbenchmark target logic
    const registry = ModelHandleRegistry.getInstance();
    registry.registerHandle('test_model_bench', { dispose: () => {} }, 128);
    expect(registry.getHandle('test_model_bench')).toBeDefined();
    expect(registry.getTotalMemoryUsageMB()).toBeGreaterThanOrEqual(128);

    // Test LegacyStoryConfigAdapter microbenchmark target logic
    const ir = LegacyStoryConfigAdapter.adapt({
      name: 'Test Story',
      scenes: [{ text: 'Hello benchmark' }],
    });
    expect(ir.schemaVersion).toBe('3.1.0');
    expect(ir.extendedChunks.length).toBe(1);
  });

  test('FFmpeg bun:ffi zero-copy pointer operations function correctly in microbenchmarks', async () => {
    await FFmpegManager.prepare();
    const framePtr = FFI.avutil.av_frame_alloc();
    expect(framePtr).not.toBe(0n);
    expect(framePtr).not.toBe(0);

    const buf = safeArrayBuffer(framePtr, 0, 64);
    expect(buf.byteLength).toBe(64);

    freePtr(FFI.avutil.av_frame_free, framePtr);

    const rescale = FFI.avutil.av_rescale_q(100n, makeAVRational(1, 30), makeAVRational(1, 1000));
    expect(rescale).toBeGreaterThan(0n);
  });

  test('Benchmark output directories can be populated', () => {
    const outDir = path.join(process.cwd(), 'autogenerated', 'benchmarks');
    if (!fs.existsSync(outDir)) {
      fs.mkdirSync(outDir, { recursive: true });
    }
    expect(fs.existsSync(outDir)).toBe(true);
  });
});
