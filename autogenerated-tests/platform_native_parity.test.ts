import { describe, it, expect, beforeEach } from 'bun:test';
import fs from 'fs';
import path from 'path';
import {
  UniversalCanvasProvider,
  CanvasAssetLoader,
  type ICanvasInstance,
  type ICanvasAdapter,
  type ICanvasContext2D,
  MediaEngineRegistry,
  type IVideoDecoder,
} from '../packages/core/src/isomorphic';
import { NapiCanvasAdapter } from '../packages/core/src/native';
import { WebCanvasAdapter } from '../packages/core/src/web';
import { FFIVideoDecoder } from '../packages/core/src/ffmpeg-ffi/FFIVideoDecoder';

describe('Iteration 14: Platform-Dependent Native Library Decoupling & Parity Suite', () => {
  beforeEach(() => {
    UniversalCanvasProvider.unregisterAll();
    UniversalCanvasProvider.setEngine('auto');
  });

  describe('Pillar 1 & 4: Static Linter Guardrails & Boundary Verification', () => {
    it('should assert zero direct @napi-rs/canvas imports outside @acc/core-native', () => {
      const forbiddenFiles: string[] = [];
      const scan = (dir: string) => {
        if (!fs.existsSync(dir)) return;
        const entries = fs.readdirSync(dir, { withFileTypes: true });
        for (const entry of entries) {
          const fullPath = path.join(dir, entry.name);
          if (entry.isDirectory()) {
            if (!['node_modules', 'dist', '.git', 'autogenerated-tests', 'benchmarks', 'scripts', '.hutch'].includes(entry.name)) {
              scan(fullPath);
            }
          } else if (entry.isFile() && (entry.name.endsWith('.ts') || entry.name.endsWith('.tsx'))) {
            const normalized = fullPath.replace(/\\/g, '/');
            if (
              !normalized.includes('packages/core/src/native') &&
              !normalized.includes('packages/core-native')
            ) {
              const code = fs.readFileSync(fullPath, 'utf-8');
              if (/['"]@napi-rs\/canvas['"]/.test(code)) {
                forbiddenFiles.push(normalized);
              }
            }
          }
        }
      };

      scan(path.resolve(process.cwd(), 'apps'));
      scan(path.resolve(process.cwd(), 'packages'));

      expect(forbiddenFiles).toEqual([]);
    });

    it('should assert zero bun:ffi imports in client & isomorphic packages', () => {
      const leakedFFIFiles: string[] = [];
      const clientDirs = [
        path.resolve(process.cwd(), 'apps/studio/src'),
        path.resolve(process.cwd(), 'packages/effect-engines/src'),
        path.resolve(process.cwd(), 'packages/core/src/isomorphic'),
        path.resolve(process.cwd(), 'packages/core/src/web'),
      ];

      const scan = (dir: string) => {
        if (!fs.existsSync(dir)) return;
        const entries = fs.readdirSync(dir, { withFileTypes: true });
        for (const entry of entries) {
          const fullPath = path.join(dir, entry.name);
          if (entry.isDirectory()) {
            if (!['node_modules', 'dist'].includes(entry.name)) {
              scan(fullPath);
            }
          } else if (entry.isFile() && (entry.name.endsWith('.ts') || entry.name.endsWith('.tsx'))) {
            const code = fs.readFileSync(fullPath, 'utf-8');
            if (/['"]bun:ffi['"]/.test(code)) {
              leakedFFIFiles.push(fullPath.replace(/\\/g, '/'));
            }
          }
        }
      };

      for (const d of clientDirs) {
        scan(d);
      }

      expect(leakedFFIFiles).toEqual([]);
    });
  });

  describe('Pillar 2: Universal Canvas Contract & Adapter Polymorphism', () => {
    it('should verify NapiCanvasAdapter implements ICanvasAdapter contract', () => {
      const adapter = new NapiCanvasAdapter();
      expect(adapter.name).toBe('node-napi-rs');
      expect(adapter.environment).toBe('node');
      expect(adapter.isSupported()).toBe(true);

      const canvas = adapter.createCanvas(320, 240);
      expect(canvas.width).toBe(320);
      expect(canvas.height).toBe(240);
      expect(typeof canvas.getContext).toBe('function');
      expect(typeof canvas.toBuffer).toBe('function');
      expect(typeof canvas.toDataURL).toBe('function');

      const ctx = canvas.getContext('2d');
      expect(ctx).toBeDefined();
      expect(typeof ctx.fillRect).toBe('function');
      expect(typeof ctx.clearRect).toBe('function');
    });

    it('should verify WebCanvasAdapter implements ICanvasAdapter contract', () => {
      const adapter = new WebCanvasAdapter();
      expect(adapter.name).toBe('web-canvas');
      expect(adapter.environment).toBe('web');
      // In Bun test runner, check support based on global OffscreenCanvas/document
      const isExpected =
        typeof (globalThis as any).OffscreenCanvas !== 'undefined' ||
        typeof document !== 'undefined';
      expect(adapter.isSupported()).toBe(isExpected);
    });

    it('should register and resolve adapters seamlessly via UniversalCanvasProvider', () => {
      const napi = new NapiCanvasAdapter();
      UniversalCanvasProvider.registerAdapter(napi, true);

      expect(UniversalCanvasProvider.getAdapter('node')).toBe(napi);
      expect(UniversalCanvasProvider.getAdapter('node-napi-rs')).toBe(napi);

      const canvas = UniversalCanvasProvider.createCanvas(100, 100);
      expect(canvas.width).toBe(100);
      expect(canvas.height).toBe(100);
    });

    it('should allow dynamic engine switching and singleton ergonomics', () => {
      const napi = new NapiCanvasAdapter();
      UniversalCanvasProvider.registerAdapter(napi, true);

      UniversalCanvasProvider.setEngine('node');
      expect(UniversalCanvasProvider.getInstance().getEngine()).toBe('node');

      const canvas = UniversalCanvasProvider.getInstance().createCanvas(64, 64);
      expect(canvas.width).toBe(64);
      expect(canvas.height).toBe(64);
    });
  });

  describe('Pillar 3: Pixel & Rendering Fidelity Parity', () => {
    it('should render 2D primitives and produce byte-accurate RGBA buffers', () => {
      const adapter = new NapiCanvasAdapter();
      const canvas = adapter.createCanvas(64, 64);
      const ctx = canvas.getContext('2d');

      // 1. Fill solid background (red: RGBA 255, 0, 0, 255)
      ctx.fillStyle = '#ff0000';
      ctx.fillRect(0, 0, 64, 64);

      // 2. Draw centered blue square (blue: RGBA 0, 0, 255, 255)
      ctx.fillStyle = '#0000ff';
      ctx.fillRect(16, 16, 32, 32);

      // Extract raw buffer
      const raw = canvas.toBuffer('raw');
      expect(raw.length).toBe(64 * 64 * 4); // 16,384 bytes

      // Top-left pixel should be pure red
      expect(raw[0]).toBe(255);
      expect(raw[1]).toBe(0);
      expect(raw[2]).toBe(0);
      expect(raw[3]).toBe(255);

      // Center pixel (32, 32) should be pure blue
      const centerIdx = (32 * 64 + 32) * 4;
      expect(raw[centerIdx]).toBe(0);
      expect(raw[centerIdx + 1]).toBe(0);
      expect(raw[centerIdx + 2]).toBe(255);
      expect(raw[centerIdx + 3]).toBe(255);

      // data() method parity
      if (canvas.data) {
        const directData = canvas.data();
        expect(directData.length).toBe(64 * 64 * 4);
        expect(directData[centerIdx + 2]).toBe(255);
      }
    });

    it('should extract raw pixels uniformly via CanvasAssetLoader', () => {
      const adapter = new NapiCanvasAdapter();
      UniversalCanvasProvider.registerAdapter(adapter, true);

      const canvas = UniversalCanvasProvider.createCanvas(32, 32);
      const ctx = canvas.getContext('2d');
      ctx.fillStyle = '#00ff00';
      ctx.fillRect(0, 0, 32, 32);

      const pixels = CanvasAssetLoader.extractRawPixels(canvas);
      expect(pixels instanceof Uint8Array).toBe(true);
      expect(pixels.length).toBe(32 * 32 * 4);
      expect(pixels[0]).toBe(0);
      expect(pixels[1]).toBe(255);
      expect(pixels[2]).toBe(0);
      expect(pixels[3]).toBe(255);
    });

    it('should generate valid PNG buffer and data URL', () => {
      const adapter = new NapiCanvasAdapter();
      const canvas = adapter.createCanvas(16, 16);
      const ctx = canvas.getContext('2d');
      ctx.fillStyle = '#ffffff';
      ctx.fillRect(0, 0, 16, 16);

      const pngBuf = canvas.toBuffer('image/png');
      expect(pngBuf.length).toBeGreaterThan(0);
      // PNG header magic: 0x89, 'P', 'N', 'G'
      expect(pngBuf[0]).toBe(0x89);
      expect(pngBuf[1]).toBe(0x50);
      expect(pngBuf[2]).toBe(0x4e);
      expect(pngBuf[3]).toBe(0x47);

      const dataUrl = canvas.toDataURL?.('image/png');
      expect(typeof dataUrl).toBe('string');
      expect(dataUrl!.startsWith('data:image/png;base64,')).toBe(true);
    });
  });

  describe('Pillar 4: Media Engine & Video Decoder Decoupling', () => {
    it('should verify FFIVideoDecoder implements IVideoDecoder contract with ICanvasInstance', () => {
      const decoder = new FFIVideoDecoder('dummy.mp4', 1280, 720);
      expect(typeof decoder.open).toBe('function');
      expect(typeof decoder.close).toBe('function');
      expect(typeof decoder.readNextFrame).toBe('function');
      expect(typeof decoder.getNextFrame).toBe('function');
    });

    it('should verify MediaEngineRegistry operates isomorphically without native imports', () => {
      MediaEngineRegistry.reset();
      expect(MediaEngineRegistry.listAvailable()).toEqual([]);

      // Mock strategy to verify registration without native FFI
      const mockStrategy: any = {
        id: 'bun-ffi',
        name: 'Mock Strategy',
        capabilities: {
          supportsZeroCopyFFI: true,
          supportsComplexFilters: false,
          supportsRawFrameStream: true,
          supportsBrowserRuntime: false,
          requiresNativeBinaries: true,
        },
        validatePrerequisites: () => {},
      };

      MediaEngineRegistry.register(mockStrategy);
      expect(MediaEngineRegistry.has('bun-ffi')).toBe(true);
      expect(MediaEngineRegistry.get('bun-ffi')).toBe(mockStrategy);
    });
  });
});
