export function convertSFXToPreset(def: SoundEffectDefinition): StagingPreset {
  const durationFrames = Math.max(1, Math.round(def.durationSec * 30));
  return {
    id: `preset_${def.id}`,
    category: 'sfx',
    name: def.name,
    badge: def.badge,
    description: def.description,
    iconName: def.bank === 'riser' ? 'Music' : def.bank === 'cyber' ? 'Zap' : 'Volume2',
    targetTrackId: 'track-audio',
    targetTrackType: 'audio',
    targetTrackName: 'Master Audio Track',
    durationSec: def.durationSec,
    createSequence: ({ startFrame, durationFrames: customDuration, normX = 0.5, normY = 0.5 }) => ({
      id: `seq-sfx-${def.id}-${Date.now()}`,
      type: 'audio',
      time: {
        start: startFrame,
        duration: customDuration || durationFrames,
      },
      modifiers: [
        {
          type: 'sfx/procedural',
          target: 'audio',
          params: { ...def.params },
        },
        {
          type: 'transform',
          target: ['audio'],
          params: {
            normX,
            normY,
            x: 0,
            y: 0,
            scale: 1.0,
            rotation: 0,
          },
        },
      ],
    }),
  };
}

