import { parseArgs } from 'util';
import {
  SoundRegistryManager,
  renderSoundEffect,
  renderCompositeSound,
  FFmpegManager,
  Logger,
} from '@acc/core';
import {
  intro,
  outro,
  promptSelect,
  promptText,
  promptNumber,
  spinner,
} from '../prompts';
import path from 'path';
import fs from 'fs';

export interface SfxHeadlessValues {
  effect?: string;
  variant?: string;
  'sub-variant'?: string;
  composite?: string;
  duration?: string;
  'ai-model'?: string;
  'custom-prompt'?: string;
}

export async function generateHeadless(values: SfxHeadlessValues): Promise<void> {
  if (!values.composite && !values['custom-prompt'] && (!values.effect || !values.variant || !values['sub-variant'])) {
    Logger.error('sfx', 'Error: Either --composite, --custom-prompt, OR (--effect, --variant, and --sub-variant) is required.');
    process.exit(1);
  }

  const aiModel = values['ai-model'] || 'audioldm2-base';
  const registry = new SoundRegistryManager(aiModel);
  const outDir = path.resolve(process.cwd(), 'autogenerated', 'sound-effects', 'mixed');
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }

  try {
    if (values.composite) {
      const compositeName = values.composite.toLowerCase();
      Logger.info('sfx', `Composite:  ${compositeName}`);
      const outputs = await renderCompositeSound(registry, compositeName, outDir);
      Logger.info('sfx', `✅ Composite '${compositeName}' successfully generated!`);
      outputs.forEach((o) => Logger.info('sfx', ` - Audio:    ${o}`));
    } else if (values['custom-prompt']) {
      const duration = values.duration ? parseFloat(values.duration) : 3.0;
      const customPrompt = values['custom-prompt'];
      Logger.info('sfx', `Prompt:     ${customPrompt}`);
      const output = await renderSoundEffect(registry, 'custom', 'custom', 'custom', duration, outDir, customPrompt);
      Logger.info('sfx', `✅ Successfully completed audio synthesis!\nAudio:    ${output}`);
    } else if (values.effect) {
      const effectName = values.effect.toLowerCase();
      const variantName = values.variant!.toLowerCase();
      const subVariantName = values['sub-variant']!.toLowerCase();
      const duration = values.duration ? parseFloat(values.duration) : 3.0;

      const output = await renderSoundEffect(registry, effectName, variantName, subVariantName, duration, outDir);
      Logger.info('sfx', `✅ Successfully completed audio synthesis!\nAudio:    ${output}`);
    }
  } catch (err: any) {
    Logger.error('sfx', `❌ Error: ${err.message}`);
    process.exit(1);
  }
}

export async function startWizard(): Promise<void> {
  intro('🔊 Sound Effects Interactive Console');

  const mode = await promptSelect({
    message: 'Select operation mode:',
    options: [
      { label: 'Generate Predefined Effect/Layer', value: 'predefined', hint: 'DSP procedural sound synthesis' },
      { label: 'Generate Combinatorial Composite', value: 'composite', hint: 'Multi-layer polyrhythmic SFX stack' },
      { label: 'Generate with Custom Prompt', value: 'custom', hint: 'Local AI AudioLDM2 neural synthesis' },
      { label: 'Exit', value: 'exit' },
    ],
  });

  if (mode === 'exit') {
    outro('Goodbye!');
    process.exit(0);
  }

  const aiModel = await promptSelect({
    message: 'Select AI Model Engine:',
    options: [
      { label: 'AudioLDM2 Base', value: 'audioldm2-base', hint: 'Faster inference, standard quality' },
      { label: 'AudioLDM2 Large', value: 'audioldm2-large', hint: 'High fidelity neural synthesis' },
    ],
  });

  const registry = new SoundRegistryManager(aiModel);
  const outDir = path.resolve(process.cwd(), 'autogenerated', 'sound-effects', 'mixed');
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }

  const spin = spinner();

  try {
    if (mode === 'composite') {
      const rawComposites: string[] = (registry as any).getAvailableComposites?.() || [];
      if (rawComposites.length === 0) {
        outro('No composites defined in registry.');
        return;
      }

      const composite = await promptSelect({
        message: 'Select Composite Preset:',
        options: rawComposites.map((c) => ({ label: c, value: c })),
      });

      spin.start(`Rendering composite '${composite}'...`);
      const outputs = await renderCompositeSound(registry, composite, outDir);
      spin.stop(`Composite rendered!`);
      outro(`✅ Composite '${composite}' generated successfully!\n` + outputs.map((o) => ` - Audio: ${o}`).join('\n'));
    } else if (mode === 'custom') {
      const promptText = await promptText({
        message: 'Enter description / prompt for the sound effect:',
        placeholder: 'cinematic bass drop with ambient reverb',
      });
      const duration = await promptNumber({
        message: 'Duration in seconds:',
        defaultValue: 3.0,
        min: 0.1,
        max: 60,
      });

      spin.start('Synthesizing custom neural sound effect...');
      const output = await renderSoundEffect(registry, 'custom', 'custom', 'custom', duration, outDir, promptText);
      spin.stop('Sound effect synthesized!');
      outro(`✅ Sound effect synthesized successfully!\nAudio: ${output}`);
    } else if (mode === 'predefined') {
      const effects: string[] = (registry as any).getAvailableEffects?.() || ['ui', 'cinematic', 'scifi', 'foley', 'diegetic', 'fauna'];
      const effect = await promptSelect({
        message: 'Select Effect Category:',
        options: effects.map((e) => ({ label: e, value: e })),
      });

      const variants: string[] = (registry as any).getAvailableVariants?.(effect) || ['click', 'hover', 'success'];
      const variant = await promptSelect({
        message: 'Select Variant:',
        options: variants.map((v) => ({ label: v, value: v })),
      });

      const subVariants: string[] = (registry as any).getAvailableSubVariants?.(effect, variant) || ['plastic_pop', 'glass_haptic'];
      const subVariant = await promptSelect({
        message: 'Select Sub-Variant:',
        options: subVariants.map((sv) => ({ label: sv, value: sv })),
      });

      const duration = await promptNumber({
        message: 'Duration in seconds:',
        defaultValue: 3.0,
        min: 0.1,
        max: 60,
      });

      spin.start(`Synthesizing '${effect} / ${variant} / ${subVariant}'...`);
      const output = await renderSoundEffect(registry, effect, variant, subVariant, duration, outDir);
      spin.stop('Sound effect generated!');
      outro(`✅ Sound effect generated successfully!\nAudio: ${output}`);
    }
  } catch (err: any) {
    spin.stop('Synthesis failed');
    outro(`❌ Error: ${err.message}`);
    process.exit(1);
  }
}

export async function runSFXCommand(args: string[] = process.argv.slice(2)): Promise<void> {
  await FFmpegManager.prepare();

  const isHeadless = args.some(
    (arg) =>
      arg.startsWith('-e') ||
      arg.startsWith('--effect') ||
      arg.startsWith('-c') ||
      arg.startsWith('--composite') ||
      arg.startsWith('-p') ||
      arg.startsWith('--custom-prompt')
  );

  if (isHeadless) {
    const { values } = parseArgs({
      args,
      options: {
        effect: { type: 'string', short: 'e' },
        variant: { type: 'string', short: 'v' },
        'sub-variant': { type: 'string', short: 's' },
        composite: { type: 'string', short: 'c' },
        duration: { type: 'string', short: 'd' },
        'ai-model': { type: 'string', default: 'audioldm2-base' },
        'custom-prompt': { type: 'string', short: 'p' },
      },
      allowPositionals: true,
    });
    await generateHeadless(values as SfxHeadlessValues);
  } else {
    await startWizard();
  }
}

if (import.meta.main) {
  runSFXCommand();
}
