import { parseArgs } from 'util';
import { FFmpegManager, Logger, askChoice, askQuestion, askYesNo, closeInteractiveConsole, intro, outro, isCancel, cancel } from '@acc/core';
import { RegistryManager, renderSoundEffect, renderCompositeSound } from '@acc/effect-engines';
import path from 'path';
import fs from 'fs';
import * as prompt from '@clack/prompts';

export async function generateHeadless(values: any) {
  if (!values.composite && !values['custom-prompt'] && (!values.effect || !values.variant || !values['sub-variant'])) {
    Logger.error('sfx', 'Error: Either --composite, --custom-prompt, OR (--effect, --variant, and --sub-variant) is required.');
    process.exit(1);
  }

  const aiModel = values['ai-model'] || 'audioldm2-base';

  // Instantiate Registry WITHOUT engine mode (Smart Routing applies)
  const registry = new RegistryManager(aiModel);
  const outDir = path.resolve(process.cwd(), 'autogenerated', 'sound-effects', 'mixed');
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }

  try {
    if (values.composite) {
      const compositeName = values.composite.toLowerCase();
      intro(`=== Sound Effects Composite Generator ===`);
      Logger.info('sfx', `Composite:  ${compositeName}`);

      const outputs = await renderCompositeSound(registry, compositeName, outDir);
      outro(`\n✅ Composite '${compositeName}' successfully generated!`);
      outputs.forEach(o => console.log(` - Audio:    ${o}`));
    } else if (values['custom-prompt']) {
      const duration = values.duration ? parseFloat(values.duration) : 3.0;
      const customPrompt = values['custom-prompt'];

      intro(`=== Sound Effect Generator (Custom Prompt) ===`);
      Logger.info('sfx', `Prompt:     ${customPrompt}`);

      const output = await renderSoundEffect(registry, 'custom', 'custom', 'custom', duration, outDir, customPrompt);
      outro(`\n✅ Successfully completed audio synthesis!\nAudio:    ${output}`);
    } else if (values.effect) {
      const effectName = values.effect.toLowerCase();
      const variantName = values.variant!.toLowerCase();
      const subVariantName = values['sub-variant']!.toLowerCase();
      const duration = values.duration ? parseFloat(values.duration) : 3.0;

      intro(`=== Sound Effect Generator ===`);

      const output = await renderSoundEffect(registry, effectName, variantName, subVariantName, duration, outDir);
      outro(`\n✅ Successfully completed audio synthesis!\nAudio:    ${output}`);
    }
  } catch (err: any) {
    outro(`❌ Error: ${err.message}`);
    process.exit(1);
  }
}

export async function startWizard() {
  console.log('\n============================================');
  console.log('🔊 Sound Effects Interactive Console');
  console.log('============================================');

  const mode = await askChoice('Select operation mode:', [
    'Generate Predefined Effect/Layer',
    'Generate Combinatorial Composite',
    'Generate with Custom Prompt (Local AI AudioLDM2)',
    'Exit'
  ]);

  if (mode === 'Exit') {
    closeInteractiveConsole();
    process.exit(0);
  }

  const aiModel = await askChoice('Select AI Model Engine:', [
    'audioldm2-base',
    'audioldm2-large'
  ]);

  const registry = new RegistryManager(aiModel);
  const outDir = path.resolve(process.cwd(), 'autogenerated', 'sound-effects', 'mixed');
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }

  try {
    if (mode === 'composite') {
      const composites = (registry as any).getAvailableComposites?.() || [];
      if (composites.length === 0) {
        console.log('No composites defined in registry.');
        closeInteractiveConsole();
        return;
      }

      const composite = await askChoice('Select Composite Preset:', composites);
      console.log(`\nRendering composite '${composite}'...`);
      const outputs = await renderCompositeSound(registry, composite, outDir);
      console.log(`\n✅ Composite '${composite}' generated successfully!`);
      outputs.forEach(o => console.log(` - Audio:    ${o}`));

    } else if (mode === 'Generate with Custom Prompt (Local AI AudioLDM2)') {
      const prompt = await askQuestion('Enter description / prompt for the sound effect: ');
      const durStr = await askQuestion('Duration in seconds (default: 3.0): ');
      const duration = durStr.trim() ? parseFloat(durStr) : 3.0;

      console.log(`\nSynthesizing custom sound effect...`);
      const output = await renderSoundEffect(registry, 'custom', 'custom', 'custom', duration, outDir, prompt);
      console.log(`\n✅ Sound effect synthesized successfully!\nAudio:    ${output}`);

    } else if (mode === 'predefined') {
      const effects = (registry as any).getAvailableEffects?.() || ['ui', 'cinematic', 'scifi', 'foley', 'diegetic', 'fauna'];
      const effect = await prompt.select({
        message: 'Select Effect Category:',
        options: effects.map((e: string) => ({ label: e, value: e })),
      });

      if (isCancel(effect)) {
        cancel('Operation cancelled.');
        process.exit(0);
      }

      const variants = (registry as any).getAvailableVariants?.(effect) || ['click', 'hover', 'success'];
      const variant = await prompt.select({
        message: 'Select Variant:',
        options: variants.map((v: string) => ({ label: v, value: v })),
      });

      if (isCancel(variant)) {
        cancel('Operation cancelled.');
        process.exit(0);
      }

      const subVariants = (registry as any).getAvailableSubVariants?.(effect, variant) || ['plastic_pop', 'glass_haptic'];
      const subVariant = await prompt.select({
        message: 'Select Sub-Variant:',
        options: subVariants.map((sv: string) => ({ label: sv, value: sv })),
      });

      if (isCancel(subVariant)) {
        cancel('Operation cancelled.');
        process.exit(0);
      }

      const durStr = await prompt.text({
        message: 'Duration in seconds (default: 3.0):',
        placeholder: '3.0',
        defaultValue: '3.0',
      });

      if (isCancel(durStr)) {
        cancel('Operation cancelled.');
        process.exit(0);
      }

      const duration = durStr.trim() ? parseFloat(durStr) : 3.0;

      console.log(`\nSynthesizing '${effect} / ${variant} / ${subVariant}'...`);
      const output = await renderSoundEffect(registry, effect, variant, subVariant, duration, outDir);
      console.log(`\n✅ Sound effect generated successfully!\nAudio:    ${output}`);
    }
  } catch (err: any) {
    console.error(`\n❌ Error: ${err.message}`);
  } finally {
    closeInteractiveConsole();
  }
}

export async function runSFXCommand(args: string[] = process.argv.slice(2)) {
  await FFmpegManager.prepare();

  const isHeadless = args.some(arg =>
    arg.startsWith('-e') || arg.startsWith('--effect') ||
    arg.startsWith('-c') || arg.startsWith('--composite') ||
    arg.startsWith('-p') || arg.startsWith('--custom-prompt')
  );

  if (isHeadless) {
    const { values } = parseArgs({
      args,
      options: {
        effect: { type: 'string', short: 'e' },
        variant: { type: 'string', short: 'v' },
        'sub-variant': { type: 'string', short: 's' },
        composite: { type: 'string', short: 'c' },
        duration: { type: 'string', short: 'd' },
        'ai-model': { type: 'string', default: 'audioldm2-base' },
        'custom-prompt': { type: 'string', short: 'p' }
      },
      allowPositionals: true,
    });
    await generateHeadless(values);
  } else {
    await startWizard();
  }
}

if (import.meta.main) {
  runSFXCommand();
}
