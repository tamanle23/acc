import { parseArgs } from 'util';
import { FFmpegManager, intro, outro, spinner, note, isCancel, cancel } from '@acc/core';
import * as p from '@clack/prompts';
import { RegistryManager, renderSoundEffect, renderCompositeSound } from '@acc/effect-engines';
import path from 'path';
import fs from 'fs';

export async function generateHeadless(values: any) {
  if (!values.composite && !values['custom-prompt'] && (!values.effect || !values.variant || !values['sub-variant'])) {
    console.error('Error: Either --composite, --custom-prompt, OR (--effect, --variant, and --sub-variant) is required.');
    process.exit(1);
  }

  const aiModel = values['ai-model'] || 'audioldm2-base';

  const registry = new RegistryManager(aiModel);
  const outDir = path.resolve(process.cwd(), 'autogenerated', 'sound-effects', 'mixed');
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }

  try {
    if (values.composite) {
      const compositeName = values.composite.toLowerCase();
      console.log(`\n=== Sound Effects Composite Generator ===`);
      console.log(`Composite:  ${compositeName}`);
      
      const outputs = await renderCompositeSound(registry, compositeName, outDir);
      console.log(`\n✅ Composite '${compositeName}' successfully generated!`);
      outputs.forEach(o => console.log(` - Audio:    ${o}`));
    } else if (values['custom-prompt']) {
      const duration = values.duration ? parseFloat(values.duration) : 3.0;
      const customPrompt = values['custom-prompt'];
      
      console.log(`\n=== Sound Effect Generator (Custom Prompt) ===`);
      console.log(`Prompt:     ${customPrompt}`);
      
      const output = await renderSoundEffect(registry, 'custom', 'custom', 'custom', duration, outDir, customPrompt);
      console.log(`\n✅ Successfully completed audio synthesis!\nAudio:    ${output}`);
    } else if (values.effect) {
      const effectName = values.effect.toLowerCase();
      const variantName = values.variant!.toLowerCase();
      const subVariantName = values['sub-variant']!.toLowerCase();
      const duration = values.duration ? parseFloat(values.duration) : 3.0;

      console.log(`\n=== Sound Effect Generator ===`);
      
      const output = await renderSoundEffect(registry, effectName, variantName, subVariantName, duration, outDir);
      console.log(`\n✅ Successfully completed audio synthesis!\nAudio:    ${output}`);
    }
  } catch (err: any) {
    console.error(`\n❌ Error: ${err.message}`);
    process.exit(1);
  }
}

export async function startWizard() {
  intro('🔊 Sound Effects Interactive Console');

  const mode = await p.select({
    message: 'Select operation mode:',
    options: [
      { label: 'Generate Predefined Effect/Layer', value: 'predefined' },
      { label: 'Generate Combinatorial Composite', value: 'composite' },
      { label: 'Generate with Custom Prompt (Local AI AudioLDM2)', value: 'custom' },
      { label: 'Exit', value: 'exit' },
    ],
  });

  if (isCancel(mode) || mode === 'exit') {
    cancel('Operation cancelled.');
    process.exit(0);
  }

  const aiModel = await p.select({
    message: 'Select AI Model Engine:',
    options: [
      { label: 'audioldm2-base', value: 'audioldm2-base' },
      { label: 'audioldm2-large', value: 'audioldm2-large' },
    ],
  });

  if (isCancel(aiModel)) {
    cancel('Operation cancelled.');
    process.exit(0);
  }

  const registry = new RegistryManager(aiModel as string);
  const outDir = path.resolve(process.cwd(), 'autogenerated', 'sound-effects', 'mixed');
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }

  try {
    if (mode === 'composite') {
      const composites = (registry as any).getAvailableComposites?.() || [];
      if (composites.length === 0) {
        outro('No composites defined in registry.');
        return;
      }

      const composite = await p.select({
        message: 'Select Composite Preset:',
        options: composites.map((c: string) => ({ label: c, value: c })),
      });

      if (isCancel(composite)) {
        cancel('Operation cancelled.');
        process.exit(0);
      }

      const s = spinner();
      s.start(`Rendering composite '${composite}'...`);
      const outputs = await renderCompositeSound(registry, composite as string, outDir);
      s.stop(`Composite '${composite}' generated successfully!`);

      note(outputs.map(o => `Audio: ${o}`).join('\n'), 'Rendered Audio Files');
      outro('Done!');

    } else if (mode === 'custom') {
      const prompt = await p.text({
        message: 'Enter description / prompt for the sound effect:',
        placeholder: 'e.g. cinematic explosion with deep bass',
        validate: (val) => (!val || val.trim() === '' ? 'Prompt cannot be empty.' : undefined),
      });

      if (isCancel(prompt)) {
        cancel('Operation cancelled.');
        process.exit(0);
      }

      const durStr = await p.text({
        message: 'Duration in seconds (default: 3.0):',
        placeholder: '3.0',
        defaultValue: '3.0',
      });

      if (isCancel(durStr)) {
        cancel('Operation cancelled.');
        process.exit(0);
      }

      const duration = durStr.trim() ? parseFloat(durStr) : 3.0;

      const s = spinner();
      s.start('Synthesizing custom sound effect...');
      const output = await renderSoundEffect(registry, 'custom', 'custom', 'custom', duration, outDir, prompt as string);
      s.stop('Sound effect synthesized successfully!');

      note(`Audio: ${output}`, 'Generated File');
      outro('Done!');

    } else if (mode === 'predefined') {
      const effects = (registry as any).getAvailableEffects?.() || ['ui', 'cinematic', 'scifi', 'foley', 'diegetic', 'fauna'];
      const effect = await p.select({
        message: 'Select Effect Category:',
        options: effects.map((e: string) => ({ label: e, value: e })),
      });

      if (isCancel(effect)) {
        cancel('Operation cancelled.');
        process.exit(0);
      }

      const variants = (registry as any).getAvailableVariants?.(effect) || ['click', 'hover', 'success'];
      const variant = await p.select({
        message: 'Select Variant:',
        options: variants.map((v: string) => ({ label: v, value: v })),
      });

      if (isCancel(variant)) {
        cancel('Operation cancelled.');
        process.exit(0);
      }

      const subVariants = (registry as any).getAvailableSubVariants?.(effect, variant) || ['plastic_pop', 'glass_haptic'];
      const subVariant = await p.select({
        message: 'Select Sub-Variant:',
        options: subVariants.map((sv: string) => ({ label: sv, value: sv })),
      });

      if (isCancel(subVariant)) {
        cancel('Operation cancelled.');
        process.exit(0);
      }

      const durStr = await p.text({
        message: 'Duration in seconds (default: 3.0):',
        placeholder: '3.0',
        defaultValue: '3.0',
      });

      if (isCancel(durStr)) {
        cancel('Operation cancelled.');
        process.exit(0);
      }

      const duration = durStr.trim() ? parseFloat(durStr) : 3.0;

      const s = spinner();
      s.start(`Synthesizing '${effect} / ${variant} / ${subVariant}'...`);
      const output = await renderSoundEffect(registry, effect as string, variant as string, subVariant as string, duration, outDir);
      s.stop('Sound effect generated successfully!');

      note(`Audio: ${output}`, 'Generated File');
      outro('Done!');
    }
  } catch (err: any) {
    outro(`❌ Error: ${err.message}`);
  }
}

export async function runSFXCommand(args: string[] = process.argv.slice(2)) {
  await FFmpegManager.prepare();

  const isHeadless = args.some(arg =>
    arg.startsWith('-e') || arg.startsWith('--effect') ||
    arg.startsWith('-c') || arg.startsWith('--composite') ||
    arg.startsWith('-p') || arg.startsWith('--custom-prompt')
  );

  if (isHeadless) {
    const { values } = parseArgs({
      args,
      options: {
        effect: { type: 'string', short: 'e' },
        variant: { type: 'string', short: 'v' },
        'sub-variant': { type: 'string', short: 's' },
        composite: { type: 'string', short: 'c' },
        duration: { type: 'string', short: 'd' },
        'ai-model': { type: 'string', default: 'audioldm2-base' },
        'custom-prompt': { type: 'string', short: 'p' }
      },
      allowPositionals: true,
    });
    await generateHeadless(values);
  } else {
    await startWizard();
  }
}

if (import.meta.main) {
  runSFXCommand();
}
