import { parseArgs } from 'util';
import {
  RegistryManager,
  FFmpegManager,
  Logger,
  renderEffectLayer,
} from '@acc/core';
import {
  intro,
  outro,
  promptSelect,
  promptNumber,
  spinner,
} from '../prompts';
import fs from 'fs';

export interface OverlayHeadlessValues {
  effect?: string;
  variant?: string;
  composite?: string;
  duration?: string;
  fps?: string;
  width?: string;
  height?: string;
}

export async function generateHeadless(values: OverlayHeadlessValues): Promise<void> {
  if (!values.effect && !values.composite) {
    Logger.error('OverlayCommand', 'Error: Either --effect or --composite is required.');
    process.exit(1);
  }

  const registry = await RegistryManager.create();
  const outDir = './autogenerated/overlay-effects';
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }

  const layerOptions = {
    fps: values.fps ? parseInt(values.fps, 10) : undefined,
    width: values.width ? parseInt(values.width, 10) : undefined,
    height: values.height ? parseInt(values.height, 10) : undefined,
  };

  try {
    if (values.composite) {
      const compositeName = values.composite.toLowerCase();
      const compositeConfig = registry.getCompositeConfig(compositeName);
      Logger.info('OverlayCommand', `Composite:  ${compositeName}`);

      const renderPromises = compositeConfig.layers.map((layer: any) => {
        return renderEffectLayer(registry, layer.effect, layer.variant, layer.duration, outDir, layerOptions);
      });

      const outputs = await Promise.all(renderPromises);
      Logger.info(
        'OverlayCommand',
        `✅ Composite '${compositeName}' successfully generated!\n` +
          outputs.map((o: any) => ` - Video:    ${o}`).join('\n')
      );
    } else if (values.effect) {
      const effectName = values.effect.toLowerCase();
      const variantName = values.variant || 'default';
      const duration = values.duration ? parseFloat(values.duration) : 3.0;

      const output = await renderEffectLayer(registry, effectName, variantName, duration, outDir, layerOptions);
      Logger.info('OverlayCommand', `✅ Successfully completed rendering!\nVideo: ${output}`);
    }
  } catch (err: any) {
    Logger.error('OverlayCommand', `❌ Error: ${err.message}`);
    process.exit(1);
  }
}

export async function startWizard(): Promise<void> {
  intro('🎥 Overlay Effects Interactive Console');

  const mode = await promptSelect({
    message: 'Select operation mode:',
    options: [
      { label: 'Generate Single Dynamic Effect', value: 'single', hint: 'Render single procedural dynamic overlay effect' },
      { label: 'Generate Combinatorial Composite', value: 'composite', hint: 'Multi-layer polyrhythmic visual stack' },
      { label: 'Exit', value: 'exit' },
    ],
  });

  if (mode === 'exit') {
    outro('Goodbye!');
    process.exit(0);
  }

  const registry = await RegistryManager.create();
  const outDir = './autogenerated/overlay-effects';
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }

  const spin = spinner();

  try {
    if (mode === 'composite') {
      const composites = registry.getAvailableComposites();
      if (composites.length === 0) {
        outro('No composites defined in registry.');
        return;
      }

      const composite = await promptSelect({
        message: 'Select Composite Preset:',
        options: composites.map((c) => ({ label: c, value: c })),
      });
      const compositeConfig = registry.getCompositeConfig(composite);

      spin.start(`Rendering composite '${composite}' (${compositeConfig.layers.length} layers)...`);
      const renderPromises = compositeConfig.layers.map((layer: any) => {
        return renderEffectLayer(registry, layer.effect, layer.variant, layer.duration, outDir);
      });

      const outputs = await Promise.all(renderPromises);
      spin.stop('Composite render complete!');
      outro(`✅ Composite '${composite}' generated successfully!\n` + outputs.map((o: any) => ` - Video: ${o}`).join('\n'));
    } else if (mode === 'single') {
      const effects = registry.getAvailableEffects();
      const effect = await promptSelect({
        message: 'Select Effect Type:',
        options: effects.map((e) => ({ label: e, value: e })),
      });

      const variants = registry.getAvailableVariants(effect);
      const variant = await promptSelect({
        message: 'Select Variant:',
        options: variants.map((v) => ({ label: v, value: v })),
      });

      const duration = await promptNumber({
        message: 'Duration in seconds:',
        defaultValue: 3.0,
        min: 0.1,
        max: 60,
      });

      spin.start(`Rendering '${effect}' (variant: ${variant})...`);
      const output = await renderEffectLayer(registry, effect, variant, duration, outDir);
      spin.stop('Effect render complete!');
      outro(`✅ Effect generated successfully!\nVideo: ${output}`);
    }
  } catch (err: any) {
    spin.stop('Rendering failed');
    outro(`❌ Error: ${err.message}`);
    process.exit(1);
  }
}

export async function runOverlayCommand(args: string[] = process.argv.slice(2)): Promise<void> {
  await FFmpegManager.prepare();

  const isHeadless = args.some(
    (arg) =>
      arg.startsWith('-e') ||
      arg.startsWith('--effect') ||
      arg.startsWith('-c') ||
      arg.startsWith('--composite')
  );

  if (isHeadless) {
    const { values } = parseArgs({
      args,
      options: {
        effect: { type: 'string', short: 'e' },
        variant: { type: 'string', short: 'v' },
        composite: { type: 'string', short: 'c' },
        duration: { type: 'string', short: 'd' },
        fps: { type: 'string' },
        width: { type: 'string' },
        height: { type: 'string' },
      },
      allowPositionals: true,
    });
    await generateHeadless(values as OverlayHeadlessValues);
  } else {
    await startWizard();
  }
}

if (import.meta.main) {
  runOverlayCommand();
}
