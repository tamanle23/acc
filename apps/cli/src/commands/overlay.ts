import { parseArgs } from 'util';
import { RegistryManager, FFmpegManager, intro, outro, spinner, note, isCancel, cancel } from '@acc/core';
import * as p from '@clack/prompts';
import path from 'path';
import fs from 'fs';
import { renderEffectLayer } from '@acc/effect-engines';

export async function generateHeadless(values: any) {
  if (!values.effect && !values.composite) {
    console.error('Error: Either --effect or --composite is required.');
    process.exit(1);
  }

  const registry = new RegistryManager();
  
  const outDir = './autogenerated/overlay-effects';
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }

  const layerOptions = {
    fps: values.fps ? parseInt(values.fps, 10) : undefined,
    width: values.width ? parseInt(values.width, 10) : undefined,
    height: values.height ? parseInt(values.height, 10) : undefined
  };

  try {
    if (values.composite) {
      const compositeName = values.composite.toLowerCase();
      const compositeConfig = registry.getCompositeConfig(compositeName);
      
      console.log(`\n=== Combinatorial Composite Generator ===`);
      console.log(`Composite:  ${compositeName}`);
      
      const renderPromises = compositeConfig.layers.map((layer: any) => {
        return renderEffectLayer(registry, layer.effect, layer.variant, layer.duration, outDir, layerOptions);
      });

      const outputs = await Promise.all(renderPromises);
      console.log(`\n✅ Composite '${compositeName}' successfully generated!`);
      outputs.forEach((o: any) => console.log(` - Video:    ${o}`));
    } else if (values.effect) {
      const effectName = values.effect.toLowerCase();
      const variantName = values.variant || 'default';
      const duration = values.duration ? parseFloat(values.duration) : 3.0;

      console.log(`\n=== Single Dynamic Effect Generator ===`);
      const output = await renderEffectLayer(registry, effectName, variantName, duration, outDir, layerOptions);
      console.log(`\n✅ Successfully completed rendering!\nVideo:    ${output}`);
    }
  } catch (err: any) {
    console.error(`\n❌ Error: ${err.message}`);
    process.exit(1);
  }
}

export async function startWizard() {
  intro('🎥 Overlay Effects Interactive Console');

  const mode = await p.select({
    message: 'Select operation mode:',
    options: [
      { label: 'Generate Single Dynamic Effect', value: 'single' },
      { label: 'Generate Combinatorial Composite', value: 'composite' },
      { label: 'Exit', value: 'exit' },
    ],
  });

  if (isCancel(mode) || mode === 'exit') {
    cancel('Operation cancelled.');
    process.exit(0);
  }

  const registry = new RegistryManager();
  const outDir = './autogenerated/overlay-effects';
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }

  try {
    if (mode === 'composite') {
      const composites = registry.getAvailableComposites();
      if (composites.length === 0) {
        outro('No composites defined in registry.');
        return;
      }

      const composite = await p.select({
        message: 'Select Composite Preset:',
        options: composites.map((c: string) => ({ label: c, value: c })),
      });

      if (isCancel(composite)) {
        cancel('Operation cancelled.');
        process.exit(0);
      }

      const compositeConfig = registry.getCompositeConfig(composite as string);

      const s = spinner();
      s.start(`Rendering composite '${composite}' (${compositeConfig.layers.length} layers)...`);
      const renderPromises = compositeConfig.layers.map((layer: any) => {
        return renderEffectLayer(registry, layer.effect, layer.variant, layer.duration, outDir);
      });

      const outputs = await Promise.all(renderPromises);
      s.stop(`Composite '${composite}' generated successfully!`);

      note(outputs.map((o: any) => `Video: ${o}`).join('\n'), 'Rendered Files');
      outro('Done!');

    } else if (mode === 'single') {
      const effects = registry.getAvailableEffects();
      const effect = await p.select({
        message: 'Select Effect Type:',
        options: effects.map((e: string) => ({ label: e, value: e })),
      });

      if (isCancel(effect)) {
        cancel('Operation cancelled.');
        process.exit(0);
      }

      const variants = registry.getAvailableVariants(effect as string);
      const variant = await p.select({
        message: 'Select Variant:',
        options: variants.map((v: string) => ({ label: v, value: v })),
      });

      if (isCancel(variant)) {
        cancel('Operation cancelled.');
        process.exit(0);
      }

      const durStr = await p.text({
        message: 'Duration in seconds (default: 3.0):',
        placeholder: '3.0',
        defaultValue: '3.0',
      });

      if (isCancel(durStr)) {
        cancel('Operation cancelled.');
        process.exit(0);
      }

      const duration = durStr.trim() ? parseFloat(durStr) : 3.0;

      const s = spinner();
      s.start(`Rendering '${effect}' (variant: ${variant})...`);
      const output = await renderEffectLayer(registry, effect as string, variant as string, duration, outDir);
      s.stop('Effect generated successfully!');

      note(`Video: ${output}`, 'Generated File');
      outro('Done!');
    }
  } catch (err: any) {
    outro(`❌ Error: ${err.message}`);
  }
}

export async function runOverlayCommand(args: string[] = process.argv.slice(2)) {
  await FFmpegManager.prepare();

  const isHeadless = args.some(arg => 
    arg.startsWith('-e') || arg.startsWith('--effect') || 
    arg.startsWith('-c') || arg.startsWith('--composite')
  );

  if (isHeadless) {
    const { values } = parseArgs({
      args,
      options: {
        effect: { type: 'string', short: 'e' },
        variant: { type: 'string', short: 'v' },
        composite: { type: 'string', short: 'c' },
        duration: { type: 'string', short: 'd' },
        fps: { type: 'string' },
        width: { type: 'string' },
        height: { type: 'string' }
      },
      allowPositionals: true,
    });
    await generateHeadless(values);
  } else {
    await startWizard();
  }
}

if (import.meta.main) {
  runOverlayCommand();
}
