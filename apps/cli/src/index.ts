export interface CliOptions {
  command?: 'run' | 'stream' | 'serve' | 'list' | 'overlay' | 'sfx' | 'help' | 'worker' | 'ir-render';
  pipelineId?: string;
  configPath?: string;
  outDir?: string;
  exporters?: string[];
  format?: string;
  dryRun?: boolean;
  rtmpUrl?: string;
  port?: number;
  duration?: number;
  conductorUrl?: string;
  conductorSandbox?: boolean;
  chunkStart?: number;
  chunkEnd?: number;
  concurrency?: number;
  exportIr?: string;
}
import { cancel, intro, isCancel, outro, select, spinner, text } from '@clack/prompts';

const spin = spinner({

  onCancel: () => {
    Logger.info('ACC-CLI', 'Cleaning up resources...');
  },
  cancelMessage: 'Task was cancelled by user',
  errorMessage: 'Task failed unexpectedly',
  styleFrame: (frame) => `\x1b[35m${frame}\x1b[0m`,
});

export function parseCliArgs(args: string[]): CliOptions {
  const options: CliOptions = {};
  if (!args || args.length === 0) {
    options.command = 'help';
    return options;
  }

  const firstArg = args[0].toLowerCase();
  let startIndex = 0;

  if (['run', 'stream', 'serve', 'list', 'overlay', 'sfx', 'worker', 'ir-render', 'help', '--help', '-h'].includes(firstArg)) {
    if (firstArg === '--help' || firstArg === '-h') {
      options.command = 'help';
    } else {
      options.command = firstArg as any;
    }
    startIndex = 1;
  } else {
    // If first argument is not a known command, check if it's a directory or config path
    if (fs.existsSync(args[0]) || args[0].startsWith('./') || args[0].startsWith('../') || args[0].includes('/') || args[0].includes('\\')) {
      options.command = 'run';
      options.pipelineId = 'story';
      options.configPath = args[0];
      startIndex = 1;
    } else {
      // Default to help if unrecognized
      options.command = 'help';
      return options;
    }
  }

  // Parse remaining arguments
  for (let i = startIndex; i < args.length; i++) {
    const arg = args[i];

    if (arg === '-w' || arg === '--conductor-url') {
      options.conductorUrl = args[++i];
      continue;
    }
    if (arg === '-s' || arg === '--sandbox') {
      options.conductorSandbox = true;
      continue;
    }
    if (arg === '-c' || arg === '--config' || arg === '-i' || arg === '--input') {
      options.configPath = args[++i];
      continue;
    }
    if (arg === '-e' || arg === '--exporters') {
      options.exporters = (args[++i] || '').split(',').map((s) => s.trim().toLowerCase());
      continue;
    }
    if (arg === '-o' || arg === '--out' || arg === '--output') {
      options.outDir = args[++i];
      continue;
    }
    if (arg === '-f' || arg === '--format' || arg === '--container') {
      options.format = (args[++i] || '').trim().toLowerCase();
      continue;
    }
    if (arg === '-r' || arg === '--rtmp') {
      options.rtmpUrl = args[++i];
      continue;
    }
    if (arg === '-p' || arg === '--port') {
      options.port = parseInt(args[++i] || '3000', 10);
      continue;
    }
    if (arg === '-d' || arg === '--duration') {
      options.duration = parseInt(args[++i] || '0', 10);
      continue;
    }
    if (arg === '-n' || arg === '--dry-run') {
      options.dryRun = true;
      continue;
    }
    if (arg === '--chunk-start') {
      options.chunkStart = parseInt(args[++i] || '0', 10);
      continue;
    }
    if (arg === '--chunk-end') {
      options.chunkEnd = parseInt(args[++i] || '0', 10);
      continue;
    }
    if (arg === '-j' || arg === '--concurrency' || arg === '--threads') {
      options.concurrency = parseInt(args[++i] || '1', 10);
      continue;
    }
    if (arg === '--export-ir' || arg === '--dump-ir') {
      options.exportIr = args[++i] || './autogenerated/video-ir.json';
      continue;
    }
    if (arg === '-h' || arg === '--help') {
      options.command = 'help';
      break;
    }
    if (!options.pipelineId && (options.command === 'run' || options.command === 'stream')) {
      options.pipelineId = arg.trim().toLowerCase();
    }
  }

  return options;
}

