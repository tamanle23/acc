import path from 'path';
import fs from 'fs';
import { createCanvas } from '@napi-rs/canvas';
import type { PipelineIR, ContentChunk } from '@acc/ir';
import { defaultExporterDispatcher, ExporterDispatcher, MultiExportResults } from '@acc/exporters';

export interface MathProofStep {
  stepNumber: number;
  explanation: string;
  latexFormula: string;
  evaluatedResult?: string;
}

export interface RuleLogicPayload {
  problemTitle: string;
  problemStatement: string;
  category: 'calculus' | 'algebra' | 'discrete_math' | 'physics';
  steps: MathProofStep[];
  finalAnswer: string;
}

export class RuleLogicPipeline {
  private dispatcher: ExporterDispatcher;

  constructor(dispatcher?: ExporterDispatcher) {
    this.dispatcher = dispatcher || defaultExporterDispatcher;
  }

  public async run(payload: RuleLogicPayload, outDir?: string): Promise<{ ir: PipelineIR; exportResults: MultiExportResults }> {
    const targetDir = outDir || path.resolve(process.cwd(), 'autogenerated', 'rule-logic', Date.now().toString());
    if (!fs.existsSync(targetDir)) {
      fs.mkdirSync(targetDir, { recursive: true });
    }

    // 1. Render Dark Chalkboard / Manim-style Step Solution Slide (1920x1080 Landscape)
    const cardWidth = 1920;
    const cardHeight = 1080;
    const canvas = createCanvas(cardWidth, cardHeight);
    const ctx = canvas.getContext('2d');

    // Background: Dark green blackboard texture gradient
    const bgGrad = ctx.createLinearGradient(0, 0, 0, cardHeight);
    bgGrad.addColorStop(0, '#0a1d13');
    bgGrad.addColorStop(1, '#05110a');
    ctx.fillStyle = bgGrad;
    ctx.fillRect(0, 0, cardWidth, cardHeight);

    // Blackboard wooden frame border
    ctx.strokeStyle = '#3b2210';
    ctx.lineWidth = 20;
    ctx.strokeRect(10, 10, cardWidth - 20, cardHeight - 20);

    // Inner chalkboard edge line
    ctx.strokeStyle = 'rgba(255, 255, 255, 0.15)';
    ctx.lineWidth = 2;
    ctx.strokeRect(30, 30, cardWidth - 60, cardHeight - 60);

    // Header badge
    ctx.fillStyle = '#10b981';
    ctx.fillRect(60, 50, 260, 40);
    ctx.fillStyle = '#ffffff';
    ctx.font = 'bold 20px monospace';
    ctx.fillText(`Q.E.D. RULE SOLVER`, 80, 77);

    // Problem Statement
    ctx.fillStyle = '#ffffff';
    ctx.font = 'bold 44px sans-serif';
    ctx.fillText(payload.problemTitle, 60, 140);

    ctx.font = 'italic 28px sans-serif';
    ctx.fillStyle = '#94a3b8';
    ctx.fillText(`Given: ${payload.problemStatement}`, 60, 190);

    // Steps breakdown (Manim style chalk equations)
    let y = 260;
    payload.steps.slice(0, 4).forEach((step) => {
      // Step number & rationale
      ctx.font = 'bold 26px sans-serif';
      ctx.fillStyle = '#38bdf8';
      ctx.fillText(`Step ${step.stepNumber}: ${step.explanation}`, 60, y);
      y += 40;

      // Formula (in monospace chalkboard font)
      ctx.fillStyle = '#fef08a'; // Chalk yellow
      ctx.font = '32px monospace';
      ctx.fillText(`   ${step.latexFormula}`, 60, y);

      if (step.evaluatedResult) {
        ctx.fillStyle = '#86efac';
        ctx.fillText(` => ${step.evaluatedResult}`, 60 + ctx.measureText(`   ${step.latexFormula}`).width + 20, y);
      }

      y += 65;
    });

    // Boxed Final Answer
    y = Math.min(y + 20, cardHeight - 160);
    ctx.fillStyle = 'rgba(16, 185, 129, 0.1)';
    ctx.fillRect(60, y, 700, 75);
    ctx.strokeStyle = '#10b981';
    ctx.lineWidth = 4;
    ctx.strokeRect(60, y, 700, 75);

    ctx.font = 'bold 32px monospace';
    ctx.fillStyle = '#ffffff';
    ctx.fillText(`FINAL ANSWER: ${payload.finalAnswer}`, 85, y + 48);

    const boardImagePath = path.join(targetDir, 'chalkboard_solution.png');
    fs.writeFileSync(boardImagePath, canvas.toBuffer('image/png'));

    // 2. Assemble Canonical PipelineIR
    const chunks: ContentChunk[] = [
      {
        id: 'chunk_math_0',
        order: 0,
        text: `Problem: ${payload.problemTitle}. Following deterministic proof rules, final answer is ${payload.finalAnswer}.`,
        durationMs: 4000,
        visualAsset: {
          type: 'canvas',
          sourcePathOrBuffer: boardImagePath,
          resolution: { width: cardWidth, height: cardHeight },
        },
        metadata: {
          category: payload.category,
          stepCount: payload.steps.length,
          finalAnswer: payload.finalAnswer,
        },
      },
    ];

    const ir: PipelineIR = {
      schemaVersion: '3.0.0',
      pipelineId: 'rule-logic',
      metadata: {
        jobId: `math_${Date.now()}`,
        title: payload.problemTitle,
        createdAt: new Date().toISOString(),
        tags: [payload.category, 'proof', 'deterministic-logic'],
        author: 'Rule & Math Logic Pipeline',
      },
      chunks,
      audioComposition: {
        sfxMarkers: [],
        ducking: { enabled: false, attenuationDb: 0, attackMs: 0, releaseMs: 0 },
      },
      structuredData: {
        problemStatement: payload.problemStatement,
        steps: payload.steps,
        finalAnswer: payload.finalAnswer,
      },
      distributionHints: {
        supportedExporters: ['video', 'social', 'static-web'],
        targetAspectRatios: ['16:9'],
      },
    };

    // 3. Dispatch to Exporters
    const exportResults = await this.dispatcher.exportAll(ir, {
      outputDir: targetDir,
      targetAspectRatio: '16:9',
    });

    return { ir, exportResults };
  }
}
