import path from 'path';
import fs from 'fs';
import { createCanvas } from '@napi-rs/canvas';
import type { PipelineIR, ContentChunk } from '@acc/ir';
import { defaultExporterDispatcher, ExporterDispatcher, MultiExportResults } from '@acc/exporters';

export interface AmbientLoopConfig {
  title: string;
  theme: 'deep_space' | 'cyberpunk_rain' | 'lofi_study' | 'zen_garden';
  loopDurationSeconds?: number;
  particleCount?: number;
  bpm?: number;
}

export class AmbientStreamPipeline {
  private dispatcher: ExporterDispatcher;

  constructor(dispatcher?: ExporterDispatcher) {
    this.dispatcher = dispatcher || defaultExporterDispatcher;
  }

  public async run(config: AmbientLoopConfig, outDir?: string): Promise<{ ir: PipelineIR; exportResults: MultiExportResults }> {
    const targetDir = outDir || path.resolve(process.cwd(), 'autogenerated', 'ambient-stream', Date.now().toString());
    if (!fs.existsSync(targetDir)) {
      fs.mkdirSync(targetDir, { recursive: true });
    }

    const durationSec = config.loopDurationSeconds || 5;
    const width = 1920;
    const height = 1080;
    const canvas = createCanvas(width, height);
    const ctx = canvas.getContext('2d');

    // 1. Procedural Ambient Shader Canvas Rendering
    const bgGrad = ctx.createRadialGradient(width / 2, height / 2, 50, width / 2, height / 2, width * 0.7);
    if (config.theme === 'cyberpunk_rain') {
      bgGrad.addColorStop(0, '#1a0026');
      bgGrad.addColorStop(1, '#05000a');
    } else if (config.theme === 'lofi_study') {
      bgGrad.addColorStop(0, '#2d1b0e');
      bgGrad.addColorStop(1, '#0c0704');
    } else {
      // deep_space default
      bgGrad.addColorStop(0, '#061325');
      bgGrad.addColorStop(1, '#01040a');
    }
    ctx.fillStyle = bgGrad;
    ctx.fillRect(0, 0, width, height);

    // Generative procedural particles (Starfield / Dust)
    const particleCount = config.particleCount || 100;
    for (let i = 0; i < particleCount; i++) {
      const px = ((Math.sin(i * 12.9898) * 43758.5453) % 1) * width;
      const py = ((Math.cos(i * 78.233) * 43758.5453) % 1) * height;
      const radius = 1 + (i % 4);
      const alpha = 0.2 + ((i % 10) * 0.08);

      ctx.fillStyle = `rgba(255, 255, 255, ${alpha})`;
      ctx.beginPath();
      ctx.arc(Math.abs(px), Math.abs(py), radius, 0, Math.PI * 2);
      ctx.fill();
    }

    // Subtle atmospheric aura
    ctx.font = '300 28px sans-serif';
    ctx.fillStyle = 'rgba(255, 255, 255, 0.4)';
    ctx.textAlign = 'center';
    ctx.fillText(`AMBIENT LOOP • ${config.theme.toUpperCase()} • 24/7 STREAM READY`, width / 2, height - 80);
    ctx.textAlign = 'left';

    const loopFramePath = path.join(targetDir, 'ambient_loop_frame.png');
    fs.writeFileSync(loopFramePath, canvas.toBuffer('image/png'));

    // 2. Assemble Canonical PipelineIR
    const chunks: ContentChunk[] = [
      {
        id: 'ambient_chunk_0',
        order: 0,
        text: `Continuous procedural ${config.theme} ambient stream loop.`,
        durationMs: durationSec * 1000,
        visualAsset: {
          type: 'canvas',
          sourcePathOrBuffer: loopFramePath,
          resolution: { width, height },
        },
        metadata: {
          theme: config.theme,
          loopDurationSeconds: durationSec,
        },
      },
    ];

    const ir: PipelineIR = {
      schemaVersion: '3.0.0',
      pipelineId: 'ambient-loops',
      metadata: {
        jobId: `amb_${Date.now()}`,
        title: config.title,
        createdAt: new Date().toISOString(),
        tags: [config.theme, 'ambient', 'procedural-loop'],
        author: 'Ambient Stream Pipeline',
      },
      chunks,
      audioComposition: {
        sfxMarkers: [],
        ducking: { enabled: false, attenuationDb: 0, attackMs: 0, releaseMs: 0 },
      },
      structuredData: {
        theme: config.theme,
        particleCount,
        loopDurationSeconds: durationSec,
      },
      distributionHints: {
        supportedExporters: ['video', 'audio', 'live-stream'],
        targetAspectRatios: ['16:9'],
      },
    };

    // 3. Dispatch to Exporters
    const exportResults = await this.dispatcher.exportAll(ir, {
      outputDir: targetDir,
      targetAspectRatio: '16:9',
    });

    return { ir, exportResults };
  }

  public renderProceduralFrame(config: Partial<AmbientLoopConfig>, frameIndex: number, fps: number = 30): Buffer {
    const width = 1920;
    const height = 1080;
    const canvas = createCanvas(width, height);
    const ctx = canvas.getContext('2d');

    const bgGrad = ctx.createRadialGradient(width / 2, height / 2, 50, width / 2, height / 2, width * 0.7);
    const theme = config.theme || 'deep_space';
    if (theme === 'cyberpunk_rain') {
      bgGrad.addColorStop(0, '#1a0026');
      bgGrad.addColorStop(1, '#05000a');
    } else if (theme === 'lofi_study') {
      bgGrad.addColorStop(0, '#2d1b0e');
      bgGrad.addColorStop(1, '#0c0704');
    } else {
      bgGrad.addColorStop(0, '#061325');
      bgGrad.addColorStop(1, '#01040a');
    }
    ctx.fillStyle = bgGrad;
    ctx.fillRect(0, 0, width, height);

    const particleCount = config.particleCount || 100;
    const t = frameIndex / fps;
    for (let i = 0; i < particleCount; i++) {
      const speed = 0.5 + (i % 5) * 0.2;
      const px = (((Math.sin(i * 12.9898) * 43758.5453) % 1) * width + t * 20 * speed) % width;
      const py = (((Math.cos(i * 78.233) * 43758.5453) % 1) * height + Math.sin(t + i) * 10) % height;
      const radius = 1 + (i % 4);
      const alpha = 0.2 + ((i % 10) * 0.08);

      ctx.fillStyle = `rgba(255, 255, 255, ${alpha})`;
      ctx.beginPath();
      ctx.arc(Math.abs(px), Math.abs(py), radius, 0, Math.PI * 2);
      ctx.fill();
    }

    ctx.font = '300 28px sans-serif';
    ctx.fillStyle = 'rgba(255, 255, 255, 0.4)';
    ctx.textAlign = 'center';
    ctx.fillText(`AMBIENT LOOP • ${theme.toUpperCase()} • LIVE STREAM`, width / 2, height - 80);

    const imgData = ctx.getImageData(0, 0, width, height);
    return Buffer.from(imgData.data.buffer);
  }

  public async streamToRtmp(rtmpUrl: string, config?: Partial<AmbientLoopConfig>, maxFrames: number = 300): Promise<{ framesSent: number }> {
    const { FFIVideoEncoder } = await import('../../../../../packages/core/src/ffmpeg-ffi/FFIVideoEncoder');
    const width = 1920;
    const height = 1080;
    const fps = 30;
    const encoder = new FFIVideoEncoder(width, height, fps, rtmpUrl);
    encoder.initialize();

    let sent = 0;
    for (let f = 0; f < maxFrames; f++) {
      const frameRgba = this.renderProceduralFrame(config || {}, f, fps);
      encoder.encodeRgbaFrame(frameRgba);
      sent++;
    }
    encoder.close();
    return { framesSent: sent };
  }
}

