import path from 'path';
import fs from 'fs';
import { createCanvas } from '@napi-rs/canvas';
import type { PipelineIR } from '@acc/ir';
import { defaultExporterDispatcher, ExporterDispatcher, MultiExportResults } from '@acc/exporters';
import {
  IPipeline,
  PipelineExecutionOptions,
  PipelineRunner,
  UnifiedPipelineContext,
  createUnifiedPipelineContext,
  createExporterDispatcherMiddleware,
  DefaultPipelineRegistry,
} from '@acc/core';
import { createAmbientParticleShaderCompositionStage } from './stages/AmbientParticleShaderCompositionStage';

export interface AmbientLoopConfig {
  title: string;
  theme: 'deep_space' | 'cyberpunk_rain' | 'lofi_study' | 'zen_garden' | string;
  loopDurationSeconds?: number;
  particleCount?: number;
  bpm?: number;
}

export interface AmbientStreamPipelineContext extends UnifiedPipelineContext<AmbientLoopConfig> {
  loopFramePath?: string;
  durationSec?: number;
}

export class AmbientStreamPipeline implements IPipeline<AmbientLoopConfig> {
  public readonly id = 'ambient' as const;
  public readonly name = '24/7 Procedural Ambient Stream Engine';
  public readonly description = 'Generates infinite seamless procedural canvas loops, particle shaders, and outputs multi-modal assets or real-time RTMP stream chunks.';

  private dispatcher: ExporterDispatcher;

  constructor(dispatcher?: ExporterDispatcher) {
    this.dispatcher = dispatcher || defaultExporterDispatcher;
  }

  public buildRunner(): PipelineRunner<UnifiedPipelineContext<AmbientLoopConfig>> {
    const runner = new PipelineRunner<UnifiedPipelineContext<AmbientLoopConfig>>();

    // Stage 1: Procedural Particle Shader Canvas Rendering & PipelineIR Assembly
    runner.use(createAmbientParticleShaderCompositionStage());

    // Stage 2: Exporter Dispatcher
    runner.use(createExporterDispatcherMiddleware({ dispatcher: this.dispatcher, targetAspectRatio: '16:9' }));

    return runner;
  }

  public async execute(
    config: AmbientLoopConfig,
    options: PipelineExecutionOptions = {}
  ): Promise<UnifiedPipelineContext<AmbientLoopConfig>> {
    const targetDir = options.outDir || path.resolve(process.cwd(), 'autogenerated', 'ambient-stream', Date.now().toString());
    if (!fs.existsSync(targetDir)) {
      fs.mkdirSync(targetDir, { recursive: true });
    }

    const ctx = createUnifiedPipelineContext<AmbientLoopConfig>({
      pipelineId: this.id,
      input: config,
      outDir: targetDir,
      dryRun: options.dryRun,
    });

    const runner = this.buildRunner();
    return await runner.run(ctx);
  }

  public async run(
    config: AmbientLoopConfig,
    outDir?: string
  ): Promise<{ ir: PipelineIR; exportResults: MultiExportResults }> {
    const ctx = await this.execute(config, { outDir });
    return {
      ir: ctx.ir as PipelineIR,
      exportResults: ctx.exportResults!,
    };
  }

  public renderProceduralFrame(config: Partial<AmbientLoopConfig>, frameIndex: number, fps: number = 30): Buffer {
    const width = 1920;
    const height = 1080;
    const canvas = createCanvas(width, height);
    const ctx = canvas.getContext('2d');

    const bgGrad = ctx.createRadialGradient(width / 2, height / 2, 50, width / 2, height / 2, width * 0.7);
    const theme = config.theme || 'deep_space';
    if (theme === 'cyberpunk_rain') {
      bgGrad.addColorStop(0, '#1a0026');
      bgGrad.addColorStop(1, '#05000a');
    } else if (theme === 'lofi_study') {
      bgGrad.addColorStop(0, '#2d1b0e');
      bgGrad.addColorStop(1, '#0c0704');
    } else {
      bgGrad.addColorStop(0, '#061325');
      bgGrad.addColorStop(1, '#01040a');
    }
    ctx.fillStyle = bgGrad;
    ctx.fillRect(0, 0, width, height);

    const particleCount = config.particleCount || 100;
    const t = frameIndex / fps;
    for (let i = 0; i < particleCount; i++) {
      const speed = 0.5 + (i % 5) * 0.2;
      const px = (((Math.sin(i * 12.9898) * 43758.5453) % 1) * width + t * 20 * speed) % width;
      const py = (((Math.cos(i * 78.233) * 43758.5453) % 1) * height + Math.sin(t + i) * 10) % height;
      const radius = 1 + (i % 4);
      const alpha = 0.2 + ((i % 10) * 0.08);

      ctx.fillStyle = `rgba(255, 255, 255, ${alpha})`;
      ctx.beginPath();
      ctx.arc(Math.abs(px), Math.abs(py), radius, 0, Math.PI * 2);
      ctx.fill();
    }

    ctx.font = '300 28px sans-serif';
    ctx.fillStyle = 'rgba(255, 255, 255, 0.4)';
    ctx.textAlign = 'center';
    ctx.fillText(`AMBIENT LOOP • ${theme.toUpperCase()} • LIVE STREAM`, width / 2, height - 80);

    const imgData = ctx.getImageData(0, 0, width, height);
    return Buffer.from(imgData.data.buffer);
  }

  public async streamToRtmp(
    rtmpUrl: string,
    config?: Partial<AmbientLoopConfig>,
    maxFrames: number = 300
  ): Promise<{ framesSent: number }> {
    const { FFIVideoEncoder } = await import('@acc/core');
    const width = 1920;
    const height = 1080;
    const fps = 30;
    const encoder = new FFIVideoEncoder(width, height, fps, rtmpUrl);
    encoder.initialize();

    let sent = 0;
    for (let f = 0; f < maxFrames; f++) {
      const frameRgba = this.renderProceduralFrame(config || {}, f, fps);
      encoder.encodeRgbaFrame(frameRgba);
      sent++;
    }
    encoder.close();
    return { framesSent: sent };
  }
}

// Auto-register in central registry
DefaultPipelineRegistry.register(new AmbientStreamPipeline(), ['6', 'ambient', 'ambient-stream', 'loop']);
