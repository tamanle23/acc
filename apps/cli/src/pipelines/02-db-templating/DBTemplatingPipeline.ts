import path from 'path';
import fs from 'fs';
import { createCanvas } from '@napi-rs/canvas';
import type { PipelineIR, ContentChunk } from '@acc/ir';
import { defaultExporterDispatcher, ExporterDispatcher, MultiExportResults } from '@acc/exporters';

export interface ComparisonEntity {
  id: string;
  name: string;
  category: string;
  metrics: Record<string, number>;
  highlightMetric: string;
  badge?: string;
}

export interface DBTemplatePayload {
  title: string;
  category: string;
  entities: ComparisonEntity[];
  summaryConclusion?: string;
}

export class DBTemplatingPipeline {
  private dispatcher: ExporterDispatcher;

  constructor(dispatcher?: ExporterDispatcher) {
    this.dispatcher = dispatcher || defaultExporterDispatcher;
  }

  public async run(payload: DBTemplatePayload, outDir?: string): Promise<{ ir: PipelineIR; exportResults: MultiExportResults }> {
    const targetDir = outDir || path.resolve(process.cwd(), 'autogenerated', 'db-templating', Date.now().toString());
    if (!fs.existsSync(targetDir)) {
      fs.mkdirSync(targetDir, { recursive: true });
    }

    // 1. Sort entities by the highlight metric descending
    const sorted = [...payload.entities].sort((a, b) => {
      const valA = a.metrics[a.highlightMetric] ?? 0;
      const valB = b.metrics[b.highlightMetric] ?? 0;
      return valB - valA;
    });

    const maxVal = Math.max(...sorted.map(e => e.metrics[e.highlightMetric] ?? 0), 1);

    // 2. Render Bar Chart Racing / Comparative Metric Slide (1080x1920)
    const cardWidth = 1080;
    const cardHeight = 1920;
    const canvas = createCanvas(cardWidth, cardHeight);
    const ctx = canvas.getContext('2d');

    // Background: High-tech dark gradient
    const bgGrad = ctx.createLinearGradient(0, 0, 0, cardHeight);
    bgGrad.addColorStop(0, '#0c101d');
    bgGrad.addColorStop(1, '#05070f');
    ctx.fillStyle = bgGrad;
    ctx.fillRect(0, 0, cardWidth, cardHeight);

    // Header Tag
    ctx.fillStyle = '#10b981';
    ctx.fillRect(80, 140, 280, 48);
    ctx.fillStyle = '#ffffff';
    ctx.font = 'bold 22px sans-serif';
    ctx.fillText(`DATABASE INSIGHTS`, 105, 172);

    // Category
    ctx.font = '22px sans-serif';
    ctx.fillStyle = 'rgba(255, 255, 255, 0.6)';
    ctx.fillText(`${payload.category.toUpperCase()} BENCHMARK`, 380, 172);

    // Main Title
    ctx.fillStyle = '#ffffff';
    ctx.font = 'bold 56px sans-serif';
    ctx.fillText(payload.title.slice(0, 35), 80, 280);

    // Subtitle / Highlight Metric
    ctx.font = '30px sans-serif';
    ctx.fillStyle = '#94a3b8';
    ctx.fillText(`Ranking sorted by: ${payload.highlightMetric.toUpperCase()}`, 80, 340);

    // Animated Bar Chart Representation
    let y = 440;
    const barColors = ['#38bdf8', '#818cf8', '#34d399', '#f472b6', '#fbbf24', '#a78bfa'];

    sorted.slice(0, 6).forEach((entity, idx) => {
      const val = entity.metrics[entity.highlightMetric] ?? 0;
      const pct = val / maxVal;
      const barWidth = Math.max(40, (cardWidth - 280) * pct);
      const color = barColors[idx % barColors.length];

      // Entity Rank & Name
      ctx.font = 'bold 30px sans-serif';
      ctx.fillStyle = '#ffffff';
      ctx.fillText(`#${idx + 1}  ${entity.name}`, 80, y);

      // Value label
      ctx.font = 'bold 28px sans-serif';
      ctx.fillStyle = color;
      ctx.textAlign = 'right';
      ctx.fillText(`${val.toLocaleString()}`, cardWidth - 80, y);
      ctx.textAlign = 'left';

      y += 24;

      // Bar Background
      ctx.fillStyle = 'rgba(255, 255, 255, 0.08)';
      ctx.fillRect(80, y, cardWidth - 160, 36);

      // Bar Fill
      ctx.fillStyle = color;
      ctx.fillRect(80, y, barWidth, 36);

      y += 75;
    });

    // Conclusion banner
    if (payload.summaryConclusion) {
      y += 60;
      ctx.fillStyle = 'rgba(255, 255, 255, 0.05)';
      ctx.fillRect(80, y, cardWidth - 160, 120);
      ctx.strokeStyle = 'rgba(16, 185, 129, 0.4)';
      ctx.strokeRect(80, y, cardWidth - 160, 120);

      ctx.font = 'italic 26px sans-serif';
      ctx.fillStyle = '#e2e8f0';
      ctx.fillText(payload.summaryConclusion.slice(0, 70), 105, y + 68);
    }

    // Footer
    ctx.font = '22px sans-serif';
    ctx.fillStyle = 'rgba(255, 255, 255, 0.4)';
    ctx.fillText('📊 Generated by Visual Storytelling Engine • Data-to-Video Pipeline', 80, cardHeight - 100);

    const chartCardPath = path.join(targetDir, 'comparison_chart.png');
    fs.writeFileSync(chartCardPath, canvas.toBuffer('image/png'));

    // 3. Assemble Canonical PipelineIR
    const chunks: ContentChunk[] = [
      {
        id: 'chunk_0',
        order: 0,
        text: `${payload.title}. Top rank belongs to ${sorted[0]?.name || 'Leader'} with ${sorted[0]?.metrics[payload.highlightMetric] || 0} ${payload.highlightMetric}.`,
        durationMs: 4000,
        visualAsset: {
          type: 'canvas',
          sourcePathOrBuffer: chartCardPath,
          resolution: { width: cardWidth, height: cardHeight },
        },
        metadata: {
          highlightMetric: payload.highlightMetric,
          topLeader: sorted[0]?.name,
        },
      },
    ];

    const ir: PipelineIR = {
      schemaVersion: '3.0.0',
      pipelineId: 'db-templating',
      metadata: {
        jobId: `dbt_${Date.now()}`,
        title: payload.title,
        createdAt: new Date().toISOString(),
        tags: [payload.category, 'benchmark', 'ranking'],
        author: 'DB Templating Pipeline',
      },
      chunks,
      audioComposition: {
        sfxMarkers: [],
        ducking: { enabled: false, attenuationDb: 0, attackMs: 0, releaseMs: 0 },
      },
      structuredData: {
        category: payload.category,
        highlightMetric: payload.highlightMetric,
        entities: sorted,
      },
      distributionHints: {
        supportedExporters: ['video', 'social', 'static-web'],
        targetAspectRatios: ['9:16', '16:9'],
      },
    };

    // 4. Dispatch to exporters
    const exportResults = await this.dispatcher.exportAll(ir, {
      outputDir: targetDir,
      targetAspectRatio: '9:16',
    });

    return { ir, exportResults };
  }
}
