import path from 'path';
import fs from 'fs';
import { createCanvas } from '@napi-rs/canvas';
import type { PipelineIR, ContentChunk } from '@acc/ir';
import { defaultExporterDispatcher, ExporterDispatcher, MultiExportResults } from '@acc/exporters';

export interface RepurposingWord {
  word: string;
  startMs: number;
  endMs: number;
}

export interface RepurposingInput {
  title: string;
  rawTranscript: string;
  wordTimestamps?: RepurposingWord[];
  sourceMediaUrl?: string;
  activeSpeakerPosition?: { x: number; y: number }; // normalized 0..1 coordinates
}

export class RepurposingPipeline {
  private dispatcher: ExporterDispatcher;

  constructor(dispatcher?: ExporterDispatcher) {
    this.dispatcher = dispatcher || defaultExporterDispatcher;
  }

  public async run(input: RepurposingInput, outDir?: string): Promise<{ ir: PipelineIR; exportResults: MultiExportResults }> {
    const targetDir = outDir || path.resolve(process.cwd(), 'autogenerated', 'repurposing', Date.now().toString());
    if (!fs.existsSync(targetDir)) {
      fs.mkdirSync(targetDir, { recursive: true });
    }

    // 1. Extract Viral Hook Highlights
    const sentences = input.rawTranscript
      .split(/[.!?]+/)
      .map(s => s.trim())
      .filter(s => s.length > 20);

    const hookSentences = sentences.slice(0, 3);
    const viralHookText = hookSentences.join('. ') + '.';

    // 2. Render Vertical 9:16 Active Speaker / Karaoke Subtitle Frame
    const cardWidth = 1080;
    const cardHeight = 1920;
    const canvas = createCanvas(cardWidth, cardHeight);
    const ctx = canvas.getContext('2d');

    // Background: Dark studio gradient with active speaker highlight
    const bgGrad = ctx.createLinearGradient(0, 0, 0, cardHeight);
    bgGrad.addColorStop(0, '#13111c');
    bgGrad.addColorStop(1, '#090810');
    ctx.fillStyle = bgGrad;
    ctx.fillRect(0, 0, cardWidth, cardHeight);

    // Dynamic Active Speaker Crop Frame (Simulated 9:16 face-track box)
    const speakerX = (input.activeSpeakerPosition?.x ?? 0.5) * cardWidth;
    const speakerY = (input.activeSpeakerPosition?.y ?? 0.35) * cardHeight;

    ctx.save();
    ctx.strokeStyle = 'rgba(168, 85, 247, 0.4)';
    ctx.lineWidth = 4;
    ctx.beginPath();
    ctx.arc(speakerX, speakerY, 260, 0, Math.PI * 2);
    ctx.stroke();

    // Subtle face-light radial glow
    const faceGlow = ctx.createRadialGradient(speakerX, speakerY, 50, speakerX, speakerY, 260);
    faceGlow.addColorStop(0, 'rgba(168, 85, 247, 0.18)');
    faceGlow.addColorStop(1, 'rgba(0, 0, 0, 0)');
    ctx.fillStyle = faceGlow;
    ctx.fill();
    ctx.restore();

    // Header badge
    ctx.fillStyle = '#a855f7';
    ctx.fillRect(80, 140, 240, 44);
    ctx.fillStyle = '#ffffff';
    ctx.font = 'bold 22px sans-serif';
    ctx.fillText('REPURPOSED CLIP', 105, 170);

    // Title
    ctx.fillStyle = '#ffffff';
    ctx.font = 'bold 50px sans-serif';
    ctx.fillText(input.title.slice(0, 35), 80, 260);

    // Karaoke Subtitle Placement (Lower Thirds)
    const subY = cardHeight * 0.72;
    ctx.fillStyle = 'rgba(0, 0, 0, 0.65)';
    ctx.fillRect(60, subY - 40, cardWidth - 120, 260);

    ctx.font = 'bold 44px sans-serif';
    ctx.fillStyle = '#facc15'; // Karaoke highlight color
    ctx.textAlign = 'center';
    
    // Wrapped subtitle words
    const hookWords = viralHookText.split(' ');
    let currentLine = '';
    let lineY = subY + 30;
    for (const w of hookWords.slice(0, 25)) {
      const testLine = currentLine + w + ' ';
      if (ctx.measureText(testLine).width > cardWidth - 180) {
        ctx.fillText(currentLine, cardWidth / 2, lineY);
        currentLine = w + ' ';
        lineY += 60;
      } else {
        currentLine = testLine;
      }
    }
    ctx.fillText(currentLine, cardWidth / 2, lineY);
    ctx.textAlign = 'left';

    const framePath = path.join(targetDir, 'repurposed_frame.png');
    fs.writeFileSync(framePath, canvas.toBuffer('image/png'));

    // 3. Assemble Canonical PipelineIR
    const chunks: ContentChunk[] = [
      {
        id: 'chunk_hook_0',
        order: 0,
        text: viralHookText,
        durationMs: 4500,
        visualAsset: {
          type: 'canvas',
          sourcePathOrBuffer: framePath,
          resolution: { width: cardWidth, height: cardHeight },
        },
        metadata: {
          hookType: 'high_engagement_highlight',
          originalSource: input.sourceMediaUrl,
        },
      },
    ];

    const ir: PipelineIR = {
      schemaVersion: '3.0.0',
      pipelineId: 'repurposing-recycler',
      metadata: {
        jobId: `rep_${Date.now()}`,
        title: input.title,
        createdAt: new Date().toISOString(),
        tags: ['repurposed', 'shorts', 'karaoke-clip'],
        author: 'Repurposing Pipeline',
      },
      chunks,
      audioComposition: {
        sfxMarkers: [],
        ducking: { enabled: false, attenuationDb: 0, attackMs: 0, releaseMs: 0 },
      },
      structuredData: {
        originalTranscript: input.rawTranscript,
        viralHook: viralHookText,
      },
      distributionHints: {
        supportedExporters: ['video', 'social'],
        targetAspectRatios: ['9:16'],
      },
    };

    // 4. Dispatch to exporters
    const exportResults = await this.dispatcher.exportAll(ir, {
      outputDir: targetDir,
      targetAspectRatio: '9:16',
    });

    return { ir, exportResults };
  }
}
