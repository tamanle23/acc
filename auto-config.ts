const isAutoYes = process.argv.includes('--yes') || process.argv.includes('-y');

async function promptText(message: string, placeholder = '', defaultValue = ''): Promise<string> {
  if (isAutoYes) {
    return defaultValue;
  }
  const res = await prompt.text({
    message,
    placeholder,
    defaultValue,
  });
  if (isCancel(res)) {
    cancel('Operation cancelled.');
    process.exit(0);
  }
  return (res as string).trim();
}

async function promptSelect<T extends string>(message: string, options: Option<T>[]): Promise<T> {
  if (isAutoYes) {
    return options[0].value as T;
  }
  const res = await prompt.select({
    message,
    options,
  });
  if (isCancel(res)) {
    cancel('Operation cancelled.');
    process.exit(0);
  }
  return res as T;
}

async function promptConfirm(message: string, initialValue = true): Promise<boolean> {
  if (isAutoYes) {
    return initialValue;
  }
  const res = await prompt.confirm({
    message,
    initialValue,
  });
  if (isCancel(res)) {
    cancel('Operation cancelled.');
    process.exit(0);
  }
  return Boolean(res);
}

const IMAGE_EXTENSIONS = new Set(['.jpg', '.jpeg', '.png', '.webp']);
const VIDEO_EXTENSIONS = new Set(['.mp4', '.mov', '.webm', '.mkv']);
const AUDIO_EXTENSIONS = new Set(['.mp3', '.wav', '.ogg', '.m4a', '.flac']);

function naturalSort(a: string, b: string): number {
  return a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' });
}

function getBaseNameWithoutExt(filename: string): string {
  return path.parse(filename).name.toLowerCase();
}

/**
 * Thu thập tất cả các file ảnh/video và âm thanh trong thư mục gốc và các thư mục con
 */
function collectMediaFiles(baseDir: string): { visualFiles: string[]; audioFiles: string[] } {
  const visualFiles: string[] = [];
  const audioFiles: string[] = [];

  function scanDirectory(dir: string, isRoot = false) {
    if (!fs.existsSync(dir)) return;
    try {
      const entries = fs.readdirSync(dir, { withFileTypes: true });

      for (const entry of entries) {
        if (['node_modules', '.git', 'output', 'dist', '.turbo', '.venv'].includes(entry.name)) {
          continue;
        }
        const fullPath = path.join(dir, entry.name);
        const relPath = path.relative(baseDir, fullPath).replace(/\\/g, '/');

        if (entry.isFile()) {
          const ext = path.extname(entry.name).toLowerCase();
          if (IMAGE_EXTENSIONS.has(ext) || VIDEO_EXTENSIONS.has(ext)) {
            visualFiles.push(relPath);
          } else if (AUDIO_EXTENSIONS.has(ext)) {
            audioFiles.push(relPath);
          }
        } else if (entry.isDirectory() && (isRoot || ['assets', 'images', 'audio', 'voiceovers', 'autogenerated'].includes(entry.name))) {
          scanDirectory(fullPath, false);
        }
      }
    } catch { }
  }

  scanDirectory(baseDir, true);
  return {
    visualFiles: visualFiles.sort(naturalSort),
    audioFiles: audioFiles.sort(naturalSort),
  };
}

/**
 * Ghép cặp ảnh/video và audio thông minh
 */
function pairVisualsAndAudios(
  visualFiles: string[],
  audioFiles: string[]
): { visual: string; audio: string }[] {
  const pairs: { visual: string; audio: string }[] = [];
  const usedVisuals = new Set<string>();
  const unmappedAudios: string[] = [];

  const visualBaseMap = new Map<string, string>();
  for (const vis of visualFiles) {
    visualBaseMap.set(getBaseNameWithoutExt(vis), vis);
  }

  for (const audio of audioFiles) {
    const audioBase = getBaseNameWithoutExt(audio);
    if (visualBaseMap.has(audioBase)) {
      const matchedVisual = visualBaseMap.get(audioBase)!;
      pairs.push({ visual: matchedVisual, audio });
      usedVisuals.add(matchedVisual);
    } else {
      unmappedAudios.push(audio);
    }
  }

  const remainingVisuals = visualFiles.filter((vis) => !usedVisuals.has(vis));

  for (let i = 0; i < unmappedAudios.length; i++) {
    const audio = unmappedAudios[i];
    const visual = remainingVisuals[i] || visualFiles[i % visualFiles.length] || 'scene.jpg';
    pairs.push({ visual, audio });
  }

  return pairs;
}

interface ReferenceScriptCache {
  globalLines?: string[];
  globalJson?: string[];
}

/**
 * Tự động tìm và nạp kịch bản toàn cục nếu có (script.txt, story.txt, transcript.txt, script.json...)
 */
function loadGlobalScripts(baseDir: string): ReferenceScriptCache {
  const cache: ReferenceScriptCache = {};

  // 1. Kiểm tra JSON files
  const jsonNames = [
    'script.json',
    'story.json',
    'transcript.json',
    'scripts.json',
    'kịch_bản.json',
    'kich_ban.json',
  ];
  for (const name of jsonNames) {
    const p = path.join(baseDir, name);
    if (fs.existsSync(p)) {
      try {
        const data = JSON.parse(fs.readFileSync(p, 'utf-8'));
        if (Array.isArray(data)) {
          cache.globalJson = data
            .map((item) => {
              if (typeof item === 'string') return item.trim();
              if (typeof item === 'object' && item !== null) {
                return (
                  item.text ||
                  item.script ||
                  item.content ||
                  item.caption ||
                  item.voiceover ||
                  ''
                ).trim();
              }
              return '';
            })
            .filter((s) => s.length > 0);
          break;
        }
      } catch { }
    }
  }

  // 2. Kiểm tra TXT files (mỗi dòng hoặc mỗi đoạn ứng với 1 slide)
  const txtNames = [
    'script.txt',
    'story.txt',
    'transcript.txt',
    'scripts.txt',
    'kịch_bản.txt',
    'kich_ban.txt',
    'noidung.txt',
    'noi_dung.txt',
  ];
  for (const name of txtNames) {
    const p = path.join(baseDir, name);
    if (fs.existsSync(p)) {
      try {
        const content = fs.readFileSync(p, 'utf-8');
        const lines = content
          .split(/\r?\n/)
          .map((l) => l.trim())
          .filter((l) => l.length > 0 && !l.startsWith('#'));
        if (lines.length > 0) {
          cache.globalLines = lines;
          break;
        }
      } catch { }
    }
  }

  return cache;
}

/**
 * Tìm văn bản kịch bản gốc tương ứng cho từng slide:
 * 1. File .txt / .script cùng thư mục với audio (VD: voiceover/01.txt, voiceover/01.mp3.txt)
 * 2. File .txt ở thư mục gốc có cùng tên audio hoặc ảnh (VD: 01.txt, voiceover1.txt, scene1.txt)
 * 3. File .txt theo số thứ tự slide (VD: 1.txt, slide1.txt, scene1.txt)
 * 4. Dòng/mục tương ứng trong file script.json hoặc script.txt toàn cục
 */
function findReferenceScript(
  audioName: string,
  imageName: string,
  slideIndex: number,
  baseDir: string,
  cache: ReferenceScriptCache
): { scriptText: string; source: string } | null {

  const audioBase = path.parse(audioName).name;
  const imageBase = path.parse(imageName).name;
  const baseName = audioBase || imageBase;
  const audioDir = !!audioName ? path.dirname(path.isAbsolute(audioName) ? audioName : path.join(baseDir, audioName))
    : path.join(baseDir, 'assets');

  // Danh sách các ứng viên file script riêng lẻ
  const candidates = [
    // Cùng thư mục với file audio
    path.join(audioDir, `${baseName}.txt`),
    path.join(audioDir, `${path.basename(baseName)}.txt`),
    path.join(audioDir, `${baseName}.script`),
    path.join(audioDir, `voiceover${baseName}.txt`),
  ];

  for (const candidate of candidates) {
    if (fs.existsSync(candidate)) {
      try {
        const text = fs.readFileSync(candidate, 'utf-8').trim();
        if (text.length > 0) {
          return { scriptText: text, source: candidate };
        }
      } catch { }
    }
  }

  // File JSON toàn cục
  if (cache.globalJson && cache.globalJson[slideIndex]) {
    return {
      scriptText: cache.globalJson[slideIndex],
      source: `script.json [mục ${slideIndex + 1}]`,
    };
  }

  // File TXT toàn cục (theo thứ tự dòng)
  if (cache.globalLines && cache.globalLines[slideIndex]) {
    return {
      scriptText: cache.globalLines[slideIndex],
      source: `script.txt [dòng ${slideIndex + 1}]`,
    };
  }

  return null;
}

